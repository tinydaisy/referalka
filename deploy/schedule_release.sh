#!/bin/bash
# ═══════════════════════════════════════════════════════════════════════════
# ПЛЮСОН — отложенный накат: нажали днём, выкатится ночью
#
# Зачем. Днём в кабинете люди, идут эфиры и рассылки. Даже секундный рестарт
# бота может прийтись ровно на чей-то клик. Ночью этого нет.
#
# ⚠️ GitHub «подождать до 04:00» не может — машину на 12 часов он не даст.
# Поэтому сборка кладётся НА СЕРВЕР и ждёт здесь, а переключит её системный
# таймер. Пока не наступило время, прод работает на прежней версии.
#
# Отменить: rm -f /var/www/plusson/pending/*
#
# Запуск: schedule_release.sh <архив> <коммит>
# ═══════════════════════════════════════════════════════════════════════════
set -euo pipefail

ARCHIVE="${1:?укажите путь к build.tar.gz}"
SHA="${2:-manual}"

PENDING_DIR="/var/www/plusson/pending"
LOG="/var/log/plusson-deploy.log"

log() { echo "[$(date '+%Y-%m-%d %H:%M:%S')] $1" | tee -a "$LOG"; }

mkdir -p "$PENDING_DIR"

# Отложенная сборка одна: новая заменяет прежнюю, иначе ночью встал бы вопрос
# «какую из трёх катить».
rm -f "$PENDING_DIR"/build.tar.gz "$PENDING_DIR"/COMMIT
mv "$ARCHIVE" "$PENDING_DIR/build.tar.gz"
echo "$SHA" > "$PENDING_DIR/COMMIT"

log "Отложенный накат поставлен: ${SHA:0:8}, выкатится в 04:00 МСК"
echo "Сборка ${SHA:0:8} будет выкачена в 04:00 МСК."
echo "Отменить: ssh на сервер и rm -f $PENDING_DIR/*"
