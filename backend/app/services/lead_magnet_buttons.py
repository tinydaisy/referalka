"""Кнопки выдачи материалов воронки — единая точка сборки.

Материал можно отдать ссылкой в тексте, кнопкой под сообщением или и так, и
так (`lead_magnets.link_mode`). Здесь собирается надпись на кнопке и список
кнопок для отправки; сами платформенные клавиатуры строятся уже в ботах.

⚠️ Правило одно на все три площадки. Раньше похожая логика расползлась бы по
TG/VK/MAX-веткам и разъехалась: где-то номер, где-то нет, где-то обрезка на
символ длиннее. Меняем здесь — меняется везде.
"""
from typing import Any, Optional

# ⚠️ 40 — предел ВКонтакте, самой строгой из трёх площадок. Проверено живой
# отправкой на проде: 40 принимается, 41 отвергается («label should be not
# more than 40 letters»). Telegram принимает и 128, MAX не строже. Берём
# минимум, чтобы надпись доехала везде одинаковой.
BUTTON_LABEL_LIMIT = 40

# Многоточие занимает место в этом же лимите, поэтому режем с запасом на него.
_ELLIPSIS = "…"


def fit_label(text: str, limit: int = BUTTON_LABEL_LIMIT) -> str:
    """Обрезать надпись под лимит площадки, оставив место многоточию.

    Режем ПО СИМВОЛАМ (решение владельца), а не по границе слова: у названий
    материалов «слово» бывает длиной в половину надписи, и обрезка по слову
    выбрасывала бы половину текста.
    """
    s = (text or "").strip()
    if len(s) <= limit:
        return s
    # -1 на многоточие: иначе итог оказался бы на символ длиннее лимита и
    # ВКонтакте отверг бы всё сообщение целиком, а не только кнопку.
    return s[: limit - len(_ELLIPSIS)].rstrip() + _ELLIPSIS


def button_label_for(material: dict, index: Optional[int] = None) -> str:
    """Надпись кнопки для материала.

    `index` — номер в пакете (1, 2, 3…). Одиночный материал → None, номер не
    ставим: нумеровать один пункт незачем.

    Порядок: своя надпись материала → иначе его название. Номер приклеивается
    ПЕРЕД обрезкой не целиком: сначала считаем, сколько места он займёт, и
    режем остаток — иначе у длинных названий номер сам бы и обрезался.
    """
    base = (material.get("button_label") or "").strip() or (material.get("name") or "").strip()
    if index is None:
        return fit_label(base)
    prefix = f"{index}. "
    return prefix + fit_label(base, BUTTON_LABEL_LIMIT - len(prefix))


def effective_mode(material: dict, package_mode: Optional[str] = None) -> str:
    """Как в итоге отдаём этот материал.

    ⚠️ Настройка ПАКЕТА ГЛАВНЕЕ настройки материала (решение владельца):
    пакет сказал «кнопками» — кнопками уходит всё, даже то, у чего лично
    стоит «ссылкой в тексте». Иначе вышла бы каша: часть пунктов кнопками,
    часть текстом, а нумерация «1, 2, 3» разъехалась бы со списком.

    Пакет ничего не выбрал (None) — решает сам материал.
    """
    return (package_mode or material.get("link_mode") or "text")


def buttons_for_materials(materials: list[dict],
                          package_mode: Optional[str] = None) -> list[dict]:
    """Кнопки для тех материалов, что просили отдать кнопкой.

    Возвращает [{label, url}] — платформенная клавиатура строится уже в боте.

    ⚠️ Нумеруем по позиции В ПАКЕТЕ, а не по порядку среди кнопок: если из
    трёх материалов кнопкой отдаются первый и третий, человек должен увидеть
    «1.» и «3.» — так подписи совпадут со списком в тексте сообщения.
    ⚠️ Материал без ссылки пропускаем: кнопка, ведущая в никуда, хуже её
    отсутствия.
    """
    multi = len(materials) > 1
    out: list[dict] = []
    for i, m in enumerate(materials, 1):
        if effective_mode(m, package_mode) not in ("button", "both"):
            continue
        url = (m.get("url") or "").strip()
        if not url:
            continue
        out.append({
            "label": button_label_for(m, i if multi else None),
            "url": url,
        })
    return out


def show_link_in_text(material: dict, package_mode: Optional[str] = None) -> bool:
    """Показывать ли ссылку этого материала в тексте сообщения.

    Кнопкой и только кнопкой (`button`) → в тексте ссылку не дублируем,
    остаётся название с описанием. Остальные режимы — ссылку показываем.
    """
    return effective_mode(material, package_mode) != "button"
