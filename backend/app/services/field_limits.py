"""Лимиты длины полей спикера — с учётом настройки КЛИЕНТА.

Числа подобраны по реальным данным (замер 22.08.2026): медиана
позиционирования 50 символов, регалий — 465. В поля писали офферы и целые
лендинги (у одного клиента 5922 символа с кейсами и призывами), а на карточке
спикера и на лендинге место рассчитано на перечень, а не на абзац.

⚠️ Лимит регалий — НАСТРОЙКА клиента (`clients.speaker_achievements_limit`),
а не константа кода. Одно число на всех не годится: у премии регалии
номинанта — это список достижений на десяток строк, а у короткого эфира
карточка на три строки. Раньше 1100 жило константой в шести местах, и клиенту,
которому нужно иначе, поменять было нечем, кроме релиза.

⚠️ NULL в базе = умолчание платформы (ACHIEVEMENTS_LIMIT_DEFAULT). Не ставим
дефолт колонки числом: тогда поменять умолчание для всех сразу стало бы
невозможно — пришлось бы бэкфиллить каждого клиента.

⚠️ Значение обязано совпадать с тем, что показывает счётчик символов во
фронте, — поэтому фронт получает его с сервера, а не хранит свою копию.
Разъедутся — счётчик покажет одно, а сохранение откажет по другому правилу.
"""

# Позиционирование пока общее для всех — жалоб на него не было.
POSITIONING_LIMIT = 140

# Умолчание платформы для регалий: столько было константой до миграции 420.
ACHIEVEMENTS_LIMIT_DEFAULT = 1100

# Границы, в которых клиенту разрешено задавать своё число. Нижняя — чтобы
# нельзя было закрыть поле совсем (спикер не поймёт, почему не сохраняется),
# верхняя — чтобы в карточку не уехал лендинг целиком.
ACHIEVEMENTS_LIMIT_MIN = 200
ACHIEVEMENTS_LIMIT_MAX = 6000


def normalize_achievements_limit(val) -> int | None:
    """Приводит присланное клиентом число к допустимому. Пусто → NULL."""
    if val is None or val == "":
        return None
    try:
        n = int(val)
    except (TypeError, ValueError):
        return None
    return max(ACHIEVEMENTS_LIMIT_MIN, min(ACHIEVEMENTS_LIMIT_MAX, n))


async def achievements_limit(db, client_id: int | None) -> int:
    """Сколько символов разрешено в регалиях спикера у этого клиента.

    Fail-open: клиент не найден или колонки ещё нет — возвращаем умолчание.
    Сбой чтения настройки не должен мешать спикеру сохранить профиль.
    """
    if not client_id:
        return ACHIEVEMENTS_LIMIT_DEFAULT
    try:
        val = await db.fetchval(
            "SELECT speaker_achievements_limit FROM clients WHERE id = $1",
            int(client_id),
        )
    except Exception:
        return ACHIEVEMENTS_LIMIT_DEFAULT
    return int(val) if val else ACHIEVEMENTS_LIMIT_DEFAULT
