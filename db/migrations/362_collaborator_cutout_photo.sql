-- Фото человека НА ПРОЗРАЧНОМ ФОНЕ (вырезка) — миграция 362 от 2026-09-06.
--
-- Зачем отдельное поле, а не ещё одна афиша в библиотеке.
-- Вырезка — это не готовая картинка, а ЗАГОТОВКА: человек без фона, из которого
-- потом собираются афиши (сегодня руками в редакторе, дальше — автоматом).
-- В библиотеке афиш (`collaborator_posters`) лежат готовые макеты, и класть
-- вырезку туда значило бы каждый раз глазами искать её среди макетов, а сборщику
-- афиш — гадать, какая из картинок пригодна.
--
-- ⚠️ Поле ОДНО НА ЧЕЛОВЕКА (`collaborators`), а не на событие: лицо не меняется
-- от конференции к конференции. Афиши событий разные, вырезка — одна.
--
-- ⚠️ Ожидается PNG (или WebP) с альфа-каналом. JPEG прозрачность не хранит
-- в принципе: подложив его, человек получит белый прямоугольник в афише вместо
-- вырезанной фигуры. Проверка формата — на загрузке.

ALTER TABLE collaborators ADD COLUMN IF NOT EXISTS cutout_photo_url TEXT;

COMMENT ON COLUMN collaborators.cutout_photo_url IS
  'Фото на прозрачном фоне (вырезка, PNG с альфа-каналом) — заготовка для афиш';
