-- 502: Отметка об уведомлении «WhatsApp-сессия отвалилась»
--
-- Зачем. WhatsApp — единственная площадка без бота с токеном: сообщения шлёт
-- залогиненная WhatsApp Web-сессия на мосту. Человек отвязывает «Связанные
-- устройства» на телефоне — и сессия умирает молча. У клиента 1 так вышло
-- 15.07.2026: 54 рассылки подряд упали с «session not ready», а в кабинете
-- WhatsApp всё это время выглядел подключённым, потому что запись канала в БД
-- на месте. Два месяца никто не знал, что в общие чаты ничего не уходит.
--
-- Колонка = отметка «об этом слёте уже сказали». Без неё письмо уходило бы на
-- КАЖДУЮ упавшую отправку: в одной рассылке чатов несколько, и рассылок за день
-- бывает несколько — вышел бы спам вместо предупреждения. Отметка ставится при
-- первом слёте и снимается при успешной привязке, чтобы о СЛЕДУЮЩЕМ слёте
-- клиент снова узнал (логика та же, что у contact_limit_notified_kind).
ALTER TABLE clients
    ADD COLUMN IF NOT EXISTS wa_session_dead_notified_at TIMESTAMPTZ;

COMMENT ON COLUMN clients.wa_session_dead_notified_at IS
  'Когда клиенту сообщили, что WhatsApp-сессия отвалилась и рассылки в чаты не уходят. NULL = не сообщали либо WhatsApp успешно привязан заново (снимается в connect_whatsapp).';
