-- 310: Хранить сам токен купона, а не только его хеш
--
-- Зачем. Напоминания о неактивированном бонусе должны вести ПО ССЫЛКЕ —
-- иначе письмо звучит как «ищите ссылку в старом письме», а это ровно то
-- место, где человек и потерялся. Из хеша исходную строку не восстановить.
--
-- ⚠️ Почему это допустимо, в отличие от паролей. Токен даёт ровно одно
-- действие — включить БЕСПЛАТНЫЙ доступ конкретному человеку на конкретную
-- почту. Он одноразовый, живёт 90 дней и не открывает ни кабинет, ни
-- платёжные данные: пароль владелец всё равно задаёт отдельной ссылкой.
-- Хеш оставляем и продолжаем искать по нему — так поиск не зависит от
-- регистра хранения.
ALTER TABLE plusson_bonus_coupons
    ADD COLUMN IF NOT EXISTS token TEXT;

COMMENT ON COLUMN plusson_bonus_coupons.token IS
  'Сам токен ссылки — нужен, чтобы напоминания вели по рабочей ссылке. Одноразовый, ограничен по сроку, даёт только включение бесплатного доступа.';
