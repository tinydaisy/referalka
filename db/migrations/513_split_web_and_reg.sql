-- 513. Простая страница и форма регистрации — РАЗНЫЕ галочки (24.09.2026)
--
-- ЗАЧЕМ. В «Публичных ссылках» события обе строки были помечены одной
-- площадкой 'web': «Простая страница события» (витрина: афиша, описание,
-- кнопка записаться) и «Регистрация без мессенджера» (сама форма). Галочка
-- получалась ОДНА НА ДВЕ страницы — снимаешь у витрины, пропадает и форма.
-- А это разные вещи, и выключать их нужно порознь: витрину можно не
-- показывать, оставив рабочей форму записи, и наоборот.
--
-- Теперь у формы своя площадка — 'reg'.
--
-- ⚠️ ПЕРЕНОС ЗНАЧЕНИЙ ОБЯЗАТЕЛЕН, иначе разделение молча ВКЛЮЧИЛО бы форму
-- там, где её намеренно выключили: у события 89 стоит {web}, и до этой
-- миграции оно гасило обе страницы. Без переноса форма регистрации вернулась
-- бы спикерам сама собой — как «починка», которую никто не просил.
--
-- Кто выключал 'web' — выключал обе страницы, значит и 'reg' тоже.
-- Обратное неверно: 'reg' без 'web' раньше было невыразимо, и таких строк нет.

UPDATE events
   SET disabled_platforms = disabled_platforms || ARRAY['reg']::TEXT[]
 WHERE 'web' = ANY(disabled_platforms)
   AND NOT ('reg' = ANY(disabled_platforms));

-- ⚠️ Дефолт для НОВЫХ событий (миграция 511) тоже расширяем: выключены обе
-- веб-страницы и лендинг — включают их осознанно, галочкой.
ALTER TABLE events
  ALTER COLUMN disabled_platforms SET DEFAULT ARRAY['web', 'reg', 'landing']::TEXT[];

COMMENT ON COLUMN events.disabled_platforms IS
  'Площадки и страницы, ВЫКЛЮЧЕННЫЕ у события: их ссылки не отдаются спикерам и участникам (сам бот при этом работает). Значения: telegram, vk, max, web (простая страница события), reg (форма регистрации без мессенджера), landing (Плюсоновский лендинг). По умолчанию выключены веб-страницы — включены только мессенджеры.';
