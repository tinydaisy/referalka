-- 477. Режим ссылок — ТОЛЬКО по площадкам. Шаг 1: перенос значений.
--
-- ЗАЧЕМ.
-- `clients.default_link_mode` — «общий режим» — оказался полем, которого НЕТ в
-- интерфейсе: переключателя для него никогда не существовало, значение
-- проставлялось само (DEFAULT 'bot' при создании клиента). При этом часть кода
-- читала именно его, а не площадочные `link_mode_{telegram|vk|max}`, которые
-- клиент реально настраивает в кабинете → Mini App.
--
-- Из-за этого у 6 клиентов меню в боте вело себя ОБРАТНО настройке: у клиента 1
-- стоял Telegram = «Вход через Мини-апп», а `/menu{id}` открывал веб-версию,
-- потому что общий режим был 'bot'.
--
-- ⚠️ Эта миграция НИЧЕГО не меняет в поведении. Она лишь записывает в
-- площадочные колонки то значение, которое и так применялось: старый код читал
-- площадочную колонку ПЕРВОЙ, а общий режим — только когда та пуста. После
-- бэкфилла пустых не остаётся, и обе ветки дают один результат.
--
-- Шаг 2 (код) и шаг 3 (удаление колонки, миграция 478) идут следом.

BEGIN;

-- Telegram и ВКонтакте: пусто → тот режим, который фактически действовал.
UPDATE clients
   SET link_mode_telegram = COALESCE(link_mode_telegram, default_link_mode, 'bot')
 WHERE link_mode_telegram IS NULL;

UPDATE clients
   SET link_mode_vk = COALESCE(link_mode_vk, default_link_mode, 'bot')
 WHERE link_mode_vk IS NULL;

-- ⚠️ MAX — ВСЕГДА 'bot', и код это форсит независимо от настройки: в MAX нет
-- запроса «разрешить боту писать», поэтому через Mini App человек на бота НЕ
-- подписывается и рассылки до него не дойдут. Записываем явно, чтобы в базе не
-- осталось значений, противоречащих поведению.
UPDATE clients SET link_mode_max = 'bot' WHERE link_mode_max IS DISTINCT FROM 'bot';

COMMIT;
