-- 450: у партнёра-КОМПАНИИ два логотипа — для тёмного и для светлого фона.
--
-- ⚠️⚠️ ЗАЧЕМ. У компании было ОДНО поле `photo_url`, и на афише переключатель
-- «для тёмного / для светлого фона» партнёров не касался вовсе: брать было
-- нечего. Настройка выглядела общей, а работала только на логотип бренда —
-- клиент ставил «для светлого фона» и получал те же светлые логотипы на белом
-- (жалоба владельца 18.09.2026: «логотипы все для тёмного фона у тебя»).
--
-- У бренда два поля были изначально (`clients.brand_logo_url` и
-- `brand_logo_light_url`), у партнёров — нет. Выравниваем.
--
-- ⚠️ ПОЛЕ ТОЛЬКО ДЛЯ КОМПАНИЙ. У человека карточка — это ФОТО, второй вариант
-- ему не нужен и в интерфейсе не показывается: признак — галочка
-- `is_company` (миграция 425).
--
-- ⚠️ Имена полей по СМЫСЛУ, а не «light/dark»: у бренда колонка называется
-- `brand_logo_light_url`, но лежит в ней ТЁМНАЯ версия «для светлого фона» —
-- на этом уже путались. Здесь `logo_on_light_url` читается однозначно:
-- логотип, который кладут НА СВЕТЛЫЙ фон.
--
--   photo_url         — основной логотип (кладётся на ТЁМНЫЙ фон);
--   logo_on_light_url — версия для СВЕТЛОГО фона.
--
-- Пусто во втором — берём основной: лучше показать хоть какой-то логотип, чем
-- пустое место.

BEGIN;

ALTER TABLE collaborators
  ADD COLUMN IF NOT EXISTS logo_on_light_url TEXT;

COMMENT ON COLUMN collaborators.logo_on_light_url IS
  'Логотип компании для СВЕТЛОГО фона. Основной (photo_url) — для тёмного. Только при is_company';

GRANT SELECT, INSERT, UPDATE, DELETE ON collaborators TO plusson;

COMMIT;
