-- 216: комментарий жюри к КАЖДОМУ критерию («Почему такая оценка», минимум 7 слов).
--
-- Раньше у жюри была только одна общая обратная связь на участника
-- (tournament_feedback, ≥10 слов). Теперь к каждому баллу — свой комментарий.
-- Живёт в той же строке, что и балл: одна оценка = один комментарий.
--
-- Валидация «не менее 7 слов» — на бэке (jury_lock) и на фронте, не в CHECK:
-- пустой комментарий допустим, пока жюри не зафиксировало оценку участника.

ALTER TABLE tournament_scores ADD COLUMN IF NOT EXISTS comment TEXT;

COMMENT ON COLUMN tournament_scores.comment IS
  'Комментарий жюри к этому баллу («Почему такая оценка»). Требуется ≥7 слов при фиксации.';
