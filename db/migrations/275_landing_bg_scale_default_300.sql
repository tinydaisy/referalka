--
-- ⚠️ Почему не 100. При 100% картинка вписывается в экран целиком, и на
-- широком мониторе фоновое фото выглядит мелким и «пустым» — деталей не
-- видно. 300% даёт крупный, наполненный кадр, который клиент дальше двигает
-- ползунками под свой объект. Потолок 500% нужен для фото, где смысловой
-- объект занимает малую часть кадра.

ALTER TABLE event_landing_pages
  ALTER COLUMN bg_scale SET DEFAULT 300;

