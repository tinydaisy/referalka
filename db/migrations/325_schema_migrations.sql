-- 325: учёт применённых миграций (2026-08-22)
--
-- Зачем. Учёта не было вовсе: какие из 337 файлов применены к базе — нигде не
-- записано. Отсюда две беды. Первая: dev и прод расходились месяцами, и «я
-- проверил на dev» ничего не значило — структура там была другая. Вторая:
-- проверить, накачена ли миграция, можно было только угадыванием «что она
-- создала», и на этом уже ошибались.
--
-- ⚠️ Ключ — ПОЛНОЕ ИМЯ ФАЙЛА, а не номер. В db/migrations 21 пара файлов с
-- ОДИНАКОВЫМИ номерами (004, 005, 041, 061, 065, 101, 102, 138, 164, 165, 172,
-- 200, 222, 226, 227, 228, 240, 261, 268, 282, 302) — их писали параллельно в
-- разных окнах. При учёте по номеру вторая из пары молча считалась бы
-- применённой. Заодно не нарушается правило «история миграций — летопись»:
-- переименовывать файлы не нужно.

CREATE TABLE IF NOT EXISTS schema_migrations (
    filename    TEXT PRIMARY KEY,          -- 321_webinar_recording_chunks.sql
    applied_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Как узнали, что применена: 'manual' — накатили скриптом,
    -- 'backfill' — отмечена задним числом при заведении учёта (2026-08-22).
    source      TEXT NOT NULL DEFAULT 'manual',
    checksum    TEXT                       -- sha256 файла на момент применения
);

CREATE INDEX IF NOT EXISTS idx_schema_migrations_applied
    ON schema_migrations (applied_at DESC);

COMMENT ON TABLE schema_migrations IS
  'Какие файлы из db/migrations применены к ЭТОЙ базе. Ключ — имя файла, а не '
  'номер: номера дублируются (21 пара).';

COMMENT ON COLUMN schema_migrations.checksum IS
  'sha256 файла при накате. Разошёлся с текущим — миграцию правили после '
  'применения, и базы на разных серверах могут отличаться.';

-- ⚠️ Роль plusson не владелец таблиц — без GRANT скрипт наката получит
-- permission denied.
GRANT SELECT, INSERT, UPDATE, DELETE ON schema_migrations TO plusson;
