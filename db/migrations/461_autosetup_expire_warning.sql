-- 461. Предупреждение перед удалением бота (18.09.2026, правило владельца:
--      «говори, когда удалишь — и удаляй»).
--
-- ЗАЧЕМ. Непереданный бот удаляется по истечении срока, и слот служебного
-- аккаунта освобождается. Но человек узнавал об этом ПОСТ-ФАКТУМ: бот просто
-- исчезал. Теперь за несколько часов до срока уходит отдельное предупреждение
-- «удалим тогда-то» — во все каналы, включая личку в боте.
--
-- ⚠️ Отметка нужна, потому что задача напоминаний бежит КАЖДЫЙ ЧАС. Без неё
-- предупреждение ушло бы столько раз, сколько часов осталось до срока.
-- Тот же приём, что у `queued_notice_at` и `delay_notice_at`.
--
-- ⚠️ Отдельной колонкой, а не через `reminders_sent`: обычные напоминания
-- («заберите бота») и предупреждение об удалении — разные сообщения с разной
-- срочностью, и считать их одним счётчиком значило бы, что четыре обычных
-- напоминания съедят право на предупреждение.

BEGIN;

ALTER TABLE service_orders
  ADD COLUMN IF NOT EXISTS expire_warned_at TIMESTAMPTZ;

COMMENT ON COLUMN service_orders.expire_warned_at IS
  'Когда отправлено предупреждение «скоро удалим бота». NULL — ещё не отправляли';

COMMIT;
