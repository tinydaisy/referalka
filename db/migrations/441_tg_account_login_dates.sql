-- 441. Даты готовности служебного аккаунта к передаче ботов (18.09.2026).
--
-- ЗАЧЕМ. Telegram не даёт передать бота, пока не выполнены ДВА ожидания, и
-- оба считаются от событий, которых в базе не было вовсе:
--
--   • двухфакторка включена **не менее 7 дней назад**;
--   • с последнего **входа в аккаунт** прошло **не менее 24 часов**.
--
-- ⚠️⚠️ ВТОРОЕ УСЛОВИЕ УЖЕ СТОИЛО НАМ СУТОК. На боте Светланы ждали отсчёт от
-- первой попытки передачи, а Telegram считал от ВХОДА, который случился позже
-- — при смене аккаунта. Внешне это выглядело как «передача почему-то не
-- работает на исправном аккаунте».
--
-- ⚠️ Поэтому даты храним явно, а не «помним»: только так видно, какой аккаунт
-- уже готов отдавать ботов, а какой ещё дозревает. Новый аккаунт надо логинить
-- СРАЗУ после покупки, чтобы оба отсчёта пошли заранее.
--
-- ⚠️ Обе даты NULL-able: у старых аккаунтов их взять неоткуда, а выдумывать
-- нельзя — «неизвестно» честнее, чем неверная дата, по которой решат, что
-- аккаунт готов.

BEGIN;

ALTER TABLE tg_setup_accounts
  -- Когда на аккаунте включена двухфакторка. От неё — недельный отсчёт.
  -- ⚠️ Дату спрашиваем у ПРОДАВЦА при покупке: если он включил 2FA прямо
  -- перед продажей, неделя ещё не прошла, и аккаунт не готов.
  ADD COLUMN IF NOT EXISTS twofa_enabled_at TIMESTAMPTZ,
  -- Когда мы последний раз входили в аккаунт. От неё — суточный отсчёт.
  -- ⚠️ Обновляется при КАЖДОМ входе (вход по коду, заливка сессии): любой
  -- новый логин обнуляет сутки заново, даже если аккаунт давно работает.
  ADD COLUMN IF NOT EXISTS last_login_at TIMESTAMPTZ;

COMMENT ON COLUMN tg_setup_accounts.twofa_enabled_at IS
  'Когда включена двухфакторка. Передача бота возможна не раньше чем через 7 дней после этого';
COMMENT ON COLUMN tg_setup_accounts.last_login_at IS
  'Последний вход в аккаунт. Передача бота возможна не раньше чем через 24 часа после входа';

-- ⚠️ У аккаунтов, которые УЖЕ передавали ботов, оба условия заведомо
-- выполнены — иначе передача бы не прошла.
--
-- ⚠️⚠️ ОТСЧИТЫВАЕМ 7 ДНЕЙ НАЗАД ОТ ПЕРВОЙ ПЕРЕДАЧИ, а не берём её саму.
-- Telegram разрешает передачу только через неделю после включения 2FA: если
-- передача прошла 11.09, двухфакторка была включена НЕ ПОЗЖЕ 04.09. Дата самой
-- передачи сдвинула бы отсчёт на неделю вперёд, и аккаунт, уже передавший трёх
-- ботов, показывался бы «дозревающим» (поймано сразу после наката, миграция
-- 442). Неверная дата хуже пустой в ОБЕ стороны: по ней принимают решение.
UPDATE tg_setup_accounts a
   SET twofa_enabled_at = s.first_transfer - INTERVAL '7 days',
       last_login_at    = s.first_transfer
  FROM (
        SELECT setup_account_id AS id,
               MIN(bot_transferred_at) AS first_transfer
          FROM service_orders
         WHERE setup_account_id IS NOT NULL
           AND bot_transferred_at IS NOT NULL
         GROUP BY setup_account_id
       ) s
 WHERE a.id = s.id
   AND a.twofa_enabled_at IS NULL;

COMMIT;
