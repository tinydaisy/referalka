-- Миграция 199: флаг системного сервисного клиента.
--
-- Зачем. Системного клиента «ПЛЮСОН Сервис» (держит @pluson_bot, приём лички,
-- трафик без контекста, базу «уличных» участников МедиаЛифта) раньше искали в 8
-- местах кода по `email = 'system@pluson.ru'`. Это хрупко: как только меняем email
-- этого аккаунта (напр. чтобы привязать реальную почту для восстановления пароля —
-- иначе аккаунт техподдержки могут увести), все системные флоу перестают его находить.
--
-- Решение (как у админа — по стабильному признаку, не по email): булев флаг.
-- Определяем системного клиента по `clients.is_system_service = TRUE`, а email
-- освобождаем под произвольную реальную почту.

ALTER TABLE clients
  ADD COLUMN IF NOT EXISTS is_system_service BOOLEAN NOT NULL DEFAULT FALSE;

-- Проставляем флаг текущему системному клиенту (id 3, «ПЛЮСОН Сервис»).
UPDATE clients SET is_system_service = TRUE WHERE id = 3;

-- Гарантия: системный сервисный клиент — РОВНО ОДИН (нельзя случайно пометить двух).
CREATE UNIQUE INDEX IF NOT EXISTS uniq_clients_system_service
  ON clients ((TRUE)) WHERE is_system_service = TRUE;
