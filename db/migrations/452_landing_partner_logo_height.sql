-- 452: высота белого поля с логотипом в блоке «Партнёры» на лендинге.
--
-- ⚠️⚠️ ЗАЧЕМ. Поле под логотипом было зашито в код: высота 120px, логотип не
-- выше 90px. Настройки не было вовсе — ни высоты, ни масштаба, ни подложки.
--
-- Из-за этого блок «Партнёры» выглядел неровно, и клиент не мог это починить.
-- Поле ГОРИЗОНТАЛЬНОЕ, а логотипы у партнёров чаще КВАДРАТНЫЕ: квадрат сразу
-- упирается в потолок по высоте и занимает по ширине те же ~90px из доступных
-- ~220 — то есть висит мелким значком посреди пустой белой плашки. А широкий
-- логотип (вроде 800×219) упирается в ШИРИНУ и занимает поле целиком. Рядом
-- это читается как «у одних партнёров логотип нормальный, у других — мелкий и
-- неопрятный», хотя дело только в пропорции файла.
--
-- Требование владельца (18.09.2026): дать высоту поля настройкой, чтобы блок
-- можно было сделать КВАДРАТНЫМ — тогда квадратные логотипы встают крупно, и
-- партнёрам не нужно перерисовывать свои файлы под горизонтальную плашку.
--
-- ⚠️ УМОЛЧАНИЕ 120 — ровно прежнее зашитое значение. Уже собранные лендинги
-- от этой миграции измениться не должны: высота меняется только там, где
-- клиент сам подвинул ползунок.
--
-- Границы 80..320 — те же, что у ползунка в конструкторе (BlockCard.tsx) и у
-- рендерера лендинга (LandingRenderer.tsx). Три места должны совпадать, иначе
-- настройка сохранится, а на странице обрежется до другого числа.

BEGIN;

ALTER TABLE event_landing_blocks
  ADD COLUMN IF NOT EXISTS logo_height SMALLINT NOT NULL DEFAULT 120
      CHECK (logo_height BETWEEN 80 AND 320);

COMMENT ON COLUMN event_landing_blocks.logo_height IS
  'Высота белого поля с логотипом в блоке «Партнёры», px (80..320). 120 — прежнее зашитое значение';

GRANT SELECT, INSERT, UPDATE, DELETE ON event_landing_blocks TO plusson;

COMMIT;
