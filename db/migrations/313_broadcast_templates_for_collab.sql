-- 313: спикерские шаблоны рассылок у КОЛЛАБ-события.
--
-- Проблема. Набор шаблонов подбирается по типу события через флаги
-- for_event / for_conference / for_turnir. Коллаб-событие — это обычная строка
-- в events с module_slug='base', то есть для подбора оно «мероприятие», а у
-- спикерских шаблонов (знакомство со спикерами, за 5 минут до выступления,
-- подарок после выступления) стоит for_event = FALSE. Поэтому у коллабы их не
-- было вовсе, хотя выступления там есть и программа есть.
--
-- Почему не включить им for_event. Тогда они появились бы у ВСЕХ мероприятий —
-- вебинаров, эфиров, нетворкингов, где спикеров нет в принципе, и клиент
-- получил бы в очереди мусор, который не к чему привязать.
--
-- Отсюда отдельный признак: у коллабы организаторы И ЕСТЬ спикеры, программа
-- строится по ним, поэтому спикерские шаблоны там осмысленны.
ALTER TABLE default_broadcast_templates
  ADD COLUMN IF NOT EXISTS for_collab BOOLEAN NOT NULL DEFAULT FALSE;

-- Коллабе доступно всё, что доступно обычному мероприятию…
UPDATE default_broadcast_templates SET for_collab = TRUE WHERE for_event;

-- …плюс спикерские шаблоны: у коллабы выступают сами организаторы.
UPDATE default_broadcast_templates SET for_collab = TRUE
 WHERE type IN ('pre_conf', 'speaker_intro', '5min_before', 'gift', 'expert_day');
