-- 451: приближение кадра у фото — СВОЁ для круга, квадрата и прямоугольника.
--
-- ⚠️⚠️ ЗАЧЕМ. Приближение было зашито в код константой (круг и квадрат ×1.6),
-- одинаковой для всех людей. Но снимки разные: у одного портрет по плечи — ему
-- приближать нечего, у другого человек в полный рост — там и ×1.6 мало.
-- Клиент видел результат только на готовой афише и поправить не мог.
--
-- Требование владельца (18.09.2026): подгонять кадр РУКАМИ в карточке спикера,
-- отдельно для каждой формы, а афиша берёт ровно эту настройку.
--
-- ⚠️ ТРИ ЧИСЛА, А НЕ ОДНО. Круг, квадрат и прямоугольник показывают разные по
-- форме куски снимка: в круг влезает почти квадратный фрагмент, в
-- прямоугольник — вытянутый. Один общий масштаб подошёл бы в лучшем случае
-- одной форме из трёх.
--
-- ⚠️ Точка лица (`photo_focal`, миграция 434) остаётся ОДНА на фото: центр
-- кадра везде один и тот же, меняется только насколько близко мы подходим.
--
-- 1.0 = кадр как есть (вся ширина фото), 3.0 = приближение втрое.
--
-- ⚠️ УМОЛЧАНИЕ 1.0 У ВСЕХ ФОРМ — кадр без приближения. Пробовали 1.6 у круга и
-- квадрата (так было зашито в коде): у портретов, снятых крупно, оно срезало
-- макушку и волосы. «По умолчанию ничего не отрезано» безопаснее, а приблизить
-- клиент может ползунком сам.

BEGIN;

ALTER TABLE collaborators
  ADD COLUMN IF NOT EXISTS crop_zoom_circle NUMERIC(4,2) NOT NULL DEFAULT 1.0
      CHECK (crop_zoom_circle BETWEEN 1 AND 3),
  ADD COLUMN IF NOT EXISTS crop_zoom_square NUMERIC(4,2) NOT NULL DEFAULT 1.0
      CHECK (crop_zoom_square BETWEEN 1 AND 3),
  ADD COLUMN IF NOT EXISTS crop_zoom_portrait NUMERIC(4,2) NOT NULL DEFAULT 1.0
      CHECK (crop_zoom_portrait BETWEEN 1 AND 3);

COMMENT ON COLUMN collaborators.crop_zoom_circle IS
  'Приближение кадра в КРУГЛОЙ маске (1.0 — как есть, 3.0 — втрое). Настраивается в карточке спикера';
COMMENT ON COLUMN collaborators.crop_zoom_square IS
  'Приближение кадра в КВАДРАТНОЙ маске';
COMMENT ON COLUMN collaborators.crop_zoom_portrait IS
  'Приближение кадра в ПРЯМОУГОЛЬНОЙ маске (по умолчанию 1.0 — портрет и так берётся по пояс)';

GRANT SELECT, INSERT, UPDATE, DELETE ON collaborators TO plusson;

COMMIT;
