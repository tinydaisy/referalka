-- 302_collaborator_last_name.sql
-- 2026-08-14
--
-- ФАМИЛИЯ КОЛЛАБОРАТОРА ОТДЕЛЬНЫМ ПОЛЕМ.
--
-- Было: одна строка `collaborators.name` = «Марго Форбс».
-- Стало: `name` = ИМЯ («Марго»), `last_name` = ФАМИЛИЯ («Форбс»).
--
-- Зачем. В премии номинантов сотни, и списки ищут глазами по фамилии —
-- а отсортировать по ней было нечем. Хуже: две подсистемы уже резали строку
-- по первому пробелу и делали это ПО-РАЗНОМУ —
--   speaker_cabinet._split_full_name(): первое слово = ИМЯ,
--   tournament.py ORDER BY split_part(name,' ',1): первое слово = ФАМИЛИЯ.
-- То есть один и тот же человек в кабинете и в турнире разбирался наоборот.
-- Отдельная колонка убирает обе догадки.
--
-- ⚠️ ПОРЯДОК СЛОВ ПРИ ВЫВОДЕ — РАЗНЫЙ, это осознанно (решение владельца):
--     где ИЩУТ (списки номинаций, распределение жюри, турнирная таблица,
--     привязка людей, база коллабов) — «Фамилия Имя»;
--     где ПОКАЗЫВАЮТ (лендинг, карточки, Mini App, рассылки) — «Имя Фамилия».
--     Единая точка склейки — backend/app/services/person_name.py.
--
-- ⚠️ РАЗБОР СУЩЕСТВУЮЩИХ 258 ЗАПИСЕЙ ЗДЕСЬ НЕ ДЕЛАЕТСЯ.
--     Автоматика тут врёт: «Бекренев Сергей» и «Марго Форбс» выглядят
--     одинаково, а компании («Грани (GRANI)», «Love Media») фамилии не имеют
--     вовсе. Разбор — отдельным выверенным скриптом
--     other_tasks/split_collaborator_names.sql, где перевёрнутые записи
--     и не-люди перечислены поимённо.
--
-- ⚠️ ДЕДУП КОЛЛАБОВ ПО ИМЕНИ НЕ ТРОГАЕМ (collaborators.py, conference.py:
--     LOWER(TRIM(c.name)) = LOWER($2)). Он ищет человека по полному имени;
--     сломать его = начать плодить дубли карточек.

BEGIN;

ALTER TABLE collaborators
  ADD COLUMN IF NOT EXISTS last_name TEXT;

COMMENT ON COLUMN collaborators.name IS
  'ИМЯ человека (после миграции 302). Для компаний/псевдонимов — вся строка целиком.';
COMMENT ON COLUMN collaborators.last_name IS
  'ФАМИЛИЯ. NULL/пусто у компаний, партнёров-организаций и однословных имён.';

-- Поиск по фамилии в базе коллабов (сортировка «Фамилия Имя»).
CREATE INDEX IF NOT EXISTS idx_collaborators_last_name
  ON collaborators (created_by_client_id, last_name, name);

COMMIT;
