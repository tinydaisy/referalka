-- 356: Строка «Личная переписка с подписчиками» в список возможностей тарифов
--
-- Раздел «Диалоги» (миграция 160) — история личных переписок с людьми, которые
-- писали ботам клиента, и ответы им прямо из кабинета (TG/VK/MAX), с правкой и
-- удалением своих сообщений у получателя. Живёт внутри карточки контакта.
-- В списке возможностей тарифа его не было вовсе.
--
-- ⚠️ Формулировка снимает ДВЕ путаницы сразу:
--   1. «Чат с подписчиками» читалось бы как ещё одна ГРУППА — слово «чат» в
--      кабинете уже занято («Чаты и группы для рассылок», чат события);
--   2. «Личные сообщения» читалось бы как переписка с ЛИЧНОГО аккаунта
--      клиента — а пишет бот, и отвечает клиент тоже от имени бота.
-- Отсюда «от имени бота»: видно и что переписка один на один, и кто отправитель.
-- Слово «Диалоги» для карточки тарифа не годится вовсе — это наше внутреннее
-- название раздела, человеку со стороны оно ничего не объясняет.
--
-- ⚠️ Строка ОПИСАТЕЛЬНАЯ, как `miniapp_funnels` (353) и `referral_program`
-- (355): гейта у раздела нет и `client_has_feature('dialogs')` нигде не
-- вызывается. Решите закрыть переписку тарифом — сначала проверьте, что это
-- намеренно: сейчас она работает у всех.
--
-- sort = 25 — сразу после «Чат-боты в Telegram, MAX и ВКонтакте» (20): сначала
-- «у вас есть боты», следом «и вы отвечаете их подписчикам из кабинета».

INSERT INTO features (slug, name, description, sort)
VALUES ('dialogs',
        'Переписка с подписчиками от имени бота — прямо из кабинета',
        'История личных сообщений человека с ботами клиента (Telegram, MAX, ВКонтакте) '
        'и ответы ему из кабинета, с правкой и удалением уже отправленного. '
        'Описательная строка тарифа — доступ ничем не гейтится.',
        25)
ON CONFLICT (slug) DO UPDATE SET name = EXCLUDED.name, sort = EXCLUDED.sort;

-- Всем тарифам, у которых есть лид-магниты (trial, start, pro, vip, admin).
INSERT INTO tariff_features (tariff_id, feature_id)
SELECT tf.tariff_id, (SELECT id FROM features WHERE slug = 'dialogs')
  FROM tariff_features tf
 WHERE tf.feature_id = (SELECT id FROM features WHERE slug = 'lead_magnets')
ON CONFLICT DO NOTHING;
