-- 381: Фамилия клиента отдельным полем
--
-- Зачем. В форме регистрации было одно поле «Имя», и человек невольно писал
-- туда только имя — фамилии у большинства клиентов нет вовсе. Обратиться к
-- клиенту по имени и фамилии (в письме, в счёте, в разговоре поддержки) было
-- нечем, а разбирать одну строку по пробелу нельзя: «Марго Форбс» и
-- «Бекренев Сергей» для машины неотличимы (ровно на этом уже ошибались с
-- collaborators — см. миграцию 302).
--
-- ⚠️ clients.name остаётся ИМЕНЕМ и не трогается: на него завязаны JWT,
-- админка, письма и вся выдача. Существующие записи не разбираем — там могло
-- быть записано что угодно (имя, «Имя Фамилия», название компании), и любой
-- автоматический разбор испортил бы часть данных молча.
--
-- ⚠️ Фамилия НЕОБЯЗАТЕЛЬНА в базе: у клиентов-компаний её нет, а старые записи
-- заполнить нечем. Обязательность живёт в форме регистрации, а не в схеме.

ALTER TABLE clients ADD COLUMN IF NOT EXISTS last_name TEXT;

COMMENT ON COLUMN clients.name IS 'Имя клиента (без фамилии — она в last_name)';
COMMENT ON COLUMN clients.last_name IS 'Фамилия клиента; пусто у компаний и у записей до миграции 381';
