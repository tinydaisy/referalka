-- 471: сколько угодно пилюль на любой афише.
--
-- ⚠️⚠️ ЗАЧЕМ. Пилюль было ровно две и обе зашиты в код: `pill_text` (дата) и
-- `pill_text_2` (формат). Третью добавить было нельзя вовсе — ни «Бесплатно»,
-- ни «Запись будет», ни город. Клиент попросил добавлять их самому на каждой
-- афише (владелец, 20.09.2026).
--
-- ⚠️ ПОЧЕМУ JSONB, А НЕ КОЛОНКИ pill_text_3, _4, _5. Число пилюль заранее
-- неизвестно, а каждая новая колонка — это миграция, поле в модели, поле в
-- типе и ещё одна ветка в вёрстке. На пятой пилюле таблица превращается в
-- частокол почти одинаковых полей, и любая правка оформления требует
-- пройти по всем. Список же рисуется одним циклом.
--
-- Формат: [{"text": "Бесплатно", "x": null, "y": null, "align": "center"}]
--   text  — что написано (пусто — пилюля не рисуется);
--   x/y   — своя точка на листе, % рабочей области; null — стоит в общем ряду
--           с первыми двумя (миграция 470 ввела ту же логику для текста);
--   align — выключка, если пилюля вынесена отдельно.
--
-- ⚠️ Оформление (рамка, цвет, кегль, шрифт) у добавленных пилюль ОБЩЕЕ с
-- первыми двумя: это те же пилюли, а не новый вид элемента. Разное оформление
-- в одном ряду выглядит как ошибка вёрстки, а не как замысел.

BEGIN;

ALTER TABLE event_poster_layouts
  ADD COLUMN IF NOT EXISTS extra_pills JSONB NOT NULL DEFAULT '[]'::jsonb;

-- ⚠️ Именно массив: объект сюда приедет при первой же ошибке на фронте, и
-- `.map()` по нему свалит всю афишу.
ALTER TABLE event_poster_layouts
  DROP CONSTRAINT IF EXISTS event_poster_layouts_extra_pills_check;
ALTER TABLE event_poster_layouts
  ADD CONSTRAINT event_poster_layouts_extra_pills_check
  CHECK (jsonb_typeof(extra_pills) = 'array');

COMMENT ON COLUMN event_poster_layouts.extra_pills IS
  'Дополнительные пилюли: [{text, x, y, align}]. x/y в % рабочей области, '
  'null — пилюля стоит в общем ряду. Оформление общее с основными пилюлями';

GRANT SELECT, INSERT, UPDATE, DELETE ON event_poster_layouts TO plusson;

COMMIT;
