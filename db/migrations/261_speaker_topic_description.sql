-- 261: У темы спикера появляется ОПИСАНИЕ — отдельно от названия.
--
-- Проблема. Поле `topic` было одно, и спикеры вписывали в него всё сразу:
-- название мастер-класса + абзац описания + буллиты (до 350+ символов).
-- В ТЕЛЕ рассылки это выглядит нормально (переносы строк сохраняются), а вот
-- в ЗАГОЛОВКЕ письма (subject) тема обязана быть ОДНОЙ строкой — многострочный
-- текст склеивался через « · » и превращался в нечитаемую простыню.
--
-- Решение: `topic` = только НАЗВАНИЕ (одна строка, идёт в заголовок и в
-- программу), `description` = что будет на выступлении (многострочный текст,
-- идёт в тело рассылки и на карточку спикера).
--
-- Два плейсхолдера:
--   {speaker_topic}      — только НАЗВАНИЕ (одна строка) → заголовок, программа;
--   {speaker_topic_full} — название + описание → тело рассылки, карточка.
--
-- ⚠️ Бэкфилла НЕТ намеренно: уже введённые темы не режем автоматически (можно
-- порвать текст в неудачном месте). Клиент сам разносит их руками в карточке
-- спикера. Пока описание пустое, {speaker_topic_full} = просто тема — старое
-- поведение сохраняется.

ALTER TABLE conf_speaker_topics
  ADD COLUMN IF NOT EXISTS description TEXT;

GRANT SELECT, INSERT, UPDATE, DELETE ON conf_speaker_topics TO plusson;
