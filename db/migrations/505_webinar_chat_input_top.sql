-- 505. Поле ввода чата сверху или снизу — настройка комнаты (23.09.2026)
--
-- ЗАЧЕМ. Поле ввода и кнопка отправки жёстко стояли ПОД лентой сообщений.
-- Организатору бывает нужно наоборот: на длинном эфире лента уезжает вниз, и
-- поле ввода сверху не приходится искать глазами, а свежие сообщения видно
-- сразу под ним.
--
-- ⚠️ BOOLEAN, а не строка с вариантами: положений ровно два, и третьего быть
-- не может. Строка ('top'/'bottom') открыла бы дорогу опечатке в данных,
-- которую фронт молча прочитает как «ни то ни другое».
--
-- ⚠️ DEFAULT FALSE = как было (поле снизу): настроенные комнаты не меняются
-- сами по себе, организатор включит, если захочет.

ALTER TABLE webinar_rooms
    ADD COLUMN IF NOT EXISTS chat_input_on_top BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN webinar_rooms.chat_input_on_top IS
  'TRUE — поле ввода и кнопка отправки НАД лентой чата; FALSE (по умолчанию) — под лентой, как было.';
