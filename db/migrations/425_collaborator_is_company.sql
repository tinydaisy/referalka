-- 425: явная галочка «Компания» у карточки человека/организации.
--
-- ⚠️⚠️ УГАДЫВАТЬ ПО ДАННЫМ БОЛЬШЕ НЕ НАДО. Раньше признак «это компания»
-- выводили из ПУСТОЙ ФАМИЛИИ (миграция 302): мол, у организаций её не бывает.
-- Правило развалилось на живых данных: у карточки «iViSiON: ПЛЮСОН от Марго
-- Форбс» фамилия «Форбс» заполнена — и логотип поехал в портретный квадрат,
-- обрезался по бокам и растянулся по высоте (жалоба со скриншотом 16.09.2026).
--
-- Клиент вправе заполнять свои поля как ему удобно — и фамилию, и
-- позиционирование (у бренда оно тоже есть). Вид карточки не должен зависеть
-- от того, что он туда вписал: для этого есть явная галочка.
--
-- Зачем вообще различать (в вёрстке это ДВА разных показа):
--   компания — белое поле, логотип вписан ЦЕЛИКОМ (object-contain), не режется;
--   человек  — фото на всю ширину КВАДРАТОМ, обрезается по краям (object-cover).
-- Логотип в квадрате режется по бокам, портрет в белом поле висит маленьким
-- прямоугольником в пустоте — поэтому нужны оба вида.

ALTER TABLE collaborators
  ADD COLUMN IF NOT EXISTS is_company BOOLEAN;

COMMENT ON COLUMN collaborators.is_company IS
  'Карточка — организация (логотип целиком на белом), а не человек (фото квадратом). NULL = не задано, решает роль.';

-- ⚠️ Бэкфилл: ВСЕМ, у кого есть карточка партнёра, ставим TRUE — решение
-- владельца («всем партнёрам по умолчанию галочка Компания»). Партнёр почти
-- всегда организация; у кого это человек, клиент снимет галочку сам.
--
-- ⚠️ Ставим ТОЛЬКО там, где значение ещё не задано (IS NULL) — чтобы повторный
-- прогон миграции не перетёр уже снятую клиентом галочку.
UPDATE collaborators c
   SET is_company = TRUE
 WHERE c.is_company IS NULL
   AND EXISTS (
     SELECT 1 FROM event_collaborators ec
      WHERE ec.speaker_id = c.id
        AND ec.role IN ('general_partner', 'partner')
   );

