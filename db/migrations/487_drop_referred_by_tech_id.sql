-- 487: дроп clients.referred_by_tech_id — «какого техспеца привёл» больше нет (2026-09-22)
--
-- Решение владельца, дословно: такого понятия нет. Внедренец приглашает
-- ССЫЛКОЙ ИЗ СВОЕГО КЛИЕНТСКОГО КАБИНЕТА — владелец так и сказала внедренцам.
-- Значит «кто привёл» ровно одно и хранится в одном месте:
-- `clients.referred_by_client_id` (+ код `clients.referral_code`).
--
-- ⚠️⚠️ ЧТО ЭТО ОТМЕНЯЕТ. Миграция 393 завела ВТОРОЙ реф-код на того же человека:
-- `tech_specialists.referral_code` и парную колонку `clients.referred_by_tech_id`.
-- Задумка не работала ни дня: при регистрации `pid` резолвился ТОЛЬКО как
-- клиентский код, внедренческий не проверялся вовсе — колонка читалась при
-- расчёте премий, но заполнялась лишь руками при заведении тестовых данных.
-- Урок, чтобы не наступить второй раз: два кода на одного человека — это две
-- правды о том, кто привёл клиента, и деньги по ним считаются по-разному.
--
-- ⚠️ Начисления от этого НЕ меняются по смыслу. Цепочка уровней и раньше шла по
-- клиентским ссылкам (`referred_by_client_id`), а `referred_by_tech_id` лишь
-- переводил «клиент → его внедренец». После 486 этот перевод делает
-- `tech_specialists.client_id`, то есть JOIN вместо колонки. Ставки, вилки,
-- пороги и условия премии не тронуты.
--
-- ⚠️ У внедренца остаются И премия, И проценты — это его система мотивации
-- (решение владельца 22.09.2026). У партнёра, который не внедренец, только
-- процент. Поэтому «премия или процент» не выбирается: получает оба.

-- Индекс уходит вместе с колонкой, но снимаем явно — понятнее в логе наката.
DROP INDEX IF EXISTS clients_referred_by_tech_idx;

ALTER TABLE clients DROP COLUMN IF EXISTS referred_by_tech_id;

-- Второй реф-код внедренца — под нож по той же причине: один человек, один код.
DROP INDEX IF EXISTS tech_specialists_referral_code_key;
ALTER TABLE tech_specialists DROP COLUMN IF EXISTS referral_code;

COMMENT ON COLUMN clients.referred_by_client_id IS
  'Кто привёл этого клиента — ЕДИНСТВЕННОЕ «кто привёл» в системе. Внедренец '
  'приглашает ссылкой из своего клиентского кабинета, поэтому отдельного '
  '«какой техспец привёл» нет (миграция 487 дропнула referred_by_tech_id).';

