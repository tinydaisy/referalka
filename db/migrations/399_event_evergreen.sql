-- 398. Событие без даты: «идёт постоянно».
--
-- Зачем. Часть предложений датой не описывается вовсе: запись на консультацию,
-- доступ к материалам, приём заявок «пока не наберём группу». Дата у них
-- существует только чтобы обойти проверку публикации, и клиенту приходится
-- выдумывать её — обычно ставят 2050 год.
--
-- ⚠️⚠️ ДАТА 2050 — ХУДШЕЕ ИЗ РЕШЕНИЙ, и поэтому заводится отдельный признак.
-- Такое событие садится в самый конец календаря, оказывается в «Скоро» после
-- всех настоящих событий, и за сутки до него уходят напоминания «завтра
-- начинается» — в 2050 году. То есть выдуманная дата не просто бесполезна,
-- она ломает три механизма сразу.
--
-- ⚠️ Что даёт признак: событие публикуется без даты, показывается в календаре
-- отдельной группой «Идут постоянно» (а не среди датированных), не участвует в
-- напоминаниях и никогда не считается завершённым.
--
-- ⚠️ Дату при этом НЕ запрещаем: у бессрочного события её просто нет. Если
-- клиент однажды поставит дату — признак снимается, и событие становится
-- обычным. Обратной чистки не требуется.

ALTER TABLE events
    ADD COLUMN IF NOT EXISTS is_evergreen BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN events.is_evergreen IS
    'Событие идёт постоянно и не имеет даты: запись на консультацию, доступ к '
    'материалам, бессрочный приём заявок. Публикуется без start_at, в календаре '
    'показывается отдельной группой, напоминания по нему не шлются и '
    'завершённым оно не становится.';
