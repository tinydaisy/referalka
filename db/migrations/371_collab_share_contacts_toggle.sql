-- 371: галочка «раздавать контакты всем организаторам» у коллаб-события
--
-- Раздача почты и телефона всем организаторам коллабы (миграция от 2026-08-18)
-- была БЕЗУСЛОВНОЙ: зарегистрировался человек — его контакты появлялись в базе
-- каждого партнёра. Партнёры договариваются об этом по-разному: где-то база
-- общая по уговору, где-то каждый ведёт свою и делиться не готов. Решать за
-- них платформа не должна — теперь это выбор организаторов на самом событии.
--
-- ⚠️⚠️ ПО УМОЛЧАНИЮ TRUE — так работало до сих пор. Поставить FALSE значило бы
-- молча отключить раздачу у идущих коллабораций: партнёр, который вчера видел
-- контакты пришедших, сегодня перестал бы их получать и решил, что сломалось.
--
-- ⚠️ Галочка НЕ трогает уже розданное. Снятая — прекращает раздачу с этого
-- момента; отобрать контакты, которые партнёр уже получил (и мог использовать),
-- нельзя ни технически, ни по смыслу.
--
-- ⚠️ Поле на СОБЫТИИ, а не на клиенте: у одного и того же организатора одна
-- коллаборация может быть с полным доверием, другая — с раздельными базами.

ALTER TABLE events
  ADD COLUMN IF NOT EXISTS collab_share_contacts BOOLEAN NOT NULL DEFAULT TRUE;

COMMENT ON COLUMN events.collab_share_contacts IS
  'Коллаба: раздавать ли почту и телефон зарегистрировавшегося ВСЕМ организаторам. '
  'FALSE — контакт остаётся только у того, кто привёл. Действует с момента снятия, '
  'уже розданное не отзывается.';
