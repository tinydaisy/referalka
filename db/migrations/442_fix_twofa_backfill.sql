-- 442. Поправка дат 2FA у аккаунтов, которые уже передавали ботов (18.09.2026).
--
-- ⚠️ ЧТО БЫЛО НЕ ТАК В МИГРАЦИИ 441. Она ставила `twofa_enabled_at` = дате
-- ПЕРВОЙ УДАЧНОЙ ПЕРЕДАЧИ. Рассуждение было такое: раз передача прошла, в тот
-- момент аккаунт точно был готов. Верно — но дата получилась ПОЗЖЕ реальной.
--
-- Telegram разрешает передачу только через 7 дней после включения 2FA. Значит
-- если передача случилась 11.09, то двухфакторка была включена НЕ ПОЗЖЕ 04.09.
-- Поставив 11.09, мы сдвинули отсчёт на неделю вперёд — и аккаунт `998700388276`,
-- передавший трёх ботов (11.09 и 16.09), показывался как «дозревает».
--
-- ⚠️ Это ровно та ошибка, от которой предостерегает сама 441: неверная дата
-- хуже пустой. Там опасались обратного — что аккаунт сочтут готовым, не будучи
-- им; вышло наоборот, готовый считается неготовым. Оба случая одинаково плохи:
-- по дате принимают решение.
--
-- Сдвигаем на 7 дней назад от первой передачи — это доказанная верхняя граница
-- момента включения (раньше могло быть, позже — нет).

BEGIN;

UPDATE tg_setup_accounts a
   SET twofa_enabled_at = s.first_transfer - INTERVAL '7 days'
  FROM (
        SELECT setup_account_id AS id,
               MIN(bot_transferred_at) AS first_transfer
          FROM service_orders
         WHERE setup_account_id IS NOT NULL
           AND bot_transferred_at IS NOT NULL
         GROUP BY setup_account_id
       ) s
 WHERE a.id = s.id
   -- Только те, где дату поставила миграция 441 (она равна первой передаче).
   -- Руками вписанную дату НЕ трогаем: человек знает точнее нас.
   AND a.twofa_enabled_at = s.first_transfer;

COMMIT;
