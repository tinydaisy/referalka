-- 222. Вебинарная комната: ручной старт эфира («Начать эфир» / «Завершить эфир»).
--
-- ЗАЧЕМ. Раньше комната уходила в LIVE автоматически, как только видеокодер начинал
-- слать поток (хук runOnReady от MediaMTX). Это неправильно: спикер сначала
-- настраивается в Zoom (свет, звук, демонстрация экрана) — зрители не должны это видеть.
--
-- Как в GetCourse: поток пришёл → комната «готова» (ведущий видит превью, зрители нет)
-- → ведущий жмёт «Начать эфир» → зрители видят → «Завершить эфир» → редирект на redirect_url.
--
-- Статусы webinar_rooms.status:
--   idle  — потока нет
--   ready — поток идёт, но эфир НЕ начат (превью только ведущему; зрителям «скоро начнётся»)
--   live  — ведущий нажал «Начать эфир» → зрители видят поток
--   ended — ведущий нажал «Завершить эфир» → зрителей перебрасывает на redirect_url

BEGIN;

-- Флаг «поток физически идёт» — отдельно от статуса эфира.
-- Ставится/снимается хуком MediaMTX, не зависит от решения ведущего.
ALTER TABLE webinar_rooms
  ADD COLUMN IF NOT EXISTS stream_active BOOLEAN NOT NULL DEFAULT FALSE;

-- Бэкфилл: комнаты, которые сейчас в live по старой авто-логике, оставляем в live
-- (эфир реально шёл), для остальных stream_active=FALSE.
UPDATE webinar_rooms SET stream_active = TRUE WHERE status = 'live';

GRANT SELECT, INSERT, UPDATE, DELETE ON webinar_rooms TO plusson;

COMMIT;
