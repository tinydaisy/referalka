-- 212: Настраиваемый текст кнопки на встроенном лендинге события.
--
-- До этого текст был захардкожен в Mini App и на веб-странице события:
--   * конкурс (module_slug='contest') — «КАК ГОЛОСОВАТЬ?»
--   * все остальные типы            — «Хочу участвовать»
--
-- Теперь клиент может задать свой текст. Пусто (NULL) → прежние дефолты,
-- поэтому у существующих событий ничего не меняется.

ALTER TABLE events
  ADD COLUMN IF NOT EXISTS landing_cta_label TEXT NULL;

COMMENT ON COLUMN events.landing_cta_label IS
  'Текст кнопки на встроенном лендинге события (Mini App + веб-страница). Пусто = дефолт по типу события.';
