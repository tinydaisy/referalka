-- 335: закрепление контакта наверху списка.
--
-- Зачем. С частью людей идёт живая переписка — договариваетесь о спикерстве,
-- ждёте ответа, обещали перезвонить. В списке из тысяч контактов такой человек
-- теряется через день: он уезжает вниз по мере того, как приходят новые.
--
-- ⚠️ Закрепление ОБЩЕЕ НА КАБИНЕТ, а не личное у каждого помощника. Помощник
-- ведёт базу владельца, а не свою: закрепили контакт — его видят все, кто
-- работает в кабинете, и понимают, что с человеком идёт разговор. При личном
-- закреплении у каждого был бы свой порядок списка, и владелец не понял бы,
-- почему у помощника наверху другие люди.
--
-- Храним ВРЕМЯ, а не галочку: закреплённые показываются по свежести —
-- последний закреплённый сверху. С галочкой пришлось бы сортировать их по
-- id, то есть по дате появления в базе, что к текущей работе отношения не
-- имеет.

ALTER TABLE contacts ADD COLUMN IF NOT EXISTS pinned_at TIMESTAMPTZ;

-- ⚠️ Индекс ЧАСТИЧНЫЙ: закреплённых всегда единицы, а контактов десятки
-- тысяч. Полный индекс по той же колонке весил бы в сотни раз больше и
-- переписывался бы при каждом изменении контакта.
CREATE INDEX IF NOT EXISTS contacts_pinned_idx
    ON contacts (client_id, pinned_at DESC)
    WHERE pinned_at IS NOT NULL;
