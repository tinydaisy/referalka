-- 447: заголовок афиши из ДВУХ частей, каждая своим цветом.
--
-- ⚠️ ЗАЧЕМ. На макетах заказчика заголовок почти всегда двухцветный:
-- «ВИДЕНИЕ/iViSiON-7:» белым и «БИЗНЕСЫ ВЛИЯНИЯ ВНЕ СТАНДАРТОВ» золотом;
-- «"IVISION-6:» белым, «ДЕЛАЙ ИМЯ И ПРОДАЖИ"» золотом. Одним полем и одним
-- цветом это не собрать вовсе — приходилось бы рисовать заголовок прямо на
-- фоне в фотошопе, ради чего генератор и затевался.
--
-- ⚠️ ДВЕ ЧАСТИ, А НЕ РАЗМЕТКА ВНУТРИ ТЕКСТА. Теги вроде <b> клиенту пришлось
-- бы печатать руками, а ошибку в них он увидел бы только в готовом файле.
-- Два поля с двумя цветами — то же самое, но без синтаксиса.
--
-- ⚠️ Вторая часть НЕОБЯЗАТЕЛЬНА: пусто — заголовок остаётся одноцветным, как
-- и было. Шрифт, кегль, металл и подчёркивание общие на обе части: это ОДИН
-- заголовок, разбитый по цвету, а не два разных текста.

BEGIN;

ALTER TABLE event_poster_layouts
  ADD COLUMN IF NOT EXISTS title_2 TEXT,
  ADD COLUMN IF NOT EXISTS title_2_color TEXT,
  -- Вторая часть с новой строки или в подбор к первой.
  ADD COLUMN IF NOT EXISTS title_2_newline BOOLEAN NOT NULL DEFAULT TRUE;

COMMENT ON COLUMN event_poster_layouts.title_2 IS
  'Вторая часть заголовка — своим цветом. Пусто = заголовок одноцветный';
COMMENT ON COLUMN event_poster_layouts.title_2_color IS
  'Цвет второй части. Пусто = золото бренда';
COMMENT ON COLUMN event_poster_layouts.title_2_newline IS
  'Вторую часть — с новой строки (TRUE) или в подбор к первой';

GRANT SELECT, INSERT, UPDATE, DELETE ON event_poster_layouts TO plusson;

COMMIT;
