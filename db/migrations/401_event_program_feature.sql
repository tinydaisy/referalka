-- 401. Программа по дням у обычного мероприятия — фича «event_program» (Экстра).
--
-- Зачем. Трёхдневник нельзя было провести мероприятием: расписание по дням
-- показывалось только у конференций, турниров и коллаб. Клиенту приходилось
-- заводить конференцию (отдельный платный модуль) ради одной вкладки.
--
-- ⚠️⚠️ НОВОГО МЕХАНИЗМА НЕТ И НЕ НУЖНО. Программа живёт в `conf_days` +
-- `conf_sessions`, а доступ к ней проверяет ВЛАДЕНИЕ событием, а не его тип
-- (`check_conference_access` в modules/conference.py). У коллаб-события она
-- работала всё это время именно поэтому. Не хватало ровно одного: вкладку не
-- показывали. Своя реализация «программы для мероприятий» была бы второй
-- копией того же самого — и разъехалась бы с первой.
--
-- ⚠️ Почему по фиче, а не всем подряд: у однодневного мероприятия программа из
-- одного дня и одного слота не нужна и только путает. Клиент включает её
-- осознанно, когда событие действительно многодневное.
--
-- ⚠️ Модуль «Конференции» этим не обесценивается: там спикеры с карточками,
-- параллельные залы, рассылки по слотам и оценки. Здесь — только расписание.

INSERT INTO features (slug, name, description)
VALUES ('event_program', 'Программа по дням у мероприятий',
        'Расписание по дням у обычного мероприятия: многодневные события без '
        'подключения модуля «Конференции».')
ON CONFLICT (slug) DO UPDATE SET name = EXCLUDED.name,
                                 description = EXCLUDED.description;

-- Экстра + admin. ⚠️ Триалу фича зеркалится автоматически только для `pro`
-- (правило «триал = Профи»), поэтому здесь её нет — это возможность Экстры.
INSERT INTO tariff_features (tariff_id, feature_id)
SELECT t.id, f.id
  FROM tariffs t, features f
 WHERE t.slug IN ('vip', 'admin') AND f.slug = 'event_program'
ON CONFLICT DO NOTHING;
