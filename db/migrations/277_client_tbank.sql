-- 277: Эквайринг Т-Банка как третья платёжная система КЛИЕНТА
--      (в дополнение к LeadPay и Продамусу).
--
-- ⚠️ Не путать с ключами ПЛЮСОНа (LEADPAY_*, PRODAMUS_SECRET_KEY в переменных
-- окружения) — ими оплачивают подписку на платформу. Здесь ключи КАЖДОГО
-- клиента: ими его покупатели оплачивают тарифы его событий, деньги идут ему.
--
-- ⚠️ Т-Банк ближе к LeadPay, чем к Продамусу: ссылку на оплату он ВЫДАЁТ по
-- сети (метод Init отдаёт PaymentURL). Но кода товара, как у LeadPay, не
-- требует — название и цена уходят прямо в запросе.
--
-- ⚠️ Про «Т-Чеки». Это НЕ отдельная платёжная система, а сервис фискализации
-- поверх этого же эквайринга: клиент включает его в своём кабинете Т-Банка,
-- и банк сам выдаёт чеки покупателям. От нас требуется только передать состав
-- заказа (объект Receipt) в том же запросе Init. Поэтому отдельных полей под
-- «Т-Чеки» здесь нет — есть система налогообложения и ставка НДС, без которых
-- банк чек собрать не сможет.

-- ⚠️ Тестовый терминал у Т-Банка — это ОТДЕЛЬНАЯ ПАРА КЛЮЧЕЙ, а не флаг в
-- запросе: банк выдаёт её в кабинете рядом с боевой. Адрес API один и тот же.
-- Поэтому храним обе пары сразу и переключаемся галочкой: иначе клиент,
-- закончив проверку, стирал бы тестовые ключи и вбивал боевые руками — а
-- вернуться к проверке потом было бы нечем.

ALTER TABLE clients
  ADD COLUMN IF NOT EXISTS pay_tbank_terminal_key TEXT,  -- боевой TerminalKey
  ADD COLUMN IF NOT EXISTS pay_tbank_password     TEXT,  -- боевой пароль (для подписи)
  ADD COLUMN IF NOT EXISTS pay_tbank_test_terminal_key TEXT,  -- тестовый TerminalKey
  ADD COLUMN IF NOT EXISTS pay_tbank_test_password     TEXT,  -- тестовый пароль
  -- Галочка «работать на тестовом терминале». По умолчанию FALSE — боевой
  -- режим: забытая включённой галочка означала бы, что деньги не приходят.
  ADD COLUMN IF NOT EXISTS pay_tbank_test_mode BOOLEAN NOT NULL DEFAULT FALSE,
  -- Для чека: система налогообложения и ставка НДС. Значения — из документации
  -- Т-Банка (osn | usn_income | usn_income_outcome | esn | patent и
  -- none | vat0 | vat5 | vat7 | vat10 | vat20 …). Пусто → usn_income / none:
  -- самый частый случай у наших клиентов, и оплата не сорвётся из-за пустого поля.
  ADD COLUMN IF NOT EXISTS pay_tbank_taxation     TEXT,
  ADD COLUMN IF NOT EXISTS pay_tbank_vat          TEXT;

-- pay_provider теперь принимает 'leadpay' | 'prodamus' | 'tbank' | NULL.
-- CHECK по-прежнему не ставим: значение нормализуется в API, а лишнее
-- ограничение помешает добавить четвёртую систему данными.

