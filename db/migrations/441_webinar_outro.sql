-- 441: Экран «эфир завершён» — предложение, кнопка и автопереход со счётчиком.
--
-- Было: «Вебинар завершён · Спасибо, что были с нами!» и всё. Если задан
-- redirect_url — молчаливый переход через 4 секунды (хардкод во фронте).
-- Человек, пришедший после эфира, не узнавал ни про следующий день, ни про
-- предложение — просто улетал по ссылке, не успев ничего прочитать.
--
-- Стало: на экране завершения
--   • строка про СЛЕДУЮЩИЙ ДЕНЬ, если он есть в программе (считается на бэке,
--     той же логикой, что {next_day_mention} в рассылках — формулировки совпадают);
--   • предложение + кнопка, если задана ссылка перехода;
--   • видимый счётчик «перейдём через N сек».
-- Кнопка и автопереход ведут в ОДНО место — тот самый redirect_url.
--
-- ⚠️ ЗНАЧЕНИЯ ПО УМОЛЧАНИЮ — НЕ ПУСТЫЕ (требование владельца 18.09.2026).
-- Пустое поле с подсказкой-плейсхолдером не годится: непонятно, покажется
-- что-то в итоге или нет. Тексты сразу лежат в поле, их видно и можно править.
--
-- Блок предложения не показывается, если не задана ссылка: кнопка в никуда
-- бессмысленна. Текст при этом сохраняется — вернут ссылку, и он оживёт.

ALTER TABLE webinar_rooms
  ADD COLUMN IF NOT EXISTS outro_offer_text TEXT
    DEFAULT 'А пока у нас для вас предложение';
ALTER TABLE webinar_rooms
  ADD COLUMN IF NOT EXISTS outro_button_label TEXT
    DEFAULT 'Смотреть предложение';
-- Секунды до автоперехода. 15 вместо прежних 4: за 4 секунды человек не успеет
-- прочитать ни про следующий день, ни про предложение. 0 = не переводить
-- автоматически (уйдёт только по кнопке).
ALTER TABLE webinar_rooms
  ADD COLUMN IF NOT EXISTS outro_redirect_sec INTEGER NOT NULL DEFAULT 15;

COMMENT ON COLUMN webinar_rooms.outro_offer_text
  IS 'Подводка к предложению на экране «эфир завершён». Пусто → строки нет';
COMMENT ON COLUMN webinar_rooms.outro_button_label
  IS 'Надпись на кнопке перехода. Кнопка и автопереход ведут на redirect_url';
COMMENT ON COLUMN webinar_rooms.outro_redirect_sec
  IS 'Через сколько секунд автопереход на redirect_url. 0 = не переводить';

-- Уже созданным комнатам DEFAULT не проставляется задним числом — заполняем,
-- иначе у старых дней поля остались бы пустыми и владелец увидел бы ровно то,
-- чего просил избежать: пустые поля и неясность, что покажется.
UPDATE webinar_rooms
   SET outro_offer_text   = COALESCE(outro_offer_text,   'А пока у нас для вас предложение'),
       outro_button_label = COALESCE(outro_button_label, 'Смотреть предложение')
 WHERE outro_offer_text IS NULL OR outro_button_label IS NULL;
