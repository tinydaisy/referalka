-- 396. Обложка нарезки выступления.
--
-- Нарезку отдают спикеру, чтобы он выложил её у себя (VK, YouTube, Rutube).
-- Без обложки видео там выглядит чёрным прямоугольником, а собирать картинку
-- руками на каждое выступление — работа на весь состав конференции.
--
-- ⚠️⚠️ ОТДЕЛЬНЫЙ ШАБЛОН СЮДА НЕ ЗАВОДИТСЯ. Обложка строится видом `speaker`
-- из `cover_templates` — он и создавался ровно под это (миграция 387: «обложка
-- нужна записи эфира — её грузят на YouTube и клеят к видео»). Второй шаблон
-- рядом означал бы, что клиент правит оформление в двух местах и они
-- расходятся.
--
-- ⚠️ Храним ССЫЛКУ на готовый PNG, а не настройки обложки. Настройки живут в
-- шаблоне и читаются при сборке; копия здесь застыла бы на день нарезки, и
-- правка фирменного стиля не доехала бы до уже нарезанных выступлений.
--
-- ⚠️ Пусто = обложку ещё не собирали. Это НЕ «обложки не будет»: её собирают
-- перед нарезкой (кнопкой «Проверить обложки») и заново при самой нарезке.

ALTER TABLE webinar_recording_cuts
    ADD COLUMN IF NOT EXISTS cover_url TEXT;

COMMENT ON COLUMN webinar_recording_cuts.cover_url IS
    'PNG обложки выступления: вклеивается в начало ролика и отдаётся файлом '
    'при скачивании. Собирается видом speaker из cover_templates. '
    'NULL — ещё не собирали.';
