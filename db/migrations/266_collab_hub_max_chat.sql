-- 266. Закрытый чат Коллабораторной — вторая площадка (MAX).
--
-- Чат один по смыслу, но живёт на двух площадках: у части участников нет
-- Telegram, у части — MAX. Раньше в `collab_hub_settings` была одна колонка
-- `chat_url` (Telegram), и пункт меню вёл прямо в неё — второй площадке места
-- не было.
--
-- Теперь пункт «Закрытый чат» открывает страницу с кнопками на те площадки,
-- где ссылка заполнена. Заполнена одна — на странице одна кнопка; не заполнена
-- ни одна — пункта в меню нет (как и было).
--
-- ⚠️ Существующую `chat_url` НЕ переименовываем в `chat_url_tg`: на неё
-- завязаны API, админка и сайдбар, а выигрыш — косметический.

ALTER TABLE collab_hub_settings
    ADD COLUMN IF NOT EXISTS chat_url_max TEXT;

COMMENT ON COLUMN collab_hub_settings.chat_url     IS 'Инвайт-ссылка в закрытый чат, Telegram';
COMMENT ON COLUMN collab_hub_settings.chat_url_max IS 'Инвайт-ссылка в закрытый чат, MAX';
