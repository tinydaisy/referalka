-- 521: Почта в «Диалогах» — входящие письма на support@pluson.ru и ответы на них.
--
-- ⚠️⚠️ ЗАЧЕМ. Почтовый сервер ПЛЮСОНа до сих пор только ОТПРАВЛЯЛ (решение
-- 04.05.2026): клиент отвечал на письмо — ответ пропадал. «Диалоги» внедренца
-- при этом уже предлагали «написать на почту», но отправка падала с
-- «Неизвестная платформа». Решение владельца 26.09.2026: входящие письма
-- падают в «Диалоги» рядом с Telegram/MAX/ВК — тому внедренцу, за кем закреплён
-- клиент, — и ответ уходит письмом от ПЛЮСОНа. Личных ящиков не заводим:
-- переписка остаётся у платформы, а не уходит вместе с человеком.

-- ⚠️ NOT VALID: старые строки не перепроверяем — они заведомо подходят (список
-- только расширяется), а полная проверка держала бы блокировку всей таблицы
-- переписки на время прохода. Новые строки проверяются как обычно.
ALTER TABLE direct_messages DROP CONSTRAINT IF EXISTS direct_messages_platform_chk;
ALTER TABLE direct_messages ADD CONSTRAINT direct_messages_platform_chk
    CHECK (platform IN ('telegram', 'vk', 'max', 'instagram', 'email')) NOT VALID;

-- Тема письма: у мессенджеров её нет, у почты без неё ответ не свяжется с
-- перепиской в ящике клиента («Re: <тема>» + In-Reply-To).
ALTER TABLE direct_messages ADD COLUMN IF NOT EXISTS email_subject TEXT;
