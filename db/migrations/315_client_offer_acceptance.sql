-- 315: Фиксация акцепта Оферты и согласия на обработку персональных данных
--
-- Зачем. Публичная оферта считается заключённым договором с момента акцепта
-- (п. 3 ст. 438 ГК РФ). До сих пор на /register не было ни отметки о принятии
-- Оферты, ни согласия на обработку ПД — доказать, что клиент с ними
-- согласился, было нечем: ни факта, ни даты, ни редакции документа.
--
-- Храним ТРИ вещи, а не одну галочку:
--   • факт и МОМЕНТ акцепта — без даты согласие недоказуемо;
--   • РЕДАКЦИЮ документа — оферта меняется, и через год нужно знать, с какой
--     именно версией согласился человек, а не «с офертой вообще»;
--   • IP — техническое подтверждение обстоятельств акцепта.
--
-- ⚠️ Существующим клиентам НИЧЕГО не проставляем: они акцептовали конклюдентно
-- (фактическим использованием, п. 3.1.5 Оферты), и вписывать им задним числом
-- дату и редакцию, которых они не видели, — это подделка согласия.
-- NULL здесь означает «акцепт получен конклюдентно, отметка не собиралась».
ALTER TABLE clients
    ADD COLUMN IF NOT EXISTS offer_accepted_at        TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS offer_accepted_version   TEXT,
    ADD COLUMN IF NOT EXISTS privacy_consent_at       TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS privacy_consent_version  TEXT,
    ADD COLUMN IF NOT EXISTS acceptance_ip            TEXT;

COMMENT ON COLUMN clients.offer_accepted_at IS
  'Момент акцепта Публичной оферты при регистрации. NULL = акцепт конклюдентными действиями (клиент зарегистрирован до внедрения отметки).';
COMMENT ON COLUMN clients.offer_accepted_version IS
  'Редакция Оферты, действовавшая на момент акцепта (дата в формате YYYY-MM-DD). Нужна, чтобы знать, с какой именно версией согласился клиент.';
COMMENT ON COLUMN clients.privacy_consent_at IS
  'Момент согласия на обработку персональных данных самого клиента (152-ФЗ).';
COMMENT ON COLUMN clients.privacy_consent_version IS
  'Редакция Политики обработки персональных данных на момент согласия.';
COMMENT ON COLUMN clients.acceptance_ip IS
  'IP-адрес, с которого совершён акцепт. Техническое подтверждение обстоятельств.';
