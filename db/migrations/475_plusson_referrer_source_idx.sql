-- 475. Индекс под счётчик «дошли до бота по Плюсоновскому подарку» (20.09.2026).
--
-- ЗАЧЕМ. Ссылки подарка теперь ведут ПРЯМО в боты ПЛЮСОНа, мимо нашего сайта
-- (решение владельца) — забега воронки не возникает, и считать переходы больше
-- нечем. Считаем дошедших до бота: контакты с реф-кодом клиента и меткой
-- подарка. Запрос идёт на КАЖДОЕ открытие страницы лид-магнитов, а `contacts`
-- — одна из самых больших таблиц, так что без индекса это был бы полный
-- проход по ней у каждого клиента.
--
-- ⚠️ Индекс ЧАСТИЧНЫЙ: метка стоит у единиц контактов, и индексировать ради
-- них всю таблицу незачем.

CREATE INDEX IF NOT EXISTS contacts_plusson_ref_source_idx
    ON contacts(plusson_referrer_code, plusson_referrer_source)
    WHERE plusson_referrer_source IS NOT NULL;
