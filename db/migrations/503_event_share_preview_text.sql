-- 503. Текст карточки события при отправке прямой ссылки в мессенджер.
--
-- Когда человек кидает в чат ссылку `pluson.ru/e/{slug}`, мессенджер сам идёт
-- на наш домен за карточкой: картинка + заголовок + подпись. До сих пор в
-- подпись уезжало `events.description`, обрезанное по 200 символов, — а это
-- текст ЛЕНДИНГА: он написан для человека, который уже открыл страницу, и в
-- карточке обрывался на полуслове, нередко посреди HTML-тега.
--
-- Теперь у события есть отдельная короткая подпись именно для карточки.
-- Пусто → берётся зашитое умолчание «Приходи — {дата} "{название}"»
-- (собирается в коде страницы, в базе НЕ дублируется: иначе у каждого
-- события осела бы своя копия формулировки, и поменять её разом стало бы
-- нельзя).
--
-- ⚠️ Поле общее для всех типов событий (`module_slug`): мероприятия,
-- конференции, премии/турниры, конкурсы — карточка у всех строится одним
-- кодом на `/e/{slug}`.

ALTER TABLE events ADD COLUMN IF NOT EXISTS share_preview_text TEXT;

COMMENT ON COLUMN events.share_preview_text IS
  'Подпись под ссылкой события в мессенджере (Telegram/VK/WhatsApp). '
  'Плейсхолдеры {дата} и {название}. Пусто → умолчание из кода.';
