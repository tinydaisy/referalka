-- 480. Своя отметка «внедренцу сообщили за 3 дня».
--
-- ⚠️⚠️ ПОЧЕМУ НЕ ПЕРЕИСПОЛЬЗУЕМ `notified_3d`. Тот флаг ставится после
-- отправки КЛИЕНТУ и только если у клиента привязан чат уведомлений
-- (`notifications_telegram_chat_id IS NOT NULL`). У клиента чата нет — флаг не
-- встанет НИКОГДА, и внедренцу уведомление уходило бы каждый час, пока
-- подписка не кончится.
--
-- Обратная ошибка не менее вредна: если бы внедренец ставил общий флаг, клиент
-- перестал бы получать своё напоминание — за него «уже отметились».
--
-- Поэтому у каждого адресата своя отметка. Так же, как почтовые напоминания
-- живут на отдельных `notified_email_*`.
ALTER TABLE client_subscriptions
    ADD COLUMN IF NOT EXISTS tech_notified_3d BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN client_subscriptions.tech_notified_3d IS
    'Внедренцу сообщили, что подписка кончается через 3 дня. Отдельно от '
    'notified_3d: тот про уведомление КЛИЕНТУ и требует привязанного чата.';

-- ⚠️ Уже истекающим подписям отметку НЕ ставим: пусть внедренец получит
-- предупреждение по тем, кто заканчивается прямо сейчас, — это и есть самые
-- срочные звонки. Разовый всплеск в несколько сообщений лучше, чем тишина.
