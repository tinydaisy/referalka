-- 334: толщина границы кнопки призыва к действию в Mini App
--
-- В настройках (мигр. 333) был только ЦВЕТ границы, а толщины не было —
-- задать «без границы» или сделать её заметнее клиент не мог.
--
-- ⚠️ Отдельной миграцией, а не правкой 333: та уже накачена на прод, и менять
-- накаченную миграцию нельзя — учёт разъедется.
--
-- 0 = границы нет. По умолчанию 1 px — ровно как было захардкожено в кнопке,
-- чтобы у включивших тему вид не изменился сам по себе.
ALTER TABLE clients
  ADD COLUMN IF NOT EXISTS ma_cta_border_w INTEGER NOT NULL DEFAULT 1;

COMMENT ON COLUMN clients.ma_cta_border_w IS
  'Mini App: толщина границы кнопки действия, px. 0 — без границы.';
