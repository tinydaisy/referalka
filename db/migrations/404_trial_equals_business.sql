-- 404. Триал = БИЗНЕС (а не Профи) + Коллабораторная.
--
-- ⚠️⚠️ ОТМЕНЯЕТ ПРЕЖНЕЕ ПРАВИЛО «триал = pro» (решение владельца 11.09.2026).
-- Триал — это витрина платформы: человек должен увидеть ВСЁ, за что потом
-- платит, включая анкеты, приём оплаты, дашборды, продукты и партнёрку. На
-- Профи половина разделов стояла под замком, и попробовать их было нельзя —
-- то есть триал не показывал того, что продаёт.
--
-- Живой случай, с которого это вскрылось: у клиента 176 (триал) решение 10
-- «Розыгрыш через анкету» просило Экстру, потому что `surveys` в триал не
-- входили.
--
-- ⚠️ Даём Бизнес ЦЕЛИКОМ, вместе с `products` и `partner_program` — ими тариф
-- и отличается, и прятать их от пробующего бессмысленно.
--
-- ⚠️⚠️ КОЛЛАБОРАТОРНАЯ ВЫДАЁТСЯ ТОЖЕ, хотя это МОДУЛЬ-АДДОН, а не часть
-- тарифа. Обычно её покупают отдельно (`client_addons`), но на триале человек
-- должен пощупать и её. Поэтому строка в `tariff_features` — по ней
-- `_CLIENT_FEATURES_SQL` отдаёт фичу так же, как из купленного модуля.
--
-- ⚠️ Обратной стороны нет: после триала фичи гаснут сами — расчёт идёт по
-- активной подписке, и купивший Профи увидит ровно Профи.

-- Всё, что есть у Бизнеса.
INSERT INTO tariff_features (tariff_id, feature_id)
SELECT (SELECT id FROM tariffs WHERE slug = 'trial'), tf.feature_id
  FROM tariff_features tf
  JOIN tariffs t ON t.id = tf.tariff_id
 WHERE t.slug = 'business_beta'
ON CONFLICT DO NOTHING;

-- Плюс Коллабораторная — модуль, в тарифы не входящий.
INSERT INTO tariff_features (tariff_id, feature_id)
SELECT (SELECT id FROM tariffs WHERE slug = 'trial'), f.id
  FROM features f
 WHERE f.slug = 'collab_hub'
ON CONFLICT DO NOTHING;
