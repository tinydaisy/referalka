-- 501. Генератор афиш — открыть тарифам «Экстра» (vip) и «Бизнес Beta»
--
-- Было (миграция 436, 18.09.2026): фича `poster_generator` выдана ТОЛЬКО
-- скрытому тарифу `admin` — «делай пока у админов», возможность не обкатана
-- на живых событиях.
--
-- Стало (решение владельца 23.09.2026): обкатали, открываем клиентам —
-- но не всем, а старшим тарифам: «Экстра» (`vip`) и «Бизнес Beta»
-- (`business_beta`). Генератор собирает афишу сам, включая индивидуальные
-- афиши каждому спикеру: это тяжёлая возможность (headless Chrome на каждую
-- картинку) и заметная разница между тарифами.
--
-- ⚠️ ПРАВОК КОДА НЕ НУЖНО — и в этом был смысл гейта по ФИЧЕ, а не по
-- `client_id`. `_guard` в `event_posters_gen.py` и подвкладка в кабинете
-- читают фичу из тарифа: добавили строку — возможность появилась.
--
-- ⚠️ Профи (`pro`) НЕ получает: генератор — разница между тарифами, ради
-- которой старший и берут.

BEGIN;

INSERT INTO tariff_features (tariff_id, feature_id)
SELECT t.id, f.id
  FROM tariffs t
  CROSS JOIN features f
 WHERE t.slug IN ('vip', 'business_beta') AND f.slug = 'poster_generator'
ON CONFLICT DO NOTHING;

-- ⚠️⚠️ ТРИАЛ — ЯВНОЙ СТРОКОЙ, А НЕ «САМ ПОДТЯНЕТСЯ». Миграция 404 сделала
-- триал равным Бизнесу, но РАЗОВЫМ переносом: она скопировала фичи, какие
-- были на тот день, и с тех пор каждую новую надо добавлять триалу отдельно.
-- Не добавить — и правило «в триале клиент видит всё, что покупает» тихо
-- перестаёт действовать именно на новых возможностях, то есть на самых
-- заметных. Отсюда же правило проекта: новая фича = ЧЕТЫРЕ места со списками
-- тарифов, и триал — одно из них.
INSERT INTO tariff_features (tariff_id, feature_id)
SELECT t.id, f.id
  FROM tariffs t
  CROSS JOIN features f
 WHERE t.slug = 'trial' AND f.slug = 'poster_generator'
ON CONFLICT DO NOTHING;

COMMIT;
