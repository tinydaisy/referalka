-- 086 — collaborators.contact_id обязателен (NOT NULL)
--
-- Зачем. Коллаборатор — это «расширение контакта»: набор полей про человека
-- (фото, должность, регалии, бот-канал, личный TG-аккаунт), которое надевается
-- поверх существующего контакта из общей базы клиента. Без привязки к контакту
-- коллаб — мёртвая запись: ни рассылки слать некуда, ни email/телефон вписать,
-- ни мердж сделать. До этой миграции форма «+ Добавить коллаборатора» в UI
-- разрешала создавать «голую» запись только с именем — теперь это запрещено
-- архитектурно.
--
-- Что делает. Поле collaborators.contact_id (FK на contacts.id) становится
-- NOT NULL. Создание коллаба без существующего contact_id теперь упадёт ошибкой
-- БД. Старая ON DELETE SET NULL остаётся — но фактически больше никогда не
-- сработает (DELETE контакта будет блокировано на уровне приложения).
--
-- Предусловие. На момент применения в обеих БД (dev, prod) не должно быть
-- ни одной записи collaborators с contact_id IS NULL. На проде сирота
-- (id=123, Владислав Хорошилов) удалён вручную до прогона миграции.
-- На dev сирот не было.

ALTER TABLE collaborators
  ALTER COLUMN contact_id SET NOT NULL;
