-- 283: Анкета выдаёт подарок после заполнения (2026-08-12)
--
-- Изначально анкета подарки НЕ выдавала — выдача включалась только со
-- стороны лид-магнита («сначала анкета»). Это покрывает случай «человек
-- пришёл ЗА подарком».
--
-- ⚠️ У клиента обратный сценарий: человек идёт за консультацией, а
-- ИИ-агент обещан НАГРАДОЙ за заполнение. Он не приходит из бота за
-- подарком — открывает ссылку на анкету. Поэтому анкете нужна своя выдача.
--
-- Цикла «анкета выдаёт подарок, который требует эту же анкету» не будет:
-- перед выдачей код проверяет, что подарок не указывает обратно на неё.
ALTER TABLE surveys
    ADD COLUMN IF NOT EXISTS gift_lead_magnet_id INTEGER
        REFERENCES lead_magnets(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS gift_package_id INTEGER
        REFERENCES lead_magnet_packages(id) ON DELETE SET NULL;
