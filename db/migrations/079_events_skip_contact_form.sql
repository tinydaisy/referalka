-- на странице настроек мероприятия / конференции.
--
-- Используется, когда у события НЕ задан внешний лендинг
-- (events.landing_url пуст) и Mini App показывает встроенную форму регистрации
-- от ПЛЮСОНа. Если TRUE — форма регистрации не показывается: клик
-- «Хочу участвовать» создаёт contact + event_participant прямо по tg_id,
-- имя берётся из Telegram. Email / телефон у контакта остаются пустыми.

ALTER TABLE events
    ADD COLUMN IF NOT EXISTS skip_contact_form BOOLEAN NOT NULL DEFAULT FALSE;
