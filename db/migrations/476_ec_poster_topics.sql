-- 476: какие темы спикера показывать на его индивидуальной афише.
--
-- ⚠️⚠️ ЗАЧЕМ. У человека бывает несколько выступлений: у Марго Форбс на
-- iViSiON-9 их ЧЕТЫРЕ — «Открытие Дня» в первый день, «Открытие Дня» во
-- второй, «Как найти свой рычаг узнаваемости…» и «Онлайн-мэтчинг и
-- Коллабораторная». На афишу все четыре не нужны: «Открытие Дня» —
-- техническая строка программы, а не тема для анонса.
--
-- Показывать первую (как было) — неверно: ею как раз и оказывается
-- «Открытие Дня». Показывать все — каша. Значит выбирает клиент
-- (решение владельца 21.09.2026).
--
-- Храним ВЫБРАННЫЕ id сессий. Пустой массив = показывать ВСЕ: так у тех, кто
-- ничего не отмечал, афиши остаются прежними, а не становятся пустыми.
--
-- ⚠️ Привязка к `event_collaborators`, а не к `collaborators`: набор тем свой
-- у каждого события, и отметка «эту показываем» относится к конкретной
-- конференции.

BEGIN;

ALTER TABLE event_collaborators
  ADD COLUMN IF NOT EXISTS poster_session_ids INTEGER[] NOT NULL DEFAULT '{}'::INTEGER[];

COMMENT ON COLUMN event_collaborators.poster_session_ids IS
  'Какие выступления показывать на индивидуальной афише (id из conf_sessions). '
  'Пустой массив — показывать все темы человека';

GRANT SELECT, INSERT, UPDATE, DELETE ON event_collaborators TO plusson;

COMMIT;
