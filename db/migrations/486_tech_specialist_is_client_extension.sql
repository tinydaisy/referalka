-- 486: внедренец — РАСШИРЕНИЕ НАД КЛИЕНТОМ, а не отдельный человек (2026-09-22)
--
-- Решение владельца. Внедренец всегда выбирается из клиентов: кабинет клиента —
-- его же рабочий инструмент, на нём тестовое задание и уроки, и ссылки для
-- приглашений он берёт ИЗ СВОЕГО КЛИЕНТСКОГО кабинета. Значит внедренец — это
-- РОЛЬ клиента, а не второй человек в системе.
--
-- ⚠️⚠️ ЧТО ЭТО ОТМЕНЯЕТ. Прежнее решение (миграция 391) держало внедренца
-- отдельной сущностью со своей почтой и своим паролем — «третий тип входа
-- наравне с клиентом и админом». Оно ОТМЕНЕНО: у одного человека выходило два
-- пароля, две почты и два имени, а второй реф-код (`referral_code`) не работал
-- вовсе. Отдельной таблицы людей больше нет — есть таблица РОЛИ над клиентом.
--
-- ⚠️ Что остаётся своим, внедренческим (и потому таблица не исчезает совсем):
-- ставка премии и её блокировка, «берёт ли новых клиентов», права на материалы
-- и удаление вопросов, четыре поля телеграм-уведомлений о ВЕДОМЫХ клиентах,
-- признак увольнения, последний вход именно внедренцем.
--
-- ⚠️ `last_login_at` НЕ дубль клиентского: у клиента это «когда заходил в свой
-- кабинет», здесь — «когда последний раз работал внедренцем». Слить их значило
-- бы потерять второе.
--
-- ⚠️ `notify_tg_user_id` и соседние тоже НЕ дубли: у клиента уведомления про
-- его собственный кабинет, здесь — про клиентов, которых он ведёт.
--
-- Порядок работ намеренно разнесён на две миграции: здесь только ДОБАВЛЯЕМ
-- связь, дубли дропает 488 — уже после того, как вход переведён на клиентский
-- пароль. Дропни почту с паролем сейчас — и кабинет внедренца ляжет между
-- шагами, потому что вход ищет ровно эти поля.

ALTER TABLE tech_specialists
    ADD COLUMN IF NOT EXISTS client_id INTEGER
        REFERENCES clients(id) ON DELETE RESTRICT;

-- ⚠️ ON DELETE RESTRICT, а не CASCADE и не SET NULL — это и есть запрет удалять
-- клиента, на котором висит внедренец (требование владельца). CASCADE унёс бы
-- вместе с клиентом историю его начислений, SET NULL оставил бы внедренца без
-- человека — запись без почты, имени и пароля, в которую уже не войти.

-- Привязка одна к одному: один клиент — не больше одной записи внедренца.
-- ⚠️ Частичный индекс (WHERE NOT NULL) нужен, пока колонка nullable: строки
-- старой схемы без привязки не должны конфликтовать между собой по NULL.
CREATE UNIQUE INDEX IF NOT EXISTS tech_specialists_client_uniq
    ON tech_specialists (client_id) WHERE client_id IS NOT NULL;

COMMENT ON COLUMN tech_specialists.client_id IS
  'Клиент, которому принадлежит роль внедренца. Здесь живут почта, пароль, имя, '
  'телефон, телеграм и реф-код — в этой таблице их больше нет. '
  'ON DELETE RESTRICT: клиента с внедренцем удалить нельзя.';

COMMENT ON TABLE tech_specialists IS
  'РОЛЬ внедренца над клиентом (миграция 486), а не отдельный человек. '
  'Личные данные и пароль — в clients по client_id. Здесь только то, что '
  'относится к работе внедренцем: ставка премии, права, уведомления о ведомых '
  'клиентах, увольнение.';

-- ⚠️⚠️ GRANT в ТОЙ ЖЕ миграции: миграции накатываются от postgres, роль
-- plusson таблиц не владеет. Новых таблиц здесь нет, но право на изменённую
-- подтверждаем явно — без него API отвечает 500 «permission denied».
GRANT SELECT, INSERT, UPDATE, DELETE ON tech_specialists TO plusson;
GRANT SELECT, INSERT, UPDATE, DELETE ON clients TO plusson;
