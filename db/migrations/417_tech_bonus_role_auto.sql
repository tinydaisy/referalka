-- 417. Тип внедренца определяется РАБОТОЙ, а не отметкой в админке.
--
-- ⚠️⚠️ ЗАЧЕМ. Вес в премии зависит от типа: «со своей сетью» ценнее, чем «на
-- клиентах ПЛЮСОН». Но проставлять тип руками неверно: внедренец типа Б может
-- разово кому-то порекомендовать платформу — это не работа по привлечению, а
-- случайность, и повышать за неё вес нельзя. Наоборот, человек может месяцами
-- системно приводить людей, а галочку ему забыли поставить.
--
-- Решение владельца 16.09.2026: тип считается по ФАКТУ работы — сколько людей
-- ОН ПРИВЁЛ активировалось за месяц. Взял порог — значит работает на
-- привлечение, получает вес типа В. Не взял — вес типа Б.
--
-- ⚠️ Считаем АКТИВАЦИИ, а не приведённых: привести можно и десять человек,
-- которые не дойдут до оплаты. Активация — это доведённый до второй оплаты
-- клиент, то есть работа доделана.

INSERT INTO tech_settings (key, value, note) VALUES
    ('network_role_activations', 6,
     'Сколько СВОИХ активаций в месяц делают внедренца типом В (со своей сетью). '
     'Меньше — тип Б: разовая рекомендация не считается работой по привлечению.')
ON CONFLICT (key) DO NOTHING;

-- ⚠️ Роль вычисляется, но ХРАНИТСЯ: премию делят по состоянию на момент
-- раздачи, а пересчёт на лету менял бы уже начисленное задним числом.
-- Колонка `bonus_role` (миграция 416) остаётся, но теперь её ставит не человек,
-- а задача — поэтому нужен след, когда и почему роль сменилась.
CREATE TABLE IF NOT EXISTS tech_role_history (
    id        SERIAL PRIMARY KEY,
    spec_id   INTEGER NOT NULL REFERENCES tech_specialists(id) ON DELETE CASCADE,
    role      TEXT NOT NULL REFERENCES tech_bonus_weights(role),
    period    TEXT NOT NULL,          -- '2026-09'
    activations INTEGER NOT NULL,     -- сколько своих активаций дало решение
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (spec_id, period)
);

COMMENT ON TABLE tech_role_history IS
    'История смены типа внедренца. Тип считается по числу своих активаций за '
    'месяц (порог — tech_settings.network_role_activations).';

-- ⚠️ Ручная фиксация роли: если владелец хочет закрепить тип независимо от
-- порога (договорённость, испытательный срок), ставит TRUE — задача такого
-- человека не трогает.
ALTER TABLE tech_specialists
    ADD COLUMN IF NOT EXISTS bonus_role_locked BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN tech_specialists.bonus_role_locked IS
    'TRUE — тип зафиксирован вручную, автоматика его не меняет.';

-- ── Допуск к премии ────────────────────────────────────────────────────────
-- ⚠️ Порог нужен ОБОИМ типам: иначе премию получит и тот, кто весь квартал
-- ничего не делал — фонд делится по весам, а вес есть у каждого работающего.
-- Не взял порог — в дележе не участвует, его доля уходит остальным.
--
-- ⚠️ Считаются активации ЛЮБЫХ клиентов, а не только своих: для типа Б своих
-- активаций может не быть вовсе, он работает с базой ПЛЮСОНА — и это его
-- нормальная работа, за которую премия и полагается.
INSERT INTO tech_settings (key, value, note) VALUES
    ('bonus_min_activations', 3,
     'Минимум активаций за квартал для допуска к премии. Меньше — в дележе '
     'фонда не участвует, доля уходит остальным.')
ON CONFLICT (key) DO NOTHING;
