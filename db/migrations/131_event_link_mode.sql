-- 131_event_link_mode.sql (2026-06-10)
-- Тип реф-ссылок события: 'miniapp' (открытие через Mini App) или 'bot'
-- (открытие через бота → воронка события в ЛС с кнопкой «ЗАРЕГИСТРИРОВАТЬСЯ»).
-- Клиент выбирает радиокнопкой в «Публичных ссылках»; выбранный тип отдаётся в
-- кабинет спикера, реф-кабинет участника и материалы для спикеров.
-- Дефолт 'miniapp' — обратная совместимость (как было до этой миграции).

ALTER TABLE events
    ADD COLUMN IF NOT EXISTS link_mode TEXT NOT NULL DEFAULT 'miniapp'
    CHECK (link_mode IN ('miniapp', 'bot'));
