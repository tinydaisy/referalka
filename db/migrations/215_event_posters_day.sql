-- 215: афиши ДНЯ события.
--
-- У события с программой (конференция/турнир) у каждого дня своя афиша: «День 1 —
-- соревновательные эфиры», «ФИНАЛ» и т.п. Раньше афиши были только общие на всё
-- событие, и дневная рассылка («старт дня», «за 2 часа», «за сутки»…) брала общую.
--
-- Живут в той же таблице event_posters — тот же upload, тот же приоритет ориентаций
-- (square > horizontal > vertical), просто с привязкой к дню:
--   day IS NULL — общая афиша события (всё как было; все существующие записи такие);
--   day = N     — афиша дня N (conf_days.day_number).
--
-- Приоритет фото в дневных рассылках (message_builder):
--   1) фото, которое клиент загрузил в сам шаблон рассылки;
--   2) афиша ДНЯ, к которому привязана рассылка;
--   3) общая афиша события.
ALTER TABLE event_posters ADD COLUMN IF NOT EXISTS day INTEGER NULL;

COMMENT ON COLUMN event_posters.day IS
  'Номер дня программы (conf_days.day_number), к которому относится афиша. NULL = общая афиша события.';

-- Выборка афиш дня/общих идёт по (event_id, day) — индекс под неё.
CREATE INDEX IF NOT EXISTS idx_event_posters_event_day ON event_posters (event_id, day, sort, id);
