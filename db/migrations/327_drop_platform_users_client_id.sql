-- 327: удаление platform_users.client_id
--
-- ЗАЧЕМ. Колонка дублировала то, что и так известно через
-- contact_id → contacts.client_id. Два источника правды об одном и том же
-- неминуемо разъехались: на проде нашлись записи, где контакт принадлежит
-- одному клиенту, а его запись platform_users числилась в базе другого
-- (аккаунты заводились для контакта Лилии, а contact_id уехал на контакт
-- Нурии). База такое пропускала: внешний ключ смотрит только на contacts.id
-- и клиента не сверяет.
--
-- Последствия расхождения на живом проде: человек попадал в чужую базу,
-- рассылка уходила ему дважды, у записи по нику было пустое имя — и вместо
-- имени подставлялось слово-заглушка.
--
-- ⚠️ Прежнее ограничение UNIQUE (client_id, platform_slug, platform_user_id)
-- от дублей ЛЮДЕЙ не защищало, вопреки виду. Оно ловит только буквальный
-- повтор той же пары. Реальный случай: у контакта уже был телеграм числом
-- 6125115628, пришла запись того же человека ником @Nurikary — пара свободна,
-- конфликта нет, вставка прошла. Так и родился второй контакт.
-- Настоящая причина дублей — псевдо-запись по нику, не доросшая до числового
-- id; чинится отдельно, ограничением её не закрыть.
--
-- Остаётся UNIQUE (contact_id, platform_slug) — «у контакта одна запись на
-- площадку». Именно она теперь и обслуживает ON CONFLICT во вставках.
--
-- ⚠️ ПОРЯДОК ВЫКАТКИ: сначала код, потом эта миграция. Код, читающий
-- platform_users.client_id, падает с `column "client_id" does not exist` и
-- уносит рассылки, ботов и резолв контактов.
--
-- Перед накатом на проде удалены 2 битые записи (23789, 23790) — дамп снят.
-- Проверка: 297 SQL-запросов кода разобраны на базе без колонки (0 ошибок),
-- 51 переписанный запрос сверен «старый против нового» на данных прода —
-- расхождений 0.

ALTER TABLE platform_users DROP COLUMN IF EXISTS client_id;
