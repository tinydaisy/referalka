-- 394. Формат события: онлайн / офлайн / гибрид (10.09.2026).
--
-- ЗАЧЕМ.
-- До сих пор признака «онлайн или офлайн» у события НЕ БЫЛО вовсе. Были только
-- `events.address` (одно поле, куда пишут либо офлайн-адрес, либо ссылку) и
-- вебинарная комната дня, из которой берётся ссылка на эфир. Из-за этого
-- нельзя было решить, что показывать человеку: кнопку «Смотреть стрим» или
-- «Адрес мероприятия» — и офлайн-события выглядели как онлайн.
--
-- ⚠️⚠️ ПОЧЕМУ ЯВНЫЙ ПЕРЕКЛЮЧАТЕЛЬ, А НЕ «УГАДАТЬ ПО ЗАПОЛНЕННОМУ АДРЕСУ»
-- (решение владельца). Угадывание врёт в обе стороны: у офлайн-события адрес
-- могут вписать позже, чем создадут страницу, — и до этого момента человеку
-- показывалась бы кнопка эфира, которого нет. А в `address` исторически кладут
-- и ссылку на трансляцию: такое событие считалось бы офлайновым и уводило
-- людей на карту по обрывку URL. Формат — это решение организатора, и он
-- должен сказать его прямо.
--
-- ⚠️ Гибрид нужен реально: конференции идут в зале И транслируются. Там обе
-- кнопки осмысленны одновременно, поэтому третье значение, а не флаг.
--
-- ⚠️ ДЕФОЛТ — 'online'. Так работали ВСЕ существующие события: показывалась
-- кнопка эфира. Любой другой дефолт молча изменил бы поведение у полусотни
-- живых событий.

BEGIN;

ALTER TABLE events
    ADD COLUMN IF NOT EXISTS event_format TEXT NOT NULL DEFAULT 'online';

-- Значения проверяем CHECK-ом: набор закрытый и меняется миграцией, а не
-- данными (в отличие от `card_style` и подобных «вкусовых» настроек).
ALTER TABLE events DROP CONSTRAINT IF EXISTS events_event_format_chk;
ALTER TABLE events ADD CONSTRAINT events_event_format_chk
    CHECK (event_format IN ('online', 'offline', 'hybrid'));

COMMENT ON COLUMN events.event_format IS
    'Формат проведения: online (кнопка эфира) | offline (кнопка адреса и карта) | hybrid (обе)';

-- Название кнопки адреса — как у кнопки чата (`chat_button_label`): клиент
-- вправе написать «Как добраться» или «Место встречи» вместо дефолта.
-- NULL = дефолт «Адрес мероприятия», задаётся в коде (не в базе), чтобы
-- поменять формулировку можно было без миграции.
ALTER TABLE events
    ADD COLUMN IF NOT EXISTS address_button_label TEXT;

COMMENT ON COLUMN events.address_button_label IS
    'Свой текст кнопки адреса в меню бота и Mini App. NULL → «Адрес мероприятия»';

COMMIT;
