-- 394. Галочка «Офлайн-событие» + название кнопки адреса (10.09.2026).
--
-- ЗАЧЕМ.
-- Признака «онлайн или офлайн» у события НЕ БЫЛО вовсе. Были только
-- `events.address` (одно поле, куда исторически пишут либо офлайн-адрес, либо
-- ссылку на эфир) и вебинарная комната дня, откуда берётся ссылка эфира.
-- Решить, что показывать человеку — «Смотреть стрим» или «Адрес мероприятия» —
-- было не по чему, и офлайн-события выглядели как онлайн.
--
-- ⚠️⚠️ ЯВНАЯ ГАЛОЧКА, А НЕ ДОГАДКА ПО ЗАПОЛНЕННОМУ АДРЕСУ (решение владельца).
-- Угадывание врёт в обе стороны: адрес вписывают позже, чем собирают страницу —
-- и до этого человек видел бы кнопку эфира, которого нет; а в `address` кладут
-- и ссылку на трансляцию — такое событие сочли бы офлайновым и увели людей на
-- карту по обрывку URL. Формат — решение организатора, он говорит его прямо.
--
-- ⚠️⚠️ БУЛЕВО, А НЕ ПЕРЕЧИСЛЕНИЕ ИЗ ТРЁХ ЗНАЧЕНИЙ (решение владельца 10.09.2026).
-- Сначала было `event_format` с вариантом `hybrid`, но третий пункт заставлял
-- клиента выбирать там, где система решает сама:
--   • разные дни в разных форматах → у дня уже есть галочка
--     `conf_days.has_webinar` («в этот день есть эфир»), по ней и решается
--     кнопка эфира;
--   • офлайн-событие с трансляцией → адрес есть И у дня есть эфир, тогда
--     показываются обе кнопки. Их ровно две, нагромождения не выйдет.
-- Адрес по дням (гипотетически возможный) — редкость, ради которой не стоит
-- уводить настройку в раздел «Вебинары»: искать её там никто не догадается.
--
-- ⚠️ ДЕФОЛТ FALSE — так вели себя ВСЕ существующие события: показывалась
-- кнопка эфира. Любой другой дефолт молча изменил бы поведение у полусотни
-- живых событий.

BEGIN;

ALTER TABLE events
    ADD COLUMN IF NOT EXISTS is_offline BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN events.is_offline IS
    'Офлайн-событие: показываем адрес и карту вместо кнопки эфира. '
    'Адрес берётся из events.address. Смешанный случай отдельным значением не '
    'описывается — эфир решается галочкой дня conf_days.has_webinar';

-- Название кнопки адреса — как у кнопки чата (`chat_button_label`): клиент
-- вправе написать «Как добраться» или «Место встречи» вместо дефолта.
-- NULL = дефолт «Адрес мероприятия», задаётся в коде (не в базе), чтобы
-- поменять формулировку можно было без миграции.
ALTER TABLE events
    ADD COLUMN IF NOT EXISTS address_button_label TEXT;

COMMENT ON COLUMN events.address_button_label IS
    'Свой текст кнопки адреса в меню бота и Mini App. NULL → «Адрес мероприятия»';

COMMIT;
