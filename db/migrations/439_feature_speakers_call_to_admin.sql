-- 439: Фичу speakers_call выдать тарифу «Администратор».
--
-- ⚠️ ИСПРАВЛЕНИЕ миграции 438. Там фича заведена, но НЕ привязана ни к одному
-- тарифу — по замыслу «выдадим точечно через client_addons». На практике этого
-- не хватило: у клиента 1 тариф `admin`, и все 37 его фич приходят именно
-- привязкой к тарифу, а не аддонами. В результате шаблон не видел никто,
-- включая владельца платформы, — то есть обкатать его было нельзя вовсе.
--
-- Теперь: привязываем к `admin` (и только к нему). Остальные тарифы по-прежнему
-- фичи не имеют — шаблон у клиентов не появится, пока его не откроют осознанно
-- (строка в tariff_features нужного тарифа или аддон конкретному клиенту).
--
-- Поля чата спикеров и ссылки входа в зум фичей не закрыты и доступны всем —
-- это обычные настройки события.

INSERT INTO tariff_features (tariff_id, feature_id)
SELECT t.id, f.id
  FROM tariffs t, features f
 WHERE t.slug = 'admin' AND f.slug = 'speakers_call'
ON CONFLICT DO NOTHING;
