-- 405. ТОП рейтинг в рефералке по умолчанию СКРЫТ.
--
-- ⚠️⚠️ МЕНЯЕТСЯ ТОЛЬКО ДЕФОЛТ ДЛЯ НОВЫХ СОБЫТИЙ (решение владельца).
-- Существующие 19 событий, где рейтинг сейчас показывается, НЕ трогаем: у
-- них своё значение уже записано, и массовое отключение убрало бы работающий
-- раздел у чужих клиентов, которые его не выключали. Кому надо — включит
-- галочкой в кабинете.
--
-- Зачем дефолт именно такой: рейтинг «кто сколько привёл» уместен далеко не
-- каждому событию. На консультации, круизе или закрытой встрече публичный
-- список соревнующихся выглядит неуместно, а выключать его руками каждый раз
-- приходилось бы всем.
--
-- ⚠️ Запасное значение в КОДЕ правится отдельно: когда строки настроек нет
-- вовсе, дефолт колонки не участвует — значение берётся из Python
-- (`referral_program.py`, `participants.py`). Там оно тоже переведено в TRUE,
-- иначе у события без настроек рейтинг продолжал бы показываться.

ALTER TABLE event_referral_settings
  ALTER COLUMN hide_rating SET DEFAULT TRUE;

COMMENT ON COLUMN event_referral_settings.hide_rating IS
  'Скрыть ТОП рейтинг в кабинете участника. По умолчанию TRUE (мигр. 405): '
  'рейтинг подходит не каждому событию, включается галочкой при надобности.';
