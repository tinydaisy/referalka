-- 330: материал можно отдавать КНОПКОЙ, а не только ссылкой в тексте
--
-- ЗАЧЕМ. Ссылка внутри абзаца теряется: человек читает текст, доходит до
-- конца и не понимает, куда нажимать. Кнопка под сообщением — привычный
-- способ, по ней просто попасть.
--
-- Настройка своя У КАЖДОГО материала: где-то уместна кнопка (одно действие —
-- «Забрать гайд»), где-то ссылка в тексте (материал упомянут по ходу
-- описания), а иногда нужно и то и другое.

ALTER TABLE lead_magnets
    ADD COLUMN IF NOT EXISTS link_mode   TEXT NOT NULL DEFAULT 'text',
    ADD COLUMN IF NOT EXISTS button_label TEXT;

-- ⚠️ Проверяем значения ограничением: вариант «а что если прилетит мусор»
-- иначе всплывёт при отправке — то есть у человека в мессенджере, а не в
-- кабинете. 'text' — прежнее поведение, поэтому оно и по умолчанию.
ALTER TABLE lead_magnets
    DROP CONSTRAINT IF EXISTS lead_magnets_link_mode_chk;
ALTER TABLE lead_magnets
    ADD CONSTRAINT lead_magnets_link_mode_chk
    CHECK (link_mode IN ('text', 'button', 'both'));

COMMENT ON COLUMN lead_magnets.link_mode IS
    'Как отдавать материал: text — ссылкой в тексте (как было), '
    'button — кнопкой под сообщением, both — и так, и так.';

-- ⚠️ 40 символов — это НЕ круглое число «на глаз», а предел ВКонтакте:
-- проверено живой отправкой, 40 принимает, 41 отвергает («label should be not
-- more than 40 letters»). Telegram берёт и 128, MAX не строже. Берём минимум
-- из трёх площадок — надпись должна доехать везде одинаковой.
COMMENT ON COLUMN lead_magnets.button_label IS
    'Надпись на кнопке, до 40 символов (предел ВКонтакте — самой строгой '
    'площадки). Пусто → берём название материала и режем до 40 с многоточием. '
    'В пакете к надписи спереди добавляется номер: «1. Запись на консультацию».';

-- ── Пакет: общая настройка на все свои материалы ──────────────────────────
--
-- ⚠️ Настройка ПАКЕТА ГЛАВНЕЕ настройки материала (решение владельца). Пакет
-- сказал «кнопками» — кнопками уходит всё, даже то, у чего лично стоит
-- «ссылкой в тексте». Иначе получилась бы каша: часть пунктов кнопками, часть
-- текстом, а нумерация «1, 2, 3» в подписях разъехалась бы со списком.
--
-- NULL = «не задано у пакета» → работает выбор каждого материала. Это и есть
-- поведение существующих пакетов: миграция ничего им не меняет.
ALTER TABLE lead_magnet_packages
    ADD COLUMN IF NOT EXISTS link_mode TEXT;

ALTER TABLE lead_magnet_packages
    DROP CONSTRAINT IF EXISTS lead_magnet_packages_link_mode_chk;
ALTER TABLE lead_magnet_packages
    ADD CONSTRAINT lead_magnet_packages_link_mode_chk
    CHECK (link_mode IS NULL OR link_mode IN ('text', 'button', 'both'));

COMMENT ON COLUMN lead_magnet_packages.link_mode IS
    'Как отдавать ВСЕ материалы пакета: text — ссылками в тексте, '
    'button — кнопками, both — и так, и так. NULL — не задано, '
    'решает настройка каждого материала. Заданное значение ПЕРЕБИВАЕТ её.';
