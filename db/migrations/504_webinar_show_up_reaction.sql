-- 504. Выключатель ПОЛОЖИТЕЛЬНОЙ реакции в вебинарной комнате (23.09.2026)
--
-- ЗАЧЕМ. Выключить можно было только «палец вниз» (`show_down_reaction`), а
-- «Огонь» показывался всегда. Организатору, которому реакции не нужны вовсе,
-- убрать их было нечем: оставалась одинокая кнопка, которую нельзя спрятать.
--
-- ⚠️ ОТДЕЛЬНОЕ ПОЛЕ, а не «show_reactions на обе». Одним флагом пришлось бы
-- ломать уже настроенные комнаты: у тех, кто выключил только «палец вниз»,
-- смысл настройки поменялся бы молча. Пара независимых флагов повторяет то,
-- как это уже устроено, и читается однозначно: выключены оба → блока нет.
--
-- ⚠️ DEFAULT TRUE — как у `show_down_reaction`: поведение существующих комнат
-- не меняется, реакции продолжают показываться, пока их не выключат руками.
--
-- ⚠️ Обе таблицы: `webinar_rooms` — настройка комнаты, `webinar_battles` —
-- слепок настройки на момент запуска баттла (там уже лежит своя копия
-- `show_down_reaction`, и без пары баттл игнорировал бы выключенный «Огонь»).

ALTER TABLE webinar_rooms
    ADD COLUMN IF NOT EXISTS show_up_reaction BOOLEAN NOT NULL DEFAULT TRUE;

ALTER TABLE webinar_battles
    ADD COLUMN IF NOT EXISTS show_up_reaction BOOLEAN NOT NULL DEFAULT TRUE;

COMMENT ON COLUMN webinar_rooms.show_up_reaction IS
  'Показывать ли положительную реакцию («Огонь») зрителям. FALSE вместе с show_down_reaction = блок реакций не показывается вовсе.';

COMMENT ON COLUMN webinar_battles.show_up_reaction IS
  'Слепок настройки комнаты на момент запуска баттла (см. webinar_rooms.show_up_reaction).';
