-- 436: фича `poster_generator` — генератор афиш (миграция 435) пока только у нас.
--
-- ⚠️ ЗАЧЕМ ГЕЙТ. Генератор собирает афишу события сам: фон, сетка спикеров,
-- подписи, логотипы партнёров. Возможность новая и ещё не обкатана на живых
-- событиях — открывать её всем клиентам сразу рано. Решение владельца от
-- 18.09.2026: «делай пока у админов».
--
-- ⚠️ ФИЧА, А НЕ ПРОВЕРКА ПО client_id. Правило проекта: гейтить по фичам,
-- никогда по конкретному клиенту. Захардкоженный id пришлось бы выкапывать из
-- кода в тот день, когда генератор решат открыть клиентам, — а фича включается
-- галочкой в тарифе, без единой правки кода. Той же логикой заведён скрытый
-- тариф `admin` (миграция 164): он существует ровно чтобы не хардкодить.
--
-- ⚠️ Строка НЕ описательная: `client_has_feature('poster_generator')`
-- действительно вызывается в `event_posters_gen.py` и прячет подвкладку в
-- кабинете. Уберёшь проверку — генератор откроется всем.

BEGIN;

INSERT INTO features (slug, name, description, sort)
VALUES ('poster_generator',
        'Генератор афиш события',
        'Афиша конференции собирается сама: фон, сетка спикеров с подписями, '
        'логотипы партнёров, выделение организатора и хедлайнера. Три вида — '
        'горизонтальная, вертикальная и квадратная.',
        85)
ON CONFLICT (slug) DO UPDATE SET name = EXCLUDED.name,
                                 description = EXCLUDED.description;

-- ⚠️ ТОЛЬКО в скрытый тариф `admin`. В публичные тарифы НЕ добавляем — иначе
-- возможность окажется у всех, а решено пока обкатать её у себя.
INSERT INTO tariff_features (tariff_id, feature_id)
SELECT t.id, f.id
  FROM tariffs t
  CROSS JOIN features f
 WHERE t.slug = 'admin' AND f.slug = 'poster_generator'
ON CONFLICT DO NOTHING;

COMMIT;
