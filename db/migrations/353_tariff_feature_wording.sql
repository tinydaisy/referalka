-- 353: Список возможностей в карточках тарифов — вычистить враньё и назвать понятно
--
-- Все строки в карточке тарифа (кабинет /dashboard/subscription и лендинг)
-- рисуются из `features.name` по связям `tariff_features`. То есть подписи —
-- это ДАННЫЕ, а не код: правим здесь, а не в .tsx.
--
-- Что было не так (сверено с прод-базой 06.09.2026):
--
-- 1. «Чаты для рассылок (по одному)» — ВРАНЬЁ. Задумывалось «Профи по одному
--    чату, Экстра безлимит», но по факту ОБЕ фичи привязаны к trial+pro+vip,
--    а `_access_level` проверяет безлимит ПЕРВЫМ — уровень 'one' недостижим ни
--    для кого. В карточке при этом стояли два пункта подряд: «Чаты и группы
--    для рассылок» и «Чаты для рассылок (по одному)», второй противоречил
--    первому. Удаляем фичу совсем; проверено, что на неё нет ни одной ссылки
--    (tariff_features 4 строки — их и снимаем; addon_orders, client_addons,
--    client_price_locks, feature_bundles, tariff_bonus_grants,
--    plusson_bonus_coupons, event_tariffs.bonus_feature_id — пусто).
--
-- 2. «Своё файловое хранилище» — не говорило главного: сколько дают. 15 ГБ
--    берётся из `settings.storage_promo_free_gb` (backend/app/config.py) — это
--    бесплатный объём Cloud.ru, который клиент подключает СВОИМ аккаунтом.
--    ⚠️ Это НЕ наша встроенная квота: она лежит в `clients.storage_quota_bytes`
--    и равна 100 МБ у большинства кабинетов (дефолт колонки — 500 МБ).
--
-- 3. «Платные тарифы мероприятия» — непонятно покупателю: слово «тариф» здесь
--    про билет на событие, а рядом в той же карточке «тариф» означает подписку
--    на ПЛЮСОН. Называем действием, которое человек получает.
--
-- 4. «Лид-магниты» — название сущности, а не пользы. Реально там готовая
--    воронка: человек идёт по ссылке → бот просит подписаться на канал →
--    выдаёт файл → через 30 минут дожимает follow-up'ом. Так и пишем.
--    ⚠️ Отдельной строкой это заводить нельзя — вышло бы два пункта про одно.
--
-- 5. Готовых воронок Mini App в списке не было вовсе, хотя это основа продукта
--    (кабинет участника в Telegram, ВКонтакте и MAX). Заводим строкой.
--
-- ⚠️ `miniapp_funnels` — ОПИСАТЕЛЬНАЯ фича: она ничего не гейтит, `client_has_feature`
--    по ней нигде не вызывается. Это допустимо (список возможностей строится из
--    тех же данных), но при добавлении гейта в код — сначала проверить, что фича
--    действительно должна что-то закрывать.

-- ── 1. Убираем «по одному» ───────────────────────────────────────────────────
DELETE FROM tariff_features
 WHERE feature_id = (SELECT id FROM features WHERE slug = 'broadcast_chats_one');

DELETE FROM features WHERE slug = 'broadcast_chats_one';

-- ── 2-4. Понятные названия ───────────────────────────────────────────────────
UPDATE features SET name = 'Файловое хранилище 15 ГБ'
 WHERE slug = 'own_storage';

UPDATE features SET name = 'Подключение платёжных систем'
 WHERE slug = 'event_tariffs';

UPDATE features SET name = 'Готовая воронка выдачи лид-магнита за подписку'
 WHERE slug = 'lead_magnets';

-- «Свои каналы (брендированный бот)» — слово «каналы» здесь означает бота, а
-- у клиента «канал» — это его Telegram-канал с подписчиками. Плюс «брендированный
-- бот» ничего не говорит человеку, который ещё не знает продукт. Называем прямо.
UPDATE features
   SET name = 'Чат-боты в Telegram, MAX и ВКонтакте',
       description = 'Подключение собственных ботов клиента на трёх площадках'
 WHERE slug = 'channels';

-- Та же формулировка жила в маркетинговых буллетах тарифов на лендинге
-- (`tariffs.bullet_points`) — вычищаем и там, иначе на лендинге и в кабинете
-- одна возможность называлась бы по-разному.
UPDATE tariffs
   SET bullet_points = replace(
         bullet_points::text,
         '"Свои боты и каналы (Telegram, MAX, ВК)"',
         '"Чат-боты в Telegram, MAX и ВКонтакте"')::jsonb
 WHERE bullet_points::text LIKE '%Свои боты и каналы%';

UPDATE tariffs
   SET bullet_points = replace(
         bullet_points::text,
         '"Подключение своих ботов и каналов"',
         '"Чат-боты в Telegram, MAX и ВКонтакте"')::jsonb
 WHERE bullet_points::text LIKE '%Подключение своих ботов и каналов%';

-- ── 5. Готовые воронки Mini App — во все тарифы ──────────────────────────────
INSERT INTO features (slug, name, description)
VALUES ('miniapp_funnels',
        'Готовые воронки Mini App в Telegram, ВКонтакте и MAX',
        'Кабинет участника внутри мессенджера на трёх площадках: регистрация, '
        'программа, подарки за приглашённых друзей. Описательная строка тарифа — '
        'доступ ничем не гейтится.')
ON CONFLICT (slug) DO UPDATE SET name = EXCLUDED.name;

-- Тем же тарифам, у которых есть лид-магниты (trial, pro, vip, admin) — то есть
-- всем. Явный список слагов не пишем: он разъедется при заведении нового тарифа.
INSERT INTO tariff_features (tariff_id, feature_id)
SELECT tf.tariff_id, (SELECT id FROM features WHERE slug = 'miniapp_funnels')
  FROM tariff_features tf
 WHERE tf.feature_id = (SELECT id FROM features WHERE slug = 'lead_magnets')
ON CONFLICT DO NOTHING;

-- ── 6. Строку можно спрятать из карточки, не отбирая саму возможность ────────
--
-- «Участие в конкурсах» просили убрать из списка. Удалить фичу нельзя: `contests`
-- РАБОЧАЯ — по ней в сайдбаре открывается раздел конкурсов, а на проде лежат
-- 5 таких событий. Снять её с тарифов = у клиентов пропадёт пункт меню и доступ
-- к уже созданным конкурсам.
--
-- ⚠️ Поэтому показ и доступ разведены: `hidden_in_card` убирает строку из
-- карточки тарифа, гейт продолжает работать. Через него же прячем всё, что
-- клиенту в списке видеть незачем.
ALTER TABLE features
  ADD COLUMN IF NOT EXISTS hidden_in_card BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN features.hidden_in_card IS
  'TRUE — не показывать строку в карточке тарифа (на лендинге и в кабинете). '
  'На доступ НЕ влияет: гейт по-прежнему решает client_has_feature.';

UPDATE features SET hidden_in_card = TRUE WHERE slug = 'contests';

-- «Автовебинары» — код рабочий (миграция 318: расписание, чат-сценарий,
-- серверный отсчёт), но на проде НИ ОДНОЙ комнаты со `stream_type='auto'` и ни
-- одного расписания. Обещать в тарифе то, что ещё никто не запускал, рано —
-- прячем строку. Доступ у Экстры остаётся: включат, когда проверим на живом.
UPDATE features SET hidden_in_card = TRUE WHERE slug = 'autowebinar';

-- «Фирменный стиль Mini App» — фраза ничего не говорит: непонятно, что именно
-- настраивается. Пишем предметно (цвета и оформление кабинета участника).
UPDATE features SET name = 'Фирменные цвета и оформление приложения'
 WHERE slug = 'miniapp_brand_theme';

-- ── 7. Порядок строк: сначала общее с Профи, потом эксклюзив Экстры ──────────
