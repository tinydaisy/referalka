-- Запрет ссылок в чате вебинара (19.09.2026)
--
-- Зачем: зрители кидают в чат ссылки на свои каналы и «полезные материалы» —
-- уводят аудиторию прямо во время эфира. Организатору нужен выключатель.
--
-- ⚠️ DEFAULT FALSE: галочка выключена, пока её не поставят. У существующих
-- комнат поведение не меняется — иначе на ближайшем эфире у людей молча
-- перестали бы отправляться сообщения, и никто бы не понял почему.
--
-- Ссылки модераторов (владельцы и организаторы события) запрет НЕ трогает:
-- их ссылки — часть эфира (оплата, материалы), и запрещать их бессмысленно.

ALTER TABLE webinar_rooms
    ADD COLUMN IF NOT EXISTS block_links BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN webinar_rooms.block_links IS
    'Запретить зрителям слать ссылки в чат. На организаторов не действует.';

-- ⚠️ GRANT В ТОЙ ЖЕ МИГРАЦИИ: миграции накатываются от postgres, приложение
-- работает под ролью plusson. Колонка добавляется в существующую таблицу,
-- права на неё наследуются от таблицы — но GRANT повторяем явно, чтобы не
-- зависеть от того, выдавались ли они когда-то целиком на таблицу.
GRANT SELECT, INSERT, UPDATE, DELETE ON webinar_rooms TO plusson;
