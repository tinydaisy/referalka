-- 402. Автонастройка Telegram приносит с собой «Готовые решения».
--
-- Кому открыта автонастройка — тому открыт и раздел готовых решений (решение
-- владельца 11.09.2026). Оба раздела про одно: за человека делают настройку,
-- которую он не хочет собирать руками. Дать одно без другого бессмысленно —
-- бот создан, а поставить в него воронку нечем.
--
-- ⚠️⚠️ СВЯЗКОЙ, А НЕ ВТОРОЙ СТРОКОЙ В `tariff_features`. Обе фичи сейчас
-- висят только на `admin`, а живым клиентам автонастройка выдаётся ОТДЕЛЬНЫМ
-- МОДУЛЕМ (`client_addons`) — так она и стоит у клиента 176. Строка в тарифе
-- такого клиента не покрыла бы вовсе: у него тариф `trial`. Связка же
-- действует на оба источника сразу и, главное, работает ДАЛЬШЕ САМА — каждому
-- следующему, кому выдадут автонастройку, решения откроются без ручной выдачи.
--
-- ⚠️ Разворот связок — ОДИН уровень, без рекурсии (`_CLIENT_FEATURES_SQL` в
-- [features.py](backend/app/services/features.py)): `ready_solutions` сама
-- ничего за собой не тянет, цепочки не будет.
--
-- ⚠️ Обратное НЕ верно: у кого есть решения, автонастройка не появляется.
-- Связка односторонняя — это разные по цене вещи (услуга 790 ₽ против
-- раздела), и дарить услугу за раздел нельзя.

INSERT INTO feature_bundles (feature_id, included_feature_id)
SELECT f_auto.id, f_sol.id
  FROM features f_auto, features f_sol
 WHERE f_auto.slug = 'tg_autosetup'
   AND f_sol.slug  = 'ready_solutions'
ON CONFLICT DO NOTHING;

