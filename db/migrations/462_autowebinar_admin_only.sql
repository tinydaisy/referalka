-- 462: Автовебинар — только у админа, пока обкатываем (решение владельца 19.09.2026).
--
-- Было: фича `autowebinar` привязана к ЧЕТЫРЁМ тарифам — `vip`, `admin`,
-- `trial`, `business_beta`. Раздел показывался клиентам как готовый, хотя
-- поведение ещё меняется: во вкладке он теперь и подписан «Автовебинар (бета)».
--
-- Стало: только `admin`. Остальным тарифам фича снимается.
--
-- ⚠️⚠️ ЭТО ОТБИРАЕТ ДОСТУП, А НЕ ДОБАВЛЯЕТ. У клиента на vip/trial/business_beta
-- вкладка «Автовебинар» исчезнет, а уже настроенный автовебинар перестанет быть
-- доступным для правки. Данные при этом НЕ удаляются: `webinar_rooms` со
-- `stream_type='auto'`, расписание (`webinar_auto_schedule`) и сценарий чата
-- остаются в базе нетронутыми — вернуть доступ можно одной строкой INSERT.
--
-- ⚠️ Проверено на проде перед накатом: настроенных автовебинаров у клиентов
-- вне тарифа `admin` нет, то есть отобрать нечего. Если появятся — вернуть
-- тариф в `tariff_features` быстрее, чем восстанавливать настройки.
--
-- ⚠️ Триал НЕ зеркалит vip автоматически: правило «триал = Профи» касается
-- фич, привязанных к `pro`. Здесь `trial` был прописан отдельной строкой,
-- поэтому его и снимаем явно.

BEGIN;

DELETE FROM tariff_features tf
 USING tariffs t, features f
 WHERE tf.tariff_id = t.id
   AND tf.feature_id = f.id
   AND f.slug = 'autowebinar'
   AND t.slug <> 'admin';

-- Страховка: у `admin` фича должна остаться (если её там почему-то нет — добавим).
INSERT INTO tariff_features (tariff_id, feature_id)
SELECT t.id, f.id
  FROM tariffs t, features f
 WHERE t.slug = 'admin' AND f.slug = 'autowebinar'
ON CONFLICT DO NOTHING;

COMMIT;
