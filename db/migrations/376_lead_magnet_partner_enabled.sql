-- 376: Галочка «участвует в партнёрской программе» у лид-магнита
--
-- Зачем. Партнёру в кабинете выдавались ВСЕ лид-магниты клиента подряд —
-- фильтра не было вовсе, в отличие от событий и продуктов, где галочка
-- `partner_enabled` есть с миграции 347. Клиент раздаёт партнёрам не всё:
-- часть подарков — под свои воронки, часть служебная. Показывать их
-- партнёрам значит отдавать наружу то, что клиент не собирался.
--
-- ⚠️ DEFAULT FALSE, как у событий и продуктов: доступ РАЗРЕШАЮТ явно, а не
-- отбирают задним числом. Включить всё существующее было бы ровно тем, чего
-- клиент не просил — раздать партнёрам весь список.

ALTER TABLE lead_magnets
    ADD COLUMN IF NOT EXISTS partner_enabled BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN lead_magnets.partner_enabled IS
    'Лид-магнит участвует в партнёрской программе клиента: партнёр видит его '
    'в своём кабинете и получает на него личную ссылку. FALSE — не показываем.';
