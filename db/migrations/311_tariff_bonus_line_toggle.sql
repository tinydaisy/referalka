-- 311: Показывать строку «Бонус:» на лендинге — по галочке
--
-- Зачем. Автоматическая строка (мигр. 308-310) собирается из настройки
-- тарифа и потому никогда не устаревает. Но клиенту не всегда удобно: в
-- одном тарифе он хочет автотекст, в другом — свою формулировку в описании,
-- со своей вёрсткой и порядком пунктов. Раньше выбора не было, и в карточке
-- получался дубль: автострока плюс написанная руками.
--
-- ⚠️ TRUE по умолчанию: у кого бонус уже настроен, строка как показывалась,
-- так и продолжит — молча прятать её после обновления неправильно.
ALTER TABLE event_tariffs
    ADD COLUMN IF NOT EXISTS bonus_line_auto BOOLEAN NOT NULL DEFAULT TRUE;

COMMENT ON COLUMN event_tariffs.bonus_line_auto IS
  'TRUE = строка «Бонус:» на лендинге собирается автоматически из настройки тарифа. FALSE = клиент пишет её сам в описании тарифа.';
