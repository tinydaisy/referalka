-- 309: Тариф может дарить ТОЛЬКО доступ в ПЛЮСОН, без платного модуля
--
-- Зачем. Миграции 307/308 научили тариф выдавать МОДУЛЬ (Коллабораторная и
-- др.). Но модуль — это наши деньги, и раздавать его могут только тарифы
-- уровня admin. А сам доступ в ПЛЮСОН (триал) выгодно раздавать ВСЕМ
-- клиентам: человек регистрируется под реф-кодом клиента, клиент получает
-- кэшбэк — он сам заинтересован.
--
-- ⚠️ Отдельный флаг, а не «модуль = NULL»: у тарифа без бонуса
-- bonus_feature_id тоже NULL, и отличить «бонуса нет» от «дарим триал»
-- было бы нечем.
--
-- ⚠️ Правило выдачи одно на все случаи: новому — полный триал (база +
-- бонус за реферала, сейчас 30 дней), действующему — 3 дня продления его
-- текущего тарифа (Профи→Профи, Экстра→Экстра, триал→триал).

ALTER TABLE event_tariffs
    ADD COLUMN IF NOT EXISTS bonus_trial BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN event_tariffs.bonus_trial IS
  'TRUE = после оплаты покупателю дарится доступ в ПЛЮСОН (новому — полный триал, действующему — 3 дня продления). Доступен ВСЕМ тарифам клиента, в отличие от bonus_feature_id (модуль — только admin).';

-- У тарифов с модулем триал идёт вместе с ним — проставляем, чтобы не
-- потерять уже настроенное поведение.
UPDATE event_tariffs SET bonus_trial = TRUE WHERE bonus_feature_id IS NOT NULL;

-- ── Комплект «Профи + модуль» ────────────────────────────────────────────
-- Модуль без подписки почти бесполезен: разделы гейтятся фичей, но кабинет
-- живёт по тарифу, и без активной подписки запись всюду закрыта. Поэтому у
-- админа есть выбор, ЧТО именно подарить вместе с модулем: обычный триал
-- или полноценный Профи на тот же срок.
--
-- NULL = как раньше (триал). 'pro' = Профи. Слаг, а не id: тарифы могут
-- пересоздаваться, а слаг стабилен.
ALTER TABLE event_tariffs
    ADD COLUMN IF NOT EXISTS bonus_tariff_slug TEXT;

ALTER TABLE event_tariffs
    DROP CONSTRAINT IF EXISTS event_tariffs_bonus_tariff_chk;
ALTER TABLE event_tariffs
    ADD CONSTRAINT event_tariffs_bonus_tariff_chk
    CHECK (bonus_tariff_slug IS NULL OR bonus_tariff_slug IN ('trial', 'pro'));

COMMENT ON COLUMN event_tariffs.bonus_tariff_slug IS
  'Какой тариф платформы дарим: NULL/trial = триал, pro = Профи (комплект «Профи + модуль»). Выбор только у admin — Профи это наши деньги.';
