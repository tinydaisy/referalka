-- 476. Какие площадки ПЛЮСОНа показываем клиентам (20.09.2026).
-- Настройка платформенная, из админки, ОДНА на все места сразу.
--
-- ЗАЧЕМ.
-- Боты платформы (TG, MAX, ВК) торчат клиенту в трёх разных местах: ссылки
-- Плюсоновского подарка, «Написать в тех.поддержку» и «Партнёрка ПЛЮСОНа».
-- До этой миграции каждое место решало само: подарок смотрел в базу на живой
-- токен бота, поддержка держала список ЗАХАРДКОЖЕННЫМ во фронте, партнёрка
-- склеивала ссылки руками и про ВК не знала вовсе. Отсюда и разнобой: в
-- подарке ВК есть, в партнёрке нет, в поддержке нет.
--
-- Теперь список один и берётся отсюда. Площадка показывается, только если
-- она отмечена ЗДЕСЬ И у ПЛЮСОНа есть на ней живой бот (handle + токен):
-- галочка без бота дала бы битую ссылку, бот без галочки — площадку, которую
-- выключили сознательно.
--
-- ⚠️ ВК выключен СРАЗУ (решение владельца 20.09.2026): бот на площадке не
-- работает, разбираемся позже. Канал и токен не трогаем — вернуть площадку
-- значит поставить галочку в админке, ничего не восстанавливая.

BEGIN;

ALTER TABLE platform_settings
    ADD COLUMN IF NOT EXISTS plusson_platforms TEXT[] NOT NULL
        DEFAULT ARRAY['telegram', 'max']::TEXT[];

-- Допустимы только площадки, на которых у платформы вообще бывают боты.
-- Пустой список разрешён осознанно: это «не показывать ни одной» — на такой
-- случай у каждого места есть запасной путь на сайт платформы.
ALTER TABLE platform_settings DROP CONSTRAINT IF EXISTS platform_settings_plusson_platforms_check;
ALTER TABLE platform_settings
    ADD CONSTRAINT platform_settings_plusson_platforms_check
    CHECK (plusson_platforms <@ ARRAY['telegram', 'max', 'vk']::TEXT[]);

COMMENT ON COLUMN platform_settings.plusson_platforms IS
    'Площадки ПЛЮСОНа, которые показываем клиентам: ссылки Плюсоновского '
    'подарка, тех.поддержка, партнёрская программа. Одна настройка на все '
    'места (services/plusson_platforms.py). Площадка выводится, только если '
    'отмечена здесь И у платформы есть на ней бот с handle и токеном';

-- Существующей строке настроек DEFAULT не достаётся — проставляем явно.
UPDATE platform_settings
   SET plusson_platforms = ARRAY['telegram', 'max']::TEXT[]
 WHERE id = 1;

COMMIT;
