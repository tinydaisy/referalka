-- 343: кому слать письмо о заполненной анкете
--
-- Анкету заполнили — об этом надо узнать сразу, а не при следующем заходе в
-- кабинет. Уведомление в чат уходит ВСЕГДА (решение владельца), а вот письмо
-- нужно не всем: у кабинета бывает несколько помощников, и заваливать письмами
-- тех, кто заявки не обрабатывает, незачем.
--
-- ⚠️ NULL — это НЕ «никому», а «по умолчанию»: владелец кабинета + помощники
-- с ролью «менеджер заказов» (`assistant_grants.access_level='orders'`) — им
-- заявки и отдают. Пустой массив `{}` — осознанное «письма не слать вовсе».
-- Различать эти два состояния обязательно: иначе у всех существующих анкет,
-- где настройку никто не открывал, письма не уходили бы никому.
--
-- ⚠️ Храним ПОЧТЫ, а не id помощников: помощника могут отозвать из кабинета,
-- и ссылка на несуществующий пропуск оставила бы настройку битой. Список
-- фильтруется при отправке по актуальным получателям — почта, которой больше
-- нет среди владельца и помощников, просто пропускается.
ALTER TABLE surveys ADD COLUMN IF NOT EXISTS notify_emails TEXT[];
