-- 453: промежуток между фото на афише — ОТДЕЛЬНО по горизонтали и вертикали.
--
-- ⚠️ ЗАЧЕМ. Был один `gap` на оба направления. Но между СТОЛБЦАМИ и между
-- РЯДАМИ нужны разные расстояния: под фото идёт подпись в две строки, и
-- вертикальный промежуток визуально складывается с ней — ряды расходятся
-- сильнее, чем задумано. Уменьшить общий `gap` нельзя: тогда слипнутся
-- столбцы.
--
-- ⚠️ `gap` ОСТАЁТСЯ как промежуток по горизонтали (между столбцами) — так
-- сохранились уже настроенные макеты. Новое поле отвечает за вертикаль; пусто
-- (NULL) — берём `gap`, то есть поведение как было.

BEGIN;

ALTER TABLE event_poster_layouts
  ADD COLUMN IF NOT EXISTS gap_y NUMERIC(5,2)
      CHECK (gap_y IS NULL OR gap_y BETWEEN 0 AND 20);

COMMENT ON COLUMN event_poster_layouts.gap IS
  'Промежуток между фото ПО ГОРИЗОНТАЛИ (между столбцами), % ширины области';
COMMENT ON COLUMN event_poster_layouts.gap_y IS
  'Промежуток между РЯДАМИ, % ширины области. NULL = как по горизонтали';

GRANT SELECT, INSERT, UPDATE, DELETE ON event_poster_layouts TO plusson;

COMMIT;
