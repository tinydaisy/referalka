-- ─────────────────────────────────────────────────────────────────────────────
-- 352. Блок «Анкета» на лендинге: анкета прямо на странице (2026-09-05)
-- ─────────────────────────────────────────────────────────────────────────────
--
-- ЗАЧЕМ. Собрать заявку прямо на странице — человек оставляет контакты, а
-- клиент связывается сам. Раньше единственным действием на лендинге была
-- оплата тарифа, и всё, что продаётся разговором, оставалось без кнопки.
--
-- ⚠️⚠️ СЕКЦИЯ САМОСТОЯТЕЛЬНАЯ И С ТАРИФАМИ НЕ СВЯЗАНА — ни кодом, ни правилом
-- показа. Её ставят ВМЕСТЕ с тарифами (цены на странице есть, а внизу
-- «остались вопросы — оставьте заявку») и БЕЗ них (наставничество,
-- консультация, услуга «под задачу», где цены нет вовсе — тогда блок «Тарифы»
-- просто выключают галочкой). Связку «анкета вместо тарифов» не заводить:
-- какие секции показывать, решает клиент, а не код.
--
-- ⚠️⚠️ ОТДЕЛЬНОЙ СУЩНОСТИ «ЗАЯВКА» НЕТ И НЕ НУЖНО. Заявка — это анкета из
-- двух-трёх вопросов, и весь механизм под неё уже построен: обработка
-- («Обработано» + заметка), счётчик необработанных в трёх местах, уведомление
-- в чат и на почту, таблица заявок с фильтрами, CRM-колонки, дашборды,
-- выгрузка. Заводить рядом вторую систему сбора ответов значило бы чинить
-- каждую из этих вещей дважды.
--
-- ⚠️ НУЛЕВОЙ ЗАКАЗ (`product_orders`) ДЛЯ ЗАЯВКИ НЕ ПОДХОДИТ, хотя мысль
-- напрашивается. Три причины, каждой достаточно:
--   1. `product_orders.tariff_id` — NOT NULL. Пришлось бы завести тариф-пустышку
--      «Заявка» ценой 0, то есть ровно ту сущность, от которой уходим.
--   2. `UNIQUE (contact_id, tariff_id)` — второй раз тот же человек заявку
--      оставить не смог бы, форма молча ничего не сделала бы.
--   3. Бесплатный тариф у продукта заказа НЕ создаёт вовсе (см. product_orders.py)
--      — доступ выдаётся сразу. Нулевой заказ противоречит уже принятому решению,
--      и заявки перемешались бы с настоящими покупателями во вкладке «Клиенты».
--
-- ⚠️ Заявка НИЧЕГО НЕ ОТКРЫВАЕТ человеку: ни кабинета, ни материалов, ни
-- доступа. Только контакт в базе клиента и уведомление ему. Это и есть разница
-- между «оставил заявку» и «купил».
--
-- ⚠️ Колонки живут в `event_landing_blocks` — таблица общая для события и
-- продукта с миграции 293 (полиморфный лендинг). Блок появляется у обоих: у
-- события анкета тоже нужна (заявка на участие, сбор вопросов спикеру).
-- ─────────────────────────────────────────────────────────────────────────────

ALTER TABLE event_landing_blocks
    -- Какую анкету показывает блок. NULL = анкета не выбрана: конструктор
    -- показывает подсказку «выберите анкету», публичная страница блок пропускает
    -- (пустая форма без вопросов бесполезна и выглядит как поломка).
    --
    -- ⚠️ ON DELETE SET NULL, а не CASCADE: удаление анкеты не должно уносить
    -- блок вместе с его оформлением, заголовком и местом в порядке секций.
    -- Клиент выберет другую анкету, а до тех пор блок просто не рисуется.
    ADD COLUMN IF NOT EXISTS survey_id INTEGER
        REFERENCES surveys(id) ON DELETE SET NULL,

    -- Как показывать: 'form' — все вопросы сразу списком (привычная форма),
    -- 'quiz' — по одному вопросу с прогрессом «Шаг 2 из 5».
    --
    -- ⚠️ Это ТОЛЬКО СПОСОБ ПОКАЗА, а не второй тип анкеты. Вопросы, ответы,
    -- обработка и аналитика — те же самые. Квиз потому и не отдельная сущность:
    -- разница между ним и формой целиком в вёрстке.
    --
    -- ⚠️ Значение проверяется в коде (`normalize_block_survey`), а не CHECK-ом:
    -- так новый вид показа добавляется кодом, без миграции — как у
    -- `title_align`, `card_style` и `btn_width`. Мусор приводится к 'form',
    -- а не роняет запрос.
    ADD COLUMN IF NOT EXISTS survey_view TEXT;

CREATE INDEX IF NOT EXISTS idx_event_landing_blocks_survey
    ON event_landing_blocks(survey_id) WHERE survey_id IS NOT NULL;

COMMENT ON COLUMN event_landing_blocks.survey_id IS
    'Блок kind=survey: какая анкета показывается на лендинге. NULL — не выбрана, блок не рисуется.';
COMMENT ON COLUMN event_landing_blocks.survey_view IS
    'Как показывать анкету: form (всё сразу) | quiz (по одному вопросу). NULL = form.';
