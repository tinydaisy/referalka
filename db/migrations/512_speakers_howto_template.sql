-- 512. Рассылка «Инструкция по подключению» в чат спикеров (24.09.2026)
--
-- ЗАЧЕМ. В день эфира спикеру нужны ровно две ссылки, и они РАЗНЫЕ: в Zoom он
-- заходит сам выступать (там демонстрация экрана), а вебинарную комнату
-- открывает с телефона, чтобы читать комментарии зрителей. Организатор
-- пересылал это руками каждому — теперь уходит в чат спикеров само и встаёт
-- в закреп.
--
-- ⚠️ ОТДЕЛЬНО от «Программы дня» (`speakers_day`), хотя уходит следом за ней.
-- Одним сообщением нельзя: программа нужна НАКАНУНЕ («во сколько я завтра»),
-- а инструкция — в ДЕНЬ эфира, и закреплять надо обе. Слепив их, пришлось бы
-- выбирать одно время и один закреп.
--
-- ⚠️ Тип попал и в `message_builder.DAY_TYPES` — это ДНЕВНАЯ рассылка (на день
-- целиком, конкретного спикера в ней нет). Без этого шаблон существовал бы как
-- запись, но при отправке не попадал ни в одну ветку сборки, и плейсхолдеры
-- ушли бы в чат сырыми.
--
-- ⚠️ `audience_exclude = 'all_event'` — НЕ опечатка: он обнуляет список
-- получателей, участникам сообщение не уходит вовсе. Доставка идёт только по
-- `send_to_speakers_chat`, как у остальных шаблонов этой группы (миграция 442).
--
-- ⚠️ for_event = FALSE: у обычного мероприятия нет ни программы по дням, ни
-- отдельной зум-ссылки для спикеров — инструкции там неоткуда взяться.
--
-- ПЛЕЙСХОЛДЕРЫ: {speaker_join_url} — вход СПИКЕРА в Zoom этого дня
-- (`webinar_rooms.speaker_join_url`, миграция 433); {stream_url} — вебинарная
-- комната дня (зрительская); {day_speakers_mentions} — «@ivan @petr», чтобы
-- спикерам пришло уведомление и инструкция не потерялась в чате. Любой из них
-- пуст → строка убирается целиком: «Ссылка на ZOOM:» без адреса хуже, чем
-- ничего.
--
-- ОТКАТ: DELETE FROM default_broadcast_templates WHERE type = 'speakers_howto';
--        (у клиентов шаблон останется — он их, правленный, и сносить его нельзя)

BEGIN;

INSERT INTO default_broadcast_templates
  (type, name, subject, text,
   schedule_mode, offset_minutes, audience_include, audience_exclude,
   allow_custom_datetime, for_event, for_conference, for_turnir,
   autoseed, multi_instance, send_to_speakers_chat, pin_in_chat,
   turnir_name, sort_order)
VALUES (
  'speakers_howto',
  'Спикерам: инструкция по подключению (в чат спикеров)',
  NULL,
  '<b>ИНСТРУКЦИЯ ПО ПОДКЛЮЧЕНИЮ К ТРАНСЛЯЦИИ</b>' || E'\n\n' ||
  'Ссылки в закреп в день конференции' || E'\n\n' ||
  '<b>1) Ссылка на ZOOM:</b>' || E'\n' ||
  '{speaker_join_url}' || E'\n\n' ||
  'Сюда заходите за 10 минут до своего выступления и ведёте выступление отсюда — будет доступ к демонстрации экрана' || E'\n\n' ||
  '<b>2) Ссылка на вебинарную комнату:</b>' || E'\n' ||
  '{stream_url}' || E'\n\n' ||
  'Заходите сюда с телефона (выключаете звук, чтобы не фонило) и читаете комментарии зрителей' || E'\n\n' ||
  '—' || E'\n\n' ||
  'Итого: выступление ведёте в зуме со мной' || E'\n\n' ||
  'Зрители и комментарии — в чате вебинарной комнаты' || E'\n\n' ||
  'Задержка 10 секунд — поэтому не пугайтесь тишины в ответ, не ждите долго ответов' || E'\n\n' ||
  'Общайтесь с аудиторией: если им не задавать вопросы, она будет молчать' || E'\n\n' ||
  '{day_speakers_mentions}',
  'fixed_offset',
  -- Точка отсчёта — старт дня. 1439 = сутки минус минута: на минуту ПОЗЖЕ
  -- «Программы дня» (1440), чтобы в чат сначала пришло «во сколько я», а потом
  -- «куда заходить». Обратный порядок читается как инструкция в пустоту.
  1439,
  'all_event',       -- не используется: рассылка идёт только в чат
  'all_event',       -- ← обнуляет список получателей: участникам НЕ уходит
  FALSE,             -- allow_custom_datetime
  FALSE,             -- for_event    — у мероприятия нет программы по дням
  TRUE,              -- for_conference
  TRUE,              -- for_turnir
  TRUE,              -- autoseed
  FALSE,             -- multi_instance
  TRUE,              -- send_to_speakers_chat
  TRUE,              -- pin_in_chat — ссылки нужны команде весь день
  'Спикерам/номинантам: инструкция по подключению (в чат)',
  -- Сразу после «Программы дня» (246): в кабинете они идут парой.
  247
)
ON CONFLICT (type) DO NOTHING;

-- ── Проверка ─────────────────────────────────────────────────────────────
DO $$
DECLARE cnt INTEGER;
BEGIN
    SELECT count(*) INTO cnt
      FROM default_broadcast_templates
     WHERE type = 'speakers_howto'
       AND send_to_speakers_chat = TRUE
       AND audience_exclude = 'all_event';
    IF cnt <> 1 THEN
        RAISE EXCEPTION 'Шаблон speakers_howto не заведён как надо (найдено: %)', cnt;
    END IF;
END $$;

COMMIT;
