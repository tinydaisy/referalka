-- 386: ширина колонки ШАПКИ по умолчанию — 100%
--
-- Зачем. `split_ratio` создавалась под ПРОПОРЦИЮ двух колонок обычной секции,
-- отсюда умолчание 50. Но у шапки то же поле означает ширину колонки с
-- текстом, и 50% там означало «текст в половину экрана»: длинный заголовок
-- рвался посреди слова («КОНФЕРЕН / ЦИЯ»), а почему — из интерфейса понять
-- было нельзя.
--
-- Решение владельца: у шапки колонка по умолчанию во всю полосу при ЛЮБОМ
-- положении текста (слева, справа, по центру), а сузить её можно ползунком.
--
-- ⚠️ Колонка NOT NULL, поэтому фолбэк в коде (`split_ratio || 100`) сам по
-- себе не работает: в строках всегда есть число. Поэтому правим уже созданные
-- шапки, а новым значение проставляет код при создании блока.
--
-- ⚠️ УМОЛЧАНИЕ КОЛОНКИ (50) НЕ ТРОГАЕМ. Оно общее на всю таблицу, а у обычной
-- секции 50% — верная пропорция двух колонок: подмени его на 100, и у каждой
-- новой двухколоночной секции второй колонке не осталось бы места. Тип блока
-- знает только код — там и решаем (event_landing.py, создание блока).
--
-- ⚠️ Правим ТОЛЬКО значение 50 — это умолчание базы, его никто не выбирал.
-- Осознанно выставленные значения (на проде одно такое, 44%) не трогаем:
-- человек сузил колонку под свою обложку, и вернуть ему 100% значило бы
-- сломать собранную страницу.

UPDATE event_landing_blocks
   SET split_ratio = 100, updated_at = NOW()
 WHERE kind = 'hero' AND split_ratio = 50;

COMMENT ON COLUMN event_landing_blocks.split_ratio IS
  'Ширина колонки в % : у шапки — колонка с текстом (по умолчанию 100), у обычной секции — пропорция двух колонок';
