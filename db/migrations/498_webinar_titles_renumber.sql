-- 498: Перенумеровать названия вебинарных комнат по ДАТАМ.
--
-- ⚠️⚠️ ИСПРАВЛЕНИЕ МИГРАЦИИ 469. Там названия «День N — …» заполнились, но
-- номер считался по порядку, в котором комнаты лежали в выборке, а дни БЕЗ
-- ДАТЫ при этом оказывались впереди датированных. У события 89 день без даты
-- получил «День 1», а ближайший эфир 24 сентября (day_number=1, первый по
-- календарю) подписался «День 2» — владелец увидел это в кабинете 23.09.2026.
--
-- Правильный порядок: сначала дни С ДАТОЙ по возрастанию, дни без даты —
-- в конец (NULLS LAST), между собой по day_number. Ровно так же сортируются
-- вкладки дней и считается `day_index` в API после правки от 19.09.2026.
--
-- ⚠️ ТРОГАЕМ ТОЛЬКО АВТОМАТИЧЕСКИЕ названия вида «День N — …» (регулярка).
-- Вписанные руками («Орг встреча», «День 1 - Соревновательные эфиры» через
-- дефис, а не тире) не перезаписываем: человек указал их осознанно.
--
-- ⚠️ Название события берём ТЕКУЩЕЕ из `events.title`: если его переименовали
-- после 469, в комнатах осталось старое — заодно освежаем.

BEGIN;

WITH numbered AS (
    SELECT wr.id,
           e.title AS ev_title,
           ROW_NUMBER() OVER (
               PARTITION BY wr.event_id
               ORDER BY cd.day_date NULLS LAST, wr.day_number
           ) AS day_index
      FROM webinar_rooms wr
      JOIN events e ON e.id = wr.event_id
      LEFT JOIN conf_days cd
             ON cd.event_id = wr.event_id AND cd.day_number = wr.day_number
     WHERE wr.title ~ '^День [0-9]+ — '
)
UPDATE webinar_rooms wr
   SET title = 'День ' || n.day_index || ' — ' || n.ev_title,
       updated_at = NOW()
  FROM numbered n
 WHERE wr.id = n.id;

COMMIT;
