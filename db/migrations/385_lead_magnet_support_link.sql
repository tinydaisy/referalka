-- 385. Лид-магнит может вести в СЛУЖБУ ЗАБОТЫ клиента, а не на фиксированный
-- адрес (09.09.2026).
--
-- ЗАЧЕМ.
-- Типовая воронка «запись на консультацию» заканчивается тем, что человек
-- пишет владельцу. Раньше в `lead_magnets.url` вбивали одну ссылку руками —
-- обычно телеграмную. Из-за этого:
--   • пришедший из ВКонтакте или MAX получал ссылку в Telegram, где его нет;
--   • при смене контакта поддержки ссылку приходилось править в каждом
--     лид-магните вручную, и они разъезжались.
--
-- Теперь у лид-магнита есть ИСТОЧНИК ссылки:
--   fixed   — как было: адрес из `url` (файл, лендинг, что угодно);
--   support — служба заботы клиента, РЕЗОЛВИТСЯ ПО ПЛОЩАДКЕ человека.
--
-- ⚠️ Резолв уже написан и переиспользуется, своего не заводим:
-- `support_url_for_platform` в app/services/support_message.py — из Telegram
-- ведёт в Telegram (`clients.work_tg_username`), из ВКонтакте в ВКонтакте
-- (`work_vk`), из MAX в MAX (`work_max`). Нет контакта на площадке — ссылки
-- нет, и строка с ней просто не показывается.
--
-- ⚠️ ТЕКСТ СООБЩЕНИЯ ПОДСТАВЛЯЕТСЯ ТОЛЬКО В TELEGRAM. Проверено по коду и
-- документации площадок: `t.me/ник?text=…` заполняет поле ввода, а у ВКонтакте
-- (`vk.me/…?ref=`) и MAX (`max.ru/…?start=`) параметр служебный — его читает
-- БОТ СООБЩЕСТВА, и текстом сообщения он не становится. Поэтому кодовое слово
-- дописывается к телеграмной ссылке, а на других площадках человек пишет сам.

BEGIN;

ALTER TABLE lead_magnets
    ADD COLUMN IF NOT EXISTS link_source TEXT NOT NULL DEFAULT 'fixed',
    -- Кодовое слово, которое подставится в поле ввода Telegram. Без пробелов:
    -- пробел в адресе ломает ссылку, поэтому слова соединяют подчёркиванием.
    ADD COLUMN IF NOT EXISTS support_prefill TEXT;

-- ⚠️ Значения проверяем ограничением, а не только кодом: колонка попадает в
-- выдачу воронки, и мусор в ней означал бы ссылку в никуда у живого человека.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conrelid = 'lead_magnets'::regclass
           AND conname = 'lead_magnets_link_source_check'
    ) THEN
        ALTER TABLE lead_magnets
            ADD CONSTRAINT lead_magnets_link_source_check
            CHECK (link_source IN ('fixed', 'support'));
    END IF;
END $$;

COMMENT ON COLUMN lead_magnets.link_source IS
    'fixed — ссылка из url; support — служба заботы клиента, по площадке человека';
COMMENT ON COLUMN lead_magnets.support_prefill IS
    'Кодовое слово в поле ввода. Работает ТОЛЬКО в Telegram: у ВК и MAX параметр ссылки читает бот, текстом он не становится';

COMMIT;
