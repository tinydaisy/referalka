-- 398. Координаты места проведения (10.09.2026).
--
-- ЗАЧЕМ.
-- Карта на лендинге и в Mini App искала место ПО ТЕКСТУ адреса
-- (`yandex.ru/map-widget/v1/?text=…`). Виджет при таком запросе показывает
-- нужный район, но **метку не ставит** — человек видит карту без указателя и
-- не понимает, куда именно ехать; метка появляется, только если он сам нажмёт
-- на строку поиска. На скриншотах клиента это выглядело как «карта не
-- работает».
--
-- ⚠️ Координаты БЕРУТСЯ ДАРОМ: их и так отдаёт DaData вместе с подсказкой
-- адреса (`geo_lat` / `geo_lon`) — мы их просто выбрасывали. Отдельного
-- запроса к геокодеру не нужно, лимит не тратится.
--
-- ⚠️ ПОЧЕМУ НЕ СЧИТАТЬ КООРДИНАТЫ НА ЛЕТУ при показе страницы: это запрос во
-- внешний сервис на КАЖДЫЙ просмотр лендинга — лишняя точка отказа и трата
-- суточного лимита на посетителей. Адрес меняют раз в жизни события, координаты
-- к нему — тоже.
--
-- ⚠️ NULL — НОРМА, а не ошибка. Адрес могли вписать руками, не выбирая из
-- подсказок (площадки, которой нет в справочнике: коворкинг в новом здании,
-- база отдыха). Тогда карта работает по-старому — ищет по тексту. Поэтому
-- координаты НЕ обязательны и ничего не блокируют.

BEGIN;

ALTER TABLE events
    ADD COLUMN IF NOT EXISTS geo_lat DOUBLE PRECISION,
    ADD COLUMN IF NOT EXISTS geo_lon DOUBLE PRECISION;

COMMENT ON COLUMN events.geo_lat IS
    'Широта места проведения — из подсказки DaData при вводе адреса. '
    'NULL = адрес вписан руками, карта ищет по тексту (метки не будет)';
COMMENT ON COLUMN events.geo_lon IS
    'Долгота места проведения — см. events.geo_lat';

COMMIT;
