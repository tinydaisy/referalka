-- 273: Точка фокуса фоновой картинки страницы — отдельно для десктопа и телефона.
--
-- ⚠️ Зачем. Фон выводится с object-cover и центрируется: картинка заполняет
-- экран, лишнее обрезается по краям. На широком мониторе видно всё, а на узком
-- экране телефона обрезаются именно БОКА — и смысловой объект, стоящий сбоку
-- (человек, предмет, логотип), уходит за край. На обложке с медитирующим
-- человеком справа его на телефоне просто не видно.
--
-- Значение — то же, что у CSS object-position: проценты по горизонтали и
-- вертикали, «50% 50%» = центр (прежнее поведение).
--
-- Два поля, а не одно: на десктопе кадр обычно нужен как есть, а на телефоне
-- фокус смещают к объекту. Одно общее поле заставило бы выбирать что-то одно.

ALTER TABLE event_landing_pages
  ADD COLUMN IF NOT EXISTS bg_position        TEXT,  -- десктоп, напр. '50% 50%'
  ADD COLUMN IF NOT EXISTS bg_position_mobile TEXT;  -- телефон, напр. '75% 50%'

GRANT SELECT, INSERT, UPDATE, DELETE ON event_landing_pages TO plusson;
