-- 409: Квота хранилища по умолчанию — 100 МБ, а не 500 МБ.
--
-- Расхождение в данных. Всем действующим клиентам когда-то проставили 100 МБ
-- вручную, а УМОЛЧАНИЕ КОЛОНКИ поправить забыли — там оставалось 500 МБ. В коде
-- регистрации квота не задаётся вовсе, поэтому каждый новый кабинет молча
-- получал впятеро больше положенного. На проде так набралось 10 кабинетов,
-- зарегистрированных с 24.08.2026 (включая клиента 176).
--
-- ⚠️ Выравниваем ТОЛЬКО тех, у кого ровно 500 МБ — то есть кому квота досталась
-- умолчанием. Всё, что выдано осознанно (у клиентов 1 и 3 — по 10 ГБ), не
-- трогаем: это ручное решение, а не побочный эффект.
--
-- ⚠️ Понижение безопасно: у всех десяти занято меньше 2 МБ, никто в новый
-- лимит не упирается. Проверено запросом перед накатом.
--
-- ⚠️ Своё хранилище (Cloud.ru, 15 ГБ бесплатно) эта квота НЕ ограничивает:
-- при подключённом `storage_provider` место считается в личном облаке клиента,
-- а наша квота к его файлам не применяется вовсе.

ALTER TABLE clients
    ALTER COLUMN storage_quota_bytes SET DEFAULT 104857600;

UPDATE clients
   SET storage_quota_bytes = 104857600
 WHERE storage_quota_bytes = 524288000
   AND storage_used_bytes < 104857600;

COMMENT ON COLUMN clients.storage_quota_bytes IS
    'Квота нашего хранилища, байты. По умолчанию 100 МБ. '
    'При подключённом своём хранилище (storage_provider) не применяется.';
