-- 427. Убрать «настройки мимо кассы» из ставок.
--
-- ⚠️ ПОЧЕМУ ЭТОГО НЕ ДОЛЖНО БЫТЬ В СИСТЕМЕ. Ставка `setup_direct` (100 %)
-- означала «клиент заплатил внедренцу напрямую». Через платформу эти деньги не
-- проходят: начислять нечего, считать не из чего, выплачивать не нужно. Строка
-- в настройках создавала ложное впечатление, что платформа этим управляет.
--
-- ⚠️ Договорённость «мимо кассы оставляете себе всё» остаётся В ТАБЛИЦЕ как
-- условие сотрудничества — но это разговор внедренца с клиентом, а не расчёт
-- платформы.

-- Гасим ставку: API отдаёт только `is_active`, поэтому из админки она исчезает.
UPDATE tech_rates SET is_active = FALSE WHERE kind = 'setup_direct';

-- ⚠️⚠️ ВИД ОСТАЁТСЯ В СПИСКЕ ДОПУСТИМЫХ, хотя из админки он и убран.
-- Сначала миграция вычёркивала `setup_direct` из CHECK — и падала на проде
-- (16.09.2026, деплой откатился):
--   ERROR: check constraint "tech_rates_kind_check" is violated by some row
-- Строка с этим видом в таблице есть, и ограничение, которое ей противоречит,
-- Postgres не создаёт.
--
-- ⚠️ Удалять строку нельзя: удаляющие миграции автоматика деплоя сознательно
-- не накатывает, и выкатка вставала бы на каждом прогоне. Строка просто
-- погашена выше — из админки её не видно (API отдаёт только is_active), а
-- заводить новые ставки этого вида неоткуда: в интерфейсе его больше нет.

-- CHECK пересоздаётся, чтобы список видов был явным и одинаковым в коде и в
-- базе. Начисления (`tech_accruals`) не трогаем — это история выплаченного.
ALTER TABLE tech_rates DROP CONSTRAINT IF EXISTS tech_rates_kind_check;
ALTER TABLE tech_rates ADD CONSTRAINT tech_rates_kind_check
    CHECK (kind IN ('activation', 'retention', 'revival', 'fix',
                    'referral', 'referral2', 'referral3',
                    'setup_pluson', 'setup_own', 'setup_direct',
                    'ticket_simple', 'ticket_hard'));
