-- 421: Настройки платформы (текстовые) + реквизиты провайдера серверов.
--
-- ⚠️⚠️ ЗАЧЕМ ОТДЕЛЬНАЯ ТАБЛИЦА, ЕСЛИ ЕСТЬ `tech_settings`.
-- В `tech_settings` колонка `value` имеет тип NUMERIC — она рассчитана на
-- ставки и коэффициенты техподдержки. Реквизиты юрлица туда физически не
-- положить, а менять тип живой таблицы ради одного поля означало бы трогать
-- расчёты, которые к этому отношения не имеют.
--
-- ⚠️ ЗАЧЕМ ВООБЩЕ НАСТРОЙКА, А НЕ СТРОКА В КОДЕ.
-- Реквизиты провайдера попадают в ОПУБЛИКОВАННЫЕ политики конфиденциальности
-- всех клиентов (152-ФЗ, абзац о месте обработки данных). Переезд на другого
-- провайдера сделал бы неверными сразу все документы, а массово переписать
-- чужие опубликованные политики платформа не вправе. Поле в настройках =
-- правка в одном месте для всех будущих публикаций.

CREATE TABLE IF NOT EXISTS platform_settings (
    id               SMALLINT PRIMARY KEY DEFAULT 1,
    -- Реквизиты того, кто предоставляет серверные мощности. Идёт в пункт
    -- «Место обработки и хранения данных» политики каждого клиента.
    hosting_provider TEXT,
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- ⚠️ Строка ровно одна: настройки платформы глобальны. Ограничение не даёт
    -- завести вторую и гадать потом, какая из них действующая.
    CONSTRAINT platform_settings_single_row CHECK (id = 1)
);

-- ⚠️ Реквизиты сверены 16.09.2026 по официальной странице beget.com/ru/details.
-- Формулировка «серверные мощности предоставлены», а НЕ «услуги хостинга»:
-- у платформы арендован VPS, а не хостинг — разные услуги.
