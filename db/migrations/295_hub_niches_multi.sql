-- 295: Коллабораторная — НЕСКОЛЬКО ниш у карточки вместо одной.
--
-- Зачем. Человек редко укладывается в одну нишу: психолог работает и с
-- «Отношениями», и со «Здоровьем». Одна ниша заставляла выбирать что-то одно,
-- и в каталоге его не находили по второй.
--
-- ⚠️ Старая колонка hub_niche НЕ УДАЛЯЕТСЯ. Она остаётся источником для
-- фильтра «одна ниша» в уже работающем коде и заполняется первой из списка —
-- так ничего не ломается, пока все точки не переведены на массив.

ALTER TABLE clients ADD COLUMN IF NOT EXISTS hub_niches TEXT[] NOT NULL DEFAULT '{}';

-- Переносим то, что уже выбрано (13 записей на проде), чтобы никто не потерял
-- свою нишу при переключении формы на галочки.
UPDATE clients
   SET hub_niches = ARRAY[hub_niche]
 WHERE hub_niche IS NOT NULL
   AND hub_niche <> ''
   AND cardinality(hub_niches) = 0;

-- Поиск «есть хотя бы одна из выбранных ниш» идёт по массиву — нужен GIN.
CREATE INDEX IF NOT EXISTS idx_clients_hub_niches ON clients USING GIN (hub_niches);

-- ── Автозавершение коллаб-событий: отметка о посланном предупреждении ──
-- Организаторов предупреждаем за сутки до автозавершения. Без отметки письмо
-- уходило бы каждый час, пока идут эти сутки.
ALTER TABLE events ADD COLUMN IF NOT EXISTS collab_finish_warned_at TIMESTAMPTZ;
