-- Миграция 081: отслеживание клика по главной CTA-ссылке события.
--
-- В Mini App на вкладке «Программа» есть главная плашка-ссылка:
--   - у мероприятий и конференций — кнопка «Смотреть стрим» (открывает ZOOM/YouTube эфир)
--   - у конкурсов — «Перейти к голосованию»
--
-- Адрес у обоих типов хранится в одном поле `events.stream_url`. Кнопка одна
-- и та же — у разных типов событий называется по-разному.
--
-- Хотим знать, кто из участников реально нажал её. Записываем ПЕРВЫЙ клик
-- (повторные не перетирают — используем COALESCE при UPDATE), NULL = не нажимал.
-- Одного timestamp хватает и как «галочка кликнул», и как «когда».
--
-- В дашборде в списке участников/голосующих рядом с галочкой «Зарегистр.»
-- появится вторая read-only галочка:
--   - у мероприятий/конференций — «Был в эфире»
--   - у конкурсов — «Проголосовал»

ALTER TABLE event_participants
    ADD COLUMN IF NOT EXISTS link_clicked_at TIMESTAMPTZ;

CREATE INDEX IF NOT EXISTS idx_event_participants_link_clicked
    ON event_participants(event_id, link_clicked_at)
    WHERE link_clicked_at IS NOT NULL;
