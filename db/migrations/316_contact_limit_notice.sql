-- 316: Отметка об уведомлении про лимит контактов + лимит триала = лимиту Профи
--
-- Зачем колонки. Проверка лимита вызывается на КАЖДОМ созданном контакте, а
-- контакты приходят пачками (импорт базы, поток регистраций из бота). Без
-- отметки о том, что клиента уже уведомили, он получил бы сотню одинаковых
-- писем подряд. Хранится ВИД события ('warn' | 'upgrade' | 'exceeded'), а не
-- просто флаг: состояние меняется (предупредили → перевели тариф), и о каждом
-- новом состоянии сообщить нужно, а о том же самом — молчать.
ALTER TABLE clients
    ADD COLUMN IF NOT EXISTS contact_limit_notified_kind TEXT,
    ADD COLUMN IF NOT EXISTS contact_limit_notified_at   TIMESTAMPTZ;

COMMENT ON COLUMN clients.contact_limit_notified_kind IS
  'Вид последнего уведомления о лимите контактов: warn (подходит к лимиту) | upgrade (тариф изменён) | exceeded (превышен, перейти некуда). NULL = не уведомляли либо клиент опустился ниже порога.';
COMMENT ON COLUMN clients.contact_limit_notified_at IS
  'Когда отправлено последнее уведомление о лимите контактов.';

-- ⚠️ Триал — это демо тарифа Профи (правило зафиксировано в CLAUDE.md:
-- «тариф trial ВСЕГДА = pro по фичам»). Лимит контактов у него был 10 000
-- против 3 000 у Профи — то есть на бесплатном пробном периоде лимит был
-- ВТРОЕ БОЛЬШЕ, чем на платном тарифе. Выравниваем по Профи.
UPDATE tariffs
   SET contact_limit = (SELECT contact_limit FROM tariffs WHERE slug = 'pro')
 WHERE slug = 'trial';
