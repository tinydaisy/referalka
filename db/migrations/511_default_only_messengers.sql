-- 511. По умолчанию у события включены ТОЛЬКО мессенджеры (24.09.2026)
--
-- ЗАЧЕМ. Галочки в «Публичных ссылках» события (миграция 263) включали ВСЁ
-- подряд: и мессенджеры, и веб-страницы. Но веб-страницы — это осознанный
-- выбор клиента: «Простая страница события» подходит не всем, а
-- «Плюсоновский лендинг» у большинства событий вообще не собран. Показывать
-- спикерам ссылки на то, чем клиент не пользуется, — значит раздавать
-- аудитории страницы, которые организатор не готовил.
--
-- Теперь у НОВОГО события в `disabled_platforms` сразу лежат 'web' и
-- 'landing': галочки стоят только у Telegram / VK / MAX. Нужна веб-страница —
-- клиент ставит галочку сам, и тогда ссылка с реф-кодом появляется у спикеров.
--
-- ⚠️ СТАРЫЕ СОБЫТИЯ НЕ ТРОГАЕМ — ни одной строки UPDATE. У них галочки стоят
-- у всего, спикерам уже разосланы веб-ссылки, и выключить их задним числом =
-- оборвать рабочие ссылки посреди идущих событий. Кому не нужно — снимет
-- галочку руками.
--
-- ⚠️ Меняем DEFAULT КОЛОНКИ, а не код: событие заводится из четырёх разных
-- мест (events.py — дважды, collab_events.py, solutions.py), и перечисление
-- в коде рано или поздно разошлось бы — новое место создания молча получило
-- бы старое поведение. У колонки дефолт один на всех.

ALTER TABLE events
  ALTER COLUMN disabled_platforms SET DEFAULT ARRAY['web', 'landing']::TEXT[];

COMMENT ON COLUMN events.disabled_platforms IS
  'Площадки и страницы, ВЫКЛЮЧЕННЫЕ у события: их ссылки не отдаются спикерам и участникам (сам бот при этом работает). Значения: telegram, vk, max, web (простая страница), landing (Плюсоновский лендинг). По умолчанию выключены веб-страницы — включены только мессенджеры.';
