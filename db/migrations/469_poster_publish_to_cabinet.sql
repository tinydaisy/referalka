-- 469: афиши попадают в кабинет спикера ТОЛЬКО по галочке «опубликовать».
--
-- ⚠️⚠️ ЗАЧЕМ. Кабинет спикера показывал ВСЁ, что лежит в афишах события: и
-- черновые сборки, и промежуточные варианты, и афиши, собранные «на посмотреть».
-- Клиент собирает афишу несколько раз подряд, подбирая раскладку, — и каждая
-- попытка немедленно уезжала спикерам. Публикация должна быть отдельным
-- осознанным действием: «только после этой галочки они появляются в кабинете
-- спикеров» (владелец, 19.09.2026).
--
-- Галочка СВОЯ У КАЖДОГО ТИПА: общие афиши, афиши дня, афиши спикеров. Типы
-- готовятся в разное время (общую собрали в понедельник, индивидуальные в
-- пятницу), и одна галочка на всё означала бы «или всё, или ничего».
--
-- ⚠️ Галочка живёт на МАКЕТЕ (event_poster_layouts), а не на каждой картинке:
-- клиент принимает решение про вид афиш целиком, а не про отдельный файл.
-- Ключ макета тройной (event_id, kind, orientation) — значит и публикация
-- решается отдельно для каждой ориентации, что верно: вертикальную можно
-- выпустить, а горизонтальную ещё дорисовывать.

BEGIN;

ALTER TABLE event_poster_layouts
  ADD COLUMN IF NOT EXISTS published_to_cabinet BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN event_poster_layouts.published_to_cabinet IS
  'Афиши этого вида и ориентации показаны в кабинете спикера. '
  'FALSE — собраны, но спикерам не видны';

-- ⚠️ УЖЕ СОБРАННЫЕ АФИШИ ОСТАВЛЯЕМ ВИДИМЫМИ. Событие может идти прямо сейчас,
-- и спикеры уже берут оттуда материалы для анонсов. Выключив их разом, мы
-- отобрали бы у людей то, чем они пользуются, без единого предупреждения.
-- Новые макеты начинают с FALSE — там и решение ещё не принято.
UPDATE event_poster_layouts SET published_to_cabinet = TRUE
 WHERE EXISTS (SELECT 1 FROM event_posters ep
                WHERE ep.event_id = event_poster_layouts.event_id
                  AND ep.orientation = event_poster_layouts.orientation);

GRANT SELECT, INSERT, UPDATE, DELETE ON event_poster_layouts TO plusson;

COMMIT;
