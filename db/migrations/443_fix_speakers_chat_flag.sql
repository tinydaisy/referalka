-- 443: Вернуть флаг «в чат спикеров» шаблонам, добавленным через «Добавить шаблон».
--
-- ⚠️ ЧТО СЛОМАЛОСЬ. Шаблон создаётся ДВУМЯ путями: авто-сид при первом открытии
-- раздела и ручка «Добавить готовый шаблон» (create_template_from_preset).
-- Флаг send_to_speakers_chat переносил только авто-сид — в INSERT второй ручки
-- его просто не было. У событий, куда шаблон добавили кнопкой (а это все старые
-- конференции), флаг остался FALSE.
--
-- Последствия были двумя, и вторая тяжелее первой:
--   1) шаблон не попадал в группу «Шаблоны в чат спикеров» в кабинете;
--   2) при отправке он не ушёл бы В ЧАТ ВООБЩЕ — получателей в личку у него нет
--      (audience_exclude='all_event'), а доставка в чат включается этим флагом.
--      То есть рассылка молча не доходила бы никуда.
--
-- Тип шаблона — надёжный признак: speakers_call и speakers_day по смыслу
-- существуют только ради чата спикеров, других получателей у них не бывает.

UPDATE broadcast_templates
   SET send_to_speakers_chat = TRUE, updated_at = NOW()
 WHERE type IN ('speakers_call', 'speakers_day')
   AND send_to_speakers_chat = FALSE;

-- То же для уже сформированных, но ещё не отправленных записей очереди:
-- флаг наследуется от шаблона при отправке, но в самой записи мог осесть FALSE
-- (его пишет generate_schedules), и по нему же рисуется плашка в очереди.
UPDATE broadcast_schedules
   SET send_to_speakers_chat = TRUE
 WHERE type IN ('speakers_call', 'speakers_day')
   AND send_to_speakers_chat = FALSE
   AND status IN ('draft', 'pending');
