-- 252: «Что НЕ входит» в тариф — отдельным полем (лендинг, миграции 240-251).
--
-- Зачем. В карточке тарифа на лендинге два списка: что входит (галочка) и
-- чего нет (зачёркнуто, крестик). Раньше «не входит» задавалось строкой,
-- начинающейся с минуса, прямо в общем описании — про такое соглашение
-- клиент знать не обязан. Теперь в форме тарифа два понятных поля.
--
-- description          — что входит (как было)
-- excluded_description — чего в тарифе нет
--
-- Минусы в основном описании продолжают работать: у кого уже так заполнено,
-- ничего не сломается.

ALTER TABLE event_tariffs
  ADD COLUMN IF NOT EXISTS excluded_description TEXT;

GRANT SELECT, INSERT, UPDATE, DELETE ON event_tariffs TO plusson;
