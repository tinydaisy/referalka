-- 473. Кому показывать Плюсоновский лид-магнит: обкатка или все (20.09.2026).
--
-- ЗАЧЕМ.
-- Подарок уже лежит в кабинете у всех 163 клиентов (миграция 472), но пока
-- владелец его не проверил, показывать его всем рано: клиенты увидели бы в
-- своих лид-магнитах предложение, текст и поведение которого ещё обкатываются.
--
-- ⚠️ Прячем ПОКАЗ, а не создание. Подарок у всех остаётся: как только владелец
-- переключит на «всем», он появится у каждого разом и с уже накопленным slug.
-- Если бы вместо этого мы не создавали его на время обкатки, включение
-- означало бы раздачу задним числом — то есть ту же миграцию ещё раз, и у
-- половины клиентов ссылка сменилась бы.
--
-- ⚠️ Кто видит на обкатке — АДМИНСКИЙ И СЕРВИСНЫЙ аккаунт, а не список id.
-- Сейчас это ровно клиенты 1 и 3 (оба на тарифе `admin`, у третьего
-- `is_system_service`), но id в коде означали бы, что при заведении второго
-- админского кабинета его пришлось бы дописывать руками — и об этом никто бы
-- не вспомнил.

BEGIN;

ALTER TABLE platform_settings
    ADD COLUMN IF NOT EXISTS plusson_lm_visibility TEXT NOT NULL DEFAULT 'testing';

ALTER TABLE platform_settings DROP CONSTRAINT IF EXISTS platform_settings_plusson_lm_visibility_check;
ALTER TABLE platform_settings
    ADD CONSTRAINT platform_settings_plusson_lm_visibility_check
    CHECK (plusson_lm_visibility IN ('testing', 'all'));

COMMENT ON COLUMN platform_settings.plusson_lm_visibility IS
    'Кому виден Плюсоновский лид-магнит: testing — только админскому и '
    'сервисному аккаунту (обкатка); all — всем клиентам. Прячется ПОКАЗ, '
    'сам подарок есть у всех';

COMMIT;
