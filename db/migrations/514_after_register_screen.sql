-- 514. Куда ведём человека сразу после регистрации (25.09.2026)
--
-- ЗАЧЕМ. После веб-регистрации человека вели по-разному, и во втором случае
-- он терял мессенджеры:
--   • НОВЫЙ человек → экран «спасибо» с кнопками ботов (TG / MAX / ВК) и
--     только потом, по кнопке «Продолжить», кабинет участника;
--   • УЖЕ ЗАРЕГИСТРИРОВАННЫЙ → редирект прямо в кабинет, экран с кнопками
--     ботов перескакивался вовсе (event_page_html.py, ветка res.registered).
--
-- А кнопки ботов — это главное, ради чего человека вообще приводят: без
-- перехода в бота до него не дойдут ни напоминания об эфире, ни подарки, ни
-- реферальная механика. Человек, пришедший по ссылке спикера повторно, просто
-- попадал в кабинет и в бота не заходил.
--
-- Теперь это НАСТРОЙКА события, одна на все пути регистрации:
--   'platforms' (по умолчанию) — показываем экран выбора площадки: три кнопки
--       на ботов организатора, отметка «вы зарегистрированы», переход в меню
--       конференции. Кабинет — ссылкой ниже;
--   'cabinet' — сразу кабинет участника, как было у повторной регистрации.
--
-- ⚠️ ДЕФОЛТ — ИМЕННО 'platforms', и для СТАРЫХ событий тоже (DEFAULT + NOT
-- NULL заполняет всю таблицу). Это осознанно: прежнее поведение было
-- непоследовательным — одним показывали ботов, другим нет. Приводить всех к
-- «сразу кабинет» значило бы закрепить худший из двух вариантов, при котором
-- человек не попадает в бота вовсе.

ALTER TABLE events
  ADD COLUMN IF NOT EXISTS after_register_screen TEXT NOT NULL DEFAULT 'platforms';

ALTER TABLE events
  DROP CONSTRAINT IF EXISTS events_after_register_screen_check;
ALTER TABLE events
  ADD CONSTRAINT events_after_register_screen_check
      CHECK (after_register_screen IN ('platforms', 'cabinet'));

COMMENT ON COLUMN events.after_register_screen IS
  'Что открывается сразу после регистрации: platforms — экран с кнопками ботов организатора (по умолчанию), cabinet — сразу кабинет участника.';
