-- 433: Ссылка входа СПИКЕРА в эфир дня (Zoom и т.п.).
--
-- ⚠️ Это НЕ ссылка на эфир. Их две, и они для разных людей:
--   • webinar_rooms → вебинарная комната дня ({stream_url}) — туда идут ЗРИТЕЛИ;
--   • speaker_join_url — куда заходит СПИКЕР, чтобы его картинка попала В эту
--     комнату. Зрители по ней не ходят никогда.
--
-- Почему у ДНЯ, а не у события: зум-конференция создаётся под конкретный эфир —
-- два дня программы означают две разные ссылки, одним полем на событие это не
-- выражается. Рядом с комнатой того же дня плейсхолдер берёт нужный день сам,
-- той же логикой, что и {stream_url} (по дню слота спикера).
--
-- Используется плейсхолдером {speaker_join_url} в рассылке speakers_call
-- («вы следующие» в чат спикеров, миграция 432).

ALTER TABLE webinar_rooms
  ADD COLUMN IF NOT EXISTS speaker_join_url TEXT;

COMMENT ON COLUMN webinar_rooms.speaker_join_url
  IS 'Ссылка входа СПИКЕРА в эфир этого дня (Zoom/Meet). Зрители идут в комнату, не сюда';
