-- 428: почта оператора персданных = почта кабинета (для уже заведённых).
--
-- ⚠️ ЗАЧЕМ. `legal_operator_email` обязателен для публикации политики по
-- 152-ФЗ. Человек этот адрес уже вводил при регистрации и подтверждал письмом
-- — спрашивать второй раз незачем. С 16.09.2026 он проставляется при
-- регистрации (`api/auth.py`), эта миграция закрывает тех, кто завёлся раньше.
--
-- ⚠️ ТОЛЬКО В ПУСТОЕ ПОЛЕ: у части клиентов для обращений по персданным
-- отдельный адрес, и затирать его настройку нельзя. То же правило, что у
-- «Службы заботы» в автонастройке.
--
-- ⚠️ Данные не удаляются и не перетираются — миграция безопасна.

UPDATE clients
   SET legal_operator_email = email
 WHERE COALESCE(legal_operator_email, '') = ''
   AND COALESCE(email, '') <> '';
