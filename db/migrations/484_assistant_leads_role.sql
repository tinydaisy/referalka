-- 484: роль помощника «Менеджер лидов» + закрепление людей за менеджером (2026-09-21)
--
-- Зачем. Клиент раздаёт своих людей сотрудникам: каждый ведёт СВОЙ кусок базы
-- — звонит, пишет, догревает. Отдавать сотруднику всю базу нельзя: он видел бы
-- чужих клиентов, а это чужая работа и чужие деньги.
--
-- Уровней стало четыре:
--   full    — как владелец (кроме управления помощниками и пароля)
--   limited — прежний широкий набор: события, рассылки, программа…
--   orders  — только «Контакты» и «Анкеты», но ВСЕ контакты кабинета
--   leads   — «Менеджер лидов»: контакты и CRM событий, но ТОЛЬКО закреплённые
--             за ним люди. Плюс переписка с ними через бота клиента.
--
-- ⚠️ Разница orders и leads именно в ВИДИМОСТИ, а не в наборе разделов:
-- менеджер заказов разбирает поток заявок целиком, менеджер лидов ведёт свой
-- закреплённый список. Поэтому это отдельный уровень, а не «orders с фильтром»:
-- обрезать видимость у orders значило бы сломать его нынешнюю работу.

ALTER TABLE assistant_grants DROP CONSTRAINT IF EXISTS assistant_grants_access_level_check;

ALTER TABLE assistant_grants
    ADD CONSTRAINT assistant_grants_access_level_check
    CHECK (access_level IN ('full', 'limited', 'orders', 'leads'));

COMMENT ON COLUMN assistant_grants.access_level IS
  'full — как владелец; limited — прежний широкий набор; '
  'orders — только «Контакты» и «Анкеты» (менеджер заказов); '
  'leads — «Контакты» и CRM событий, но только закреплённые люди (менеджер лидов).';


-- ─────────────────────────────────────────────────────────────────────────────
-- Закрепление человека за менеджером
-- ─────────────────────────────────────────────────────────────────────────────
--
-- ⚠️⚠️ ЗАКРЕПЛЯЕМ КОНТАКТ, А НЕ УЧАСТНИКА СОБЫТИЯ. Контакт — это человек, он
-- один. Участник события — его запись в ОДНОМ событии, и таких записей у
-- человека столько, во сколько событий он пришёл. Закрепи участника — и один
-- человек окажется у трёх менеджеров сразу, а в базе контактов будет вообще
-- непонятно, чей он.
-- Выигрыш решения: одно закрепление даёт фильтр СРАЗУ ВЕЗДЕ — в базе
-- контактов, в CRM любого события, в CRM лид-магнита, в переписке. Все эти
-- экраны в итоге приходят к `contacts`.
--
-- ⚠️ Ссылка на ПРОПУСК (`assistant_grants`), а не на человека (`assistants`).
-- Помощник ведёт несколько кабинетов, и закрепление действует внутри одного:
-- ссылка на человека означала бы «закреплён за ним во всех кабинетах». Ещё и
-- уборка бесплатная — отозвали пропуск, закрепления ушли каскадом.
--
-- ⚠️ Отдельная таблица, а не колонка в `contacts`: у контакта уже есть
-- `partner_id` (за каким партнёром закреплён ради реф-денег) — это ДРУГОЕ и
-- ставится один раз навсегда. Смешать их в одну колонку значит однажды
-- переназначить менеджера и сломать выплату партнёру.
CREATE TABLE IF NOT EXISTS contact_assignments (
    id         SERIAL PRIMARY KEY,
    -- В чьём кабинете закрепление. Дублирует client_id пропуска, но нужен
    -- в запросах: фильтр в списке контактов идёт по кабинету и без него
    -- пришлось бы джойнить пропуск на каждой выборке.
    client_id  INTEGER NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    contact_id INTEGER NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
    grant_id   INTEGER NOT NULL REFERENCES assistant_grants(id) ON DELETE CASCADE,

    assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- Кто закрепил: 'owner' (вручную из кабинета) или 'auto' — про запас,
    -- когда появится автораспределение по кругу.
    assigned_by TEXT NOT NULL DEFAULT 'owner',
    note       TEXT,

    -- ⚠️ Один человек — один менеджер. Требование владельца: иначе в CRM
    -- один и тот же человек попадёт в списки двоих, и оба будут ему писать.
    UNIQUE (client_id, contact_id)
);

-- Главный запрос роли: «покажи всех МОИХ людей в этом кабинете».
CREATE INDEX IF NOT EXISTS ix_contact_assign_grant
    ON contact_assignments (grant_id, assigned_at DESC);
-- Обратный: «а этот человек за кем закреплён» — подпись в карточке контакта.
CREATE INDEX IF NOT EXISTS ix_contact_assign_contact
    ON contact_assignments (contact_id);

COMMENT ON TABLE contact_assignments IS
  'За каким помощником кабинета закреплён человек. Роль leads («менеджер '
  'лидов») видит в контактах и в CRM событий только закреплённых за собой.';

