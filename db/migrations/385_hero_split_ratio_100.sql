-- 385: ширина колонки шапки лендинга — до 100%
--
-- Зачем. `split_ratio` у секции — это ПРОПОРЦИЯ двух колонок (заголовок сбоку
-- от содержимого), там 100% бессмысленно: второй колонке не осталось бы места,
-- отсюда старый потолок 80.
--
-- Но у ШАПКИ то же поле означает другое — ширину колонки с текстом. Её штатно
-- ставят во всю полосу: при сдвиге текста влево потолок 80% оставлял
-- необъяснимый зазор справа, и «во всю ширину» было не собрать.
--
-- ⚠️ Потолок 100 разрешаем В БАЗЕ ДЛЯ ВСЕХ блоков, а разграничение «шапке 100,
-- секции 80» держим в коде (event_landing.py): CHECK не знает, какой это kind,
-- а заводить ради этого условие по kind в ограничении — хрупко (новый тип
-- блока пришлось бы вписывать ещё и сюда).
--
-- ⚠️ Существующие значения не трогаем: все они ≤ 80 и остаются валидными.

ALTER TABLE event_landing_blocks
  DROP CONSTRAINT IF EXISTS event_landing_blocks_split_ratio_check;

ALTER TABLE event_landing_blocks
  ADD CONSTRAINT event_landing_blocks_split_ratio_check
  CHECK (split_ratio IS NULL OR (split_ratio >= 20 AND split_ratio <= 100));
