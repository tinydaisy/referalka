-- 460: частые вопросы техспецов — общая база готовых ответов.
--
-- ⚠️⚠️ ЗАЧЕМ. Внедренцы отвечают клиентам на одни и те же вопросы, и каждый
-- формулирует ответ заново — своими словами, своей длины, с разной степенью
-- правоты. Один и тот же вопрос («почему виден только один чат события?»)
-- получает пять разных ответов от пяти человек.
--
-- Требование владельца (18.09.2026): общий раздел с готовыми ответами, чтобы
-- ответ можно было СКОПИРОВАТЬ и сразу отправить клиенту.
--
-- ⚠️⚠️ БАЗА ОБЩАЯ НА ВСЕХ, а не личная у каждого. Что добавил один — видят
-- все: в этом весь смысл. Поэтому `author_spec_id` — только ПОДПИСЬ «кто
-- завёл», а НЕ признак владения: редактировать и удалять может любой
-- техспец и админ. Личная база превратила бы раздел в пять разных подборок,
-- то есть вернула бы ровно ту проблему, ради которой он заводится.
--
-- ⚠️ Автор хранится ДВАЖДЫ — ссылкой и снимком имени (`author_name`).
-- Ссылка `ON DELETE SET NULL`: специалист уволился и его карточку удалили —
-- вопрос обязан остаться вместе с ответом, он общий и нужен остальным. Но
-- без снимка имени подпись превратилась бы в пустоту, и нельзя было бы
-- понять, кто это писал. Снимок — на случай, когда ссылки уже нет.
--
-- ⚠️ Админ тоже может заводить вопросы, и тогда `author_spec_id` пуст —
-- в `author_name` пишется «Администратор». Отдельного поля «тип автора» не
-- заводим: подпись нужна для чтения человеком, а не для логики.

BEGIN;

CREATE TABLE IF NOT EXISTS tech_faq (
    id              SERIAL PRIMARY KEY,
    question        TEXT NOT NULL,
    answer          TEXT NOT NULL,
    -- Кто завёл: ссылка + снимок имени (см. шапку).
    author_spec_id  INTEGER REFERENCES tech_specialists(id) ON DELETE SET NULL,
    author_name     TEXT,
    -- Кто правил последним — чтобы было видно, что ответ кто-то обновил.
    updated_by_name TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Свежие вопросы сверху — так список открывается в кабинете и в админке.
CREATE INDEX IF NOT EXISTS idx_tech_faq_created ON tech_faq (created_at DESC);

COMMENT ON TABLE tech_faq IS
    'Частые вопросы техспецов: общая база готовых ответов. Видна и правится ВСЕМИ техспецами и админами';
COMMENT ON COLUMN tech_faq.author_spec_id IS
    'Кто завёл вопрос. Только подпись, НЕ владение: править и удалять может любой. NULL — завёл админ или автора удалили';
COMMENT ON COLUMN tech_faq.author_name IS
    'Имя автора снимком — остаётся читаемым, даже если карточку специалиста удалили';

GRANT SELECT, INSERT, UPDATE, DELETE ON tech_faq TO plusson;
GRANT USAGE, SELECT ON SEQUENCE tech_faq_id_seq TO plusson;

-- ⚠️ Первый вопрос заводится сразу (требование владельца): раздел не должен
-- открываться пустым, иначе непонятно, что в нём должно лежать.
INSERT INTO tech_faq (question, answer, author_name)
SELECT
    'Почему у меня отображается только один чат события? Хотя добавлены чаты в разных площадках',
    E'Скорее всего, у части чатов не заполнена ссылка.\n\n'
    'Чат показывается на странице события только тогда, когда у него указана ссылка для перехода. '
    'Если чат добавлен, но поле со ссылкой пустое — он остаётся в настройках, а на странице не появляется.\n\n'
    'Что сделать: откройте настройки события, раздел с чатами, и проверьте каждую площадку по очереди — '
    'у всех ли заполнена ссылка. Заполните пустые и сохраните.',
    'Администратор'
WHERE NOT EXISTS (SELECT 1 FROM tech_faq);

COMMIT;
