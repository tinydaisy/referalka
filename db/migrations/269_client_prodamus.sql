-- 269: Продамус как вторая платёжная система КЛИЕНТА (в дополнение к LeadPay).
--
-- ⚠️ Не путать с ключами ПЛЮСОНа (PRODAMUS_SECRET_KEY в переменных окружения) —
-- ими оплачивают подписку на платформу. Здесь ключи КАЖДОГО клиента: ими его
-- покупатели оплачивают тарифы его событий, деньги идут ему.
--
-- ⚠️ Продамус устроен иначе, чем LeadPay: у него НЕТ метода «дай ссылку».
-- Ссылка собирается на нашей стороне из адреса формы + параметров заказа +
-- подписи. Поэтому вместо «логина» здесь адрес формы, а секретный ключ нужен
-- и для подписи ссылки, и для проверки вебхука.

ALTER TABLE clients
  ADD COLUMN IF NOT EXISTS pay_prodamus_url    TEXT,  -- https://<магазин>.payform.ru/
  ADD COLUMN IF NOT EXISTS pay_prodamus_secret TEXT;  -- секретный ключ магазина

-- pay_provider теперь принимает 'leadpay' | 'prodamus' | NULL.
-- CHECK не ставим: значение нормализуется в API, а лишнее ограничение
-- помешает добавить третью систему данными.

GRANT SELECT, INSERT, UPDATE, DELETE ON clients TO plusson;
