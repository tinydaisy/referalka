-- 461: право удалять частые вопросы — поимённо, галочкой в карточке.
--
-- ⚠️⚠️ ЗАЧЕМ. Раздел частых вопросов (миграция 460) — ОБЩАЯ база: добавлять и
-- править может каждый техспец, и это правильно, ошибку в ответе должен уметь
-- поправить тот, кто её заметил. А вот удаление убирает ответ у ВСЕХ сразу и
-- безвозвратно — это уже не правка, а потеря общего знания.
--
-- Решение владельца (19.09.2026): удаление доступно админу всегда, а из
-- техспецов — тем, кому право выдали поимённо галочкой. Сначала обсуждался
-- жёсткий вариант «только админ», но он неудобен: владелец не должен быть
-- единственным, кто может убрать устаревший вопрос.
--
-- ⚠️ Право отдельное от `can_edit_materials` (миграция 391), хотя устроено
-- так же. Это разные вещи: там правка материалов Коллабораторной, здесь —
-- удаление из общей базы ответов. Общая галочка «доверенный» выдавала бы
-- вместе с нужным правом ещё и ненужное.
--
-- ⚠️ УМОЛЧАНИЕ FALSE — права нет ни у кого, пока его явно не дали. Обратное
-- умолчание раздало бы право удалять всем молча, и первым, кто о нём узнал
-- бы, оказался автор пропавшего ответа.

BEGIN;

ALTER TABLE tech_specialists
    ADD COLUMN IF NOT EXISTS can_delete_faq BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN tech_specialists.can_delete_faq IS
    'Может удалять вопросы из общей базы частых вопросов. Добавлять и править может каждый — удалять только с этой галочкой';

GRANT SELECT, INSERT, UPDATE, DELETE ON tech_specialists TO plusson;

COMMIT;
