-- 344: Где проверяем подписку на каналы + отметка о пройденной проверке
--
-- ЗАЧЕМ. Модерация ВКонтакте отклонила Mini App: «сервис запрашивает подписку
-- на сообщество до просмотра его функций» (п.1.1.2 правил Mini Apps). Раньше
-- окно подписки выскакивало сразу при открытии — до того, как человек увидел
-- событие. Теперь подписку просим ПОСЛЕ регистрации, а для этого нужно уметь
-- сказать, ГДЕ именно проверять: только при входе в чат (как было) и/или при
-- входе в кабинет после регистрации.
--
-- ⚠️ КОГО проверять (организаторы / спикеры) НЕ заводим заново — это
-- существующий `conf_conferences.subscription_mode` (none|organizer|all_speakers)
-- и `events.require_subscription` у мероприятий. Здесь только «где».

-- ── 1. Точки проверки ────────────────────────────────────────────────
-- Две отдельные колонки, а не одна строка со списком: по каждой точке нужен
-- обычный BOOLEAN в WHERE, и добавить третью точку позже будет так же дёшево.
--
-- ⚠️ Значения по умолчанию НЕ симметричны, и это осознанно:
--   • at_chat = TRUE  — так работало всегда. Поставь FALSE, и у восьми событий
--     на проде проверка при входе в чат молча отключилась бы.
--   • at_reg  = FALSE — новая точка. Включённая по умолчанию, она бы закрыла
--     кабинет тем, кто вчера заходил свободно.
ALTER TABLE events
  ADD COLUMN IF NOT EXISTS sub_check_at_chat BOOLEAN NOT NULL DEFAULT TRUE,
  ADD COLUMN IF NOT EXISTS sub_check_at_registration BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN events.sub_check_at_chat IS
  'Проверять подписку при входе в чат события (прежнее поведение).';
COMMENT ON COLUMN events.sub_check_at_registration IS
  'Проверять подписку при входе в кабинет после регистрации. Пока не пройдена — вкладки под замком.';

-- ── 2. Отметка «подписку проверили» ──────────────────────────────────
-- ⚠️ В БАЗЕ, А НЕ В localStorage: человек меняет телефон и чистит кеш, а
-- «подписался один раз — больше не спрашиваем» должно пережить и то, и другое.
--
-- ⚠️ ОТМЕТКА НЕ СНИМАЕТСЯ, даже если человек потом отписался (решение
-- владельца): требуем подписку ДО ПЕРВОГО ФАКТА. Иначе участник, отписавшийся
-- через месяц, внезапно потерял бы доступ к программе события, на которое он
-- давно зарегистрирован.
ALTER TABLE event_participants
  ADD COLUMN IF NOT EXISTS sub_checked_at TIMESTAMPTZ;

COMMENT ON COLUMN event_participants.sub_checked_at IS
  'Когда участник впервые прошёл проверку подписки на каналы. NULL — ещё не проходил. Не снимается при отписке.';

-- Частичный индекс: спрашиваем всегда «а прошёл ли уже?» по одному участнику.
-- Строк с заполненной отметкой сильно меньше, чем всего участников.
CREATE INDEX IF NOT EXISTS idx_event_participants_sub_checked
  ON event_participants (event_id, contact_id)
  WHERE sub_checked_at IS NOT NULL;

-- ⚠️ Роль plusson не владелец таблиц — на новые объекты права выдаются явно,
-- иначе API получит permission denied (см. CLAUDE.md).
GRANT SELECT, INSERT, UPDATE, DELETE ON events, event_participants TO plusson;
