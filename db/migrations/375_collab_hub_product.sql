-- 375. Продукт «Коллабораторная» — уроки для купивших модуль.
--
-- Уроки живут в кабинете СИСТЕМНОГО клиента («ПЛЮСОН Сервис»), а не у клиента 1:
-- Коллабораторную продаёт кто угодно своим тарифом события, а покупатель может
-- прийти и прямо из кабинета ПЛЮСОНа — в базе клиента 1 его тогда нет и взяться
-- ему там неоткуда. У системного клиента он заводится контактом по почте, которой
-- зарегистрирован в ПЛЮСОНе.
--
-- ⚠️ slug ОБЯЗАН совпадать с MODULE_PRODUCTS в
--    backend/app/services/module_product_access.py — по нему код находит продукт.
-- ⚠️ Продукт создаётся ЧЕРНОВИКОМ: публичная страница /pr/ ему не нужна вовсе
--    (продаётся модуль, а не продукт), а кабинет /my статус не проверяет —
--    закрывает только 'archived'. Купившие увидят уроки, посторонние — нет.
-- ⚠️ Тарифа у продукта НЕТ намеренно: доступ выдаётся не покупкой продукта, а
--    выдачей модуля, и срок берётся у модуля. product_access.tariff_id nullable.

-- ⚠️ «(Материалы)» в названии обязательно: рядом с одноимённым МОДУЛЕМ
--    голая «Коллабораторная» читается как сам модуль, а не как уроки к нему.
INSERT INTO products (client_id, slug, title, subtitle, status, wording_preset)
SELECT c.id, 'collab-hub', 'Коллабораторная ПЛЮСОН (Материалы)',
       'Записи вебинаров, афиши и тексты для приглашений',
       'draft', 'consulting'
  FROM clients c
 WHERE c.is_system_service = TRUE
ON CONFLICT (client_id, slug) DO NOTHING;
