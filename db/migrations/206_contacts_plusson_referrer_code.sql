-- Миграция 206: закрепление ПЛЮСОН-реф-кода за контактом при входе в ЛЮБОЙ VIP-бот.
--
-- Сценарий. Человек открывает бот любого клиента по ссылке `/start ref<код>`, где
-- <код> — реф-код клиента ПЛЮСОНа (clients.referral_code) или код-контакт спикера
-- с привязанным ПЛЮСОНом (contacts.ref_code → collaborators/contacts.linked_client_id).
-- Раньше бот только показывал приглашение с кнопкой на регистрацию, но НИГДЕ не
-- сохранял этот код у контакта — если человек не жал кнопку сразу, привязка терялась.
--
-- Теперь код пишется в contacts.plusson_referrer_code того контакта (в базе клиента
-- этого бота). При регистрации в ПЛЮСОН, если в URL нет pid, /register может взять
-- код отсюда и закрепить нового клиента за рефоводом (resolve_plusson_referrer).
--
-- Хранит СЫРОЙ код (как пришёл в /start) — резолвер сам поймёт, клиентский это код
-- или код-контакт. Не перезатираем существующее значение (первый рефовод выигрывает).

ALTER TABLE contacts
  ADD COLUMN IF NOT EXISTS plusson_referrer_code TEXT;
