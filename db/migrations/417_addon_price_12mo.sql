-- 417: Периоды оплаты модулей — 6 и 12 месяцев со скидкой, как у тарифов.
--
-- Было: у модуля только `price_monthly` и `price_6mo`, годовой оплаты нет вовсе.
-- Скидка за полгода стояла −20% и была ЩЕДРЕЕ тарифной (у тарифов −12%), а в
-- интерфейсе «(−20%)» было вписано текстом — то есть подпись жила отдельно от
-- цены и разошлась бы при первой же правке.
--
-- Решение владельца 15.09.2026: у модулей те же скидки, что у тарифов —
-- 6 месяцев −12%, 12 месяцев −20%. Единое правило на всю платформу.
--
-- ⚠️ ЦЕНА ХРАНИТСЯ ЗА МЕСЯЦ, как у тарифов (`tariffs.price_6mo`), а не итогом
-- за период: человеку показывают «2 640 ₽/мес», а итог считается умножением.
-- Процент скидки НЕ храним — он считается из цен, поэтому подпись физически
-- не может разойтись с суммой (см. services/tariff_periods.py).
--
-- ⚠️ ПОЛУГОДОВАЯ ЦЕНА ВЫРАСТАЕТ: было 800/2400/4000, стало 880/2640/4400.
-- Это осознанный выбор владельца ради единого правила. Оплат за 6 месяцев в
-- истории НЕ БЫЛО НИ ОДНОЙ (проверено: `addon_orders` с months > 1 — пусто),
-- поэтому никому цена задним числом не меняется.
--
-- ⚠️ Карточки LeadPay (`leadpay_product_id_6mo`) больше не нужны и не
-- заводятся: с 15.09.2026 сумма уходит в запросе через api/v2/getLink.
-- Именно из-за них полугодовая оплата модулей и не работала — колонка была
-- пуста у всех трёх, и код откатывался на месячную карточку: клиент заплатил
-- бы 1000 ₽ за полгода вместо 4800. Мина не выстрелила только потому, что
-- таких оплат не случилось.

ALTER TABLE features
  ADD COLUMN IF NOT EXISTS price_12mo INTEGER;

COMMENT ON COLUMN features.price_6mo  IS
  'Цена ЗА МЕСЯЦ при оплате за 6 месяцев (−12% от price_monthly). NULL = период не продаётся.';
COMMENT ON COLUMN features.price_12mo IS
  'Цена ЗА МЕСЯЦ при оплате за 12 месяцев (−20% от price_monthly). NULL = период не продаётся.';

-- Пересчёт по единому правилу. Округление до рубля: цены модулей круглые,
-- дробей не возникает (1000→880/800, 3000→2640/2400, 5000→4400/4000).
UPDATE features
   SET price_6mo  = ROUND(price_monthly * 0.88),
       price_12mo = ROUND(price_monthly * 0.80)
 WHERE is_addon AND COALESCE(price_monthly, 0) > 0;
