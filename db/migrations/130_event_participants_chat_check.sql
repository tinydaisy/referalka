-- Миграция 130: отметка времени последней проверки «в чате» для участника.
--
-- Кнопка «Проверить чаты» на странице участников события массово проверяет
-- членство в Telegram-чате события (events.telegram_chat_ids) через бот-админа
-- (getChatMember). Результат пишется в существующее поле event_participants.is_in_chat
-- (раньше его ставил только Salebot), а время последней проверки — в новое
-- поле chat_check_at (чтобы в UI показывать «✓ в чате · 10.06 14:20» / «нет в чате»
-- и отличать «не проверяли» от «проверили, не в чате»).
--
-- ВК/МАХ-беседы платформы проверить через API не позволяют — фича пока только TG.

ALTER TABLE event_participants
  ADD COLUMN IF NOT EXISTS chat_check_at TIMESTAMPTZ NULL;
