-- Опрос комментариев Instagram — временная замена вебхукам.
--
-- ⚠️⚠️ ЗАЧЕМ. Meta шлёт вебхуки о комментариях только ОПУБЛИКОВАННОМУ
-- приложению, а для поля `comments` требует ещё и Advanced Access — то есть
-- App Review длиной в недели (проверено 2026-09-07: подписки настроены, права
-- выданы, комментарии читаются запросом, а событий нет ни одного).
--
-- Запросы к API при этом работают в режиме разработки уже сейчас. Поэтому
-- пока проверка не пройдена, комментарии ЗАБИРАЕМ САМИ: раз в минуту
-- спрашиваем свежие и прогоняем через тот же движок воронки.
--
-- ⚠️ Это ВРЕМЕННЫЙ режим. После одобрения Meta переключаемся обратно на
-- вебхуки: они мгновенные и не тратят лимит запросов. Движок, тексты и
-- выдача общие — меняется только источник события.

-- Обработанные комментарии.
--
-- ⚠️⚠️ ОБЯЗАТЕЛЬНА именно таблица, а не «время последнего опроса». Вебхук
-- присылает каждое событие один раз, а опрос видит одни и те же комментарии
-- при каждом заходе — без отметки человек получал бы материал по кругу
-- каждую минуту. Отметка по времени тут не спасает: комментарии приходят с
-- задержкой и вразнобой, и по «новее чем» часть терялась бы, а часть
-- обрабатывалась дважды.
CREATE TABLE IF NOT EXISTS instagram_seen_comments (
  comment_id  TEXT        PRIMARY KEY,
  channel_id  INT         REFERENCES channels(id) ON DELETE CASCADE,
  media_id    TEXT        NOT NULL DEFAULT '',
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ⚠️ Индекс под уборку старых записей: таблица растёт на каждый комментарий
-- под любой отслеживаемой публикацией, а нужна только чтобы не ответить
-- дважды. Без чистки она копилась бы годами (та же история, что с _bak_*).
CREATE INDEX IF NOT EXISTS idx_ig_seen_created ON instagram_seen_comments (created_at);

-- Когда канал опрашивали в последний раз — чтобы не ходить в Meta чаще нужного
-- и видеть в базе, жив ли опрос вообще.
ALTER TABLE channels ADD COLUMN IF NOT EXISTS ig_polled_at TIMESTAMPTZ;

