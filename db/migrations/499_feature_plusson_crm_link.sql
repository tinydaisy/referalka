-- 499: фича «Связь с ПЛЮСОНом в CRM события».
--
-- Два блока в CRM события («Заинтересовались ПЛЮСОНом» и «Зарегистрированы в
-- ПЛЮСОНе») видел ТОЛЬКО внедренец. Владельцу кабинета они тоже нужны: он
-- смотрит, кто из участников его событий дошёл до платформы.
--
-- ⚠️⚠️ ГЕЙТ ПО ФИЧЕ, А НЕ ПО ID КЛИЕНТА (правило владельца). Соблазн написать
-- `client_id IN (1, 3)` велик и ломается молча: появится третий такой кабинет —
-- и про него никто не вспомнит, а в коде останется список, который невозможно
-- найти поиском по смыслу. Фича выдаётся тарифу, тариф — кому нужно.
--
-- ⚠️ Выдаём тарифу «Администратор»: на нём сидят кабинеты самой платформы,
-- которым эта связь и нужна. Другим тарифам НЕ выдаём — обычному клиенту
-- реф-коды ПЛЮСОНа ничего не говорят.

INSERT INTO features (slug, name, description, sort)
VALUES ('plusson_crm_link',
        'Связь с ПЛЮСОНом в CRM',
        'В CRM события видно, кто из участников зашёл в бот ПЛЮСОНа и кто '
        'завёл кабинет на платформе.',
        95)
ON CONFLICT (slug) DO NOTHING;

-- Тариф «Администратор» — кабинеты самой платформы.
INSERT INTO tariff_features (tariff_id, feature_id)
SELECT t.id, f.id
  FROM tariffs t, features f
 WHERE t.slug = 'admin' AND f.slug = 'plusson_crm_link'
ON CONFLICT DO NOTHING;
