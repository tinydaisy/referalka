-- 384. Воронка Instagram — открыта клиентам с тарифа «Профи» (09.09.2026).
--
-- ЗАЧЕМ.
-- Фича `instagram_funnel` (миграции 361-362) была привязана ТОЛЬКО к `admin`:
-- механика работала, но клиентам не продавалась, и секция Instagram в разделе
-- «Каналы» у них была скрыта. Решение владельца — открыть всем начиная с Профи.
--
-- ⚠️ ТРИАЛ ВКЛЮЧЁН НАМЕРЕННО: в проекте действует правило «триал = Профи по
-- фичам» (см. `_mirror_pro_features_to_trial` в app/api/admin.py). Без строки
-- для `trial` человек на пробном периоде не увидел бы того, что ему обещано
-- как «полный Профи на 7 дней», и решил бы, что раздел сломан.
--
-- ⚠️ `business_beta` тоже: он ВЫШЕ Профи и по составу включает всё из Экстры.
-- Пропустить его — значит сделать самый дорогой тариф беднее среднего.
--
-- ⚠️ `start` (Стандарт) НЕ добавляем: тариф скрыт (`is_active = FALSE`), не
-- продаётся, и клиентов на нём нет.
--
-- ⚠️ Ключи Meta (IG_APP_ID / IG_APP_SECRET / IG_CONFIG_ID) на проде заданы —
-- проверено перед выдачей. Без них раздел открылся бы мёртвым: кнопка
-- подключения ведёт в окно Facebook, которое без `config_id` не строится.

BEGIN;

INSERT INTO tariff_features (tariff_id, feature_id)
SELECT t.id, f.id
  FROM tariffs t, features f
 WHERE f.slug = 'instagram_funnel'
   AND t.slug IN ('pro', 'vip', 'trial', 'business_beta')
ON CONFLICT DO NOTHING;

COMMIT;
