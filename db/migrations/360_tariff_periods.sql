-- 360: Оплата подписки на 6 и 12 месяцев со скидкой
--
-- Было: у тарифа одна цена и одна карточка LeadPay, а в заказе не хранилось,
-- за сколько месяцев заплатили — вебхук всегда продлевал на
-- `default_duration_days` (30 дней). Подставить карточку на год было физически
-- некуда: человек заплатил бы 19 104 ₽ и получил месяц.
--
-- Скидки (решение владельца): 6 месяцев −12%, 12 месяцев −20%.
--
--            за мес   6 мес           12 мес
--   Профи    1990     1751,20         1592,00
--            итого    10 507,20       19 104,00
--   Экстра   2990     2631,20         2392,00
--            итого    15 787,20       28 704,00
--
-- ⚠️ Храним цену ЗА МЕСЯЦ по периоду, а не итог — тот же приём, что у модулей
-- (`features.price_6mo`, миграция 165). Причины две: в карточке тарифа человеку
-- показывают именно «2392 ₽/мес», а итог = цена × месяцы считается сам и не
-- разъезжается при правке.
--
-- ⚠️ Процент скидки НЕ храним и не хардкодим — он вычисляется из цен
-- (1 − цена_периода / цена_месяца). Иначе подпись «−20%» живёт отдельно от
-- суммы и однажды разойдётся с ней: именно на этом уже ошиблись, когда 19 104 ₽
-- (ровно −20%) назвали скидкой 25%.
--
-- ⚠️ Продамус здесь не заводим: у него на длинные периоды нужны отдельные
-- готовые ссылки, а все 8 реальных оплат подписки прошли через LeadPay
-- (у модулей ссылки Продамуса вообще пустые). Понадобится — добавим колонки
-- по тому же образцу.

ALTER TABLE tariffs
  ADD COLUMN IF NOT EXISTS price_6mo  NUMERIC(10,2),   -- ₽/мес при оплате за 6 мес
  ADD COLUMN IF NOT EXISTS price_12mo NUMERIC(10,2),   -- ₽/мес при оплате за 12 мес
  ADD COLUMN IF NOT EXISTS leadpay_product_id_6mo  TEXT,
  ADD COLUMN IF NOT EXISTS leadpay_product_id_12mo TEXT;

COMMENT ON COLUMN tariffs.price_6mo IS
  'Цена ЗА МЕСЯЦ при оплате сразу за 6 месяцев. NULL = период не продаётся.';
COMMENT ON COLUMN tariffs.price_12mo IS
  'Цена ЗА МЕСЯЦ при оплате сразу за 12 месяцев. NULL = период не продаётся.';

-- ⚠️ Сколько месяцев оплачено — в ЗАКАЗЕ, а не в тарифе: по нему вебхук решает,
-- на сколько продлевать. Без этого поля оплата за год давала бы 30 дней.
-- DEFAULT 1 — все прошлые заказы были помесячными.
ALTER TABLE subscription_orders
  ADD COLUMN IF NOT EXISTS months INTEGER NOT NULL DEFAULT 1;

