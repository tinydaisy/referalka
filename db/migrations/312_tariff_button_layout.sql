-- 312. Кнопка тарифа на лендинге: ширина и положение.
--
-- Зачем. Кнопка в карточке тарифа была жёстко растянута во всю ширину карточки
-- и текстом по центру. Это годится не всем: на широкой карточке кнопка
-- «Выбрать» превращается в полосу через весь блок и выглядит тяжело, а при
-- выравнивании содержимого влево — спорит с остальным текстом карточки.
--
-- Настраивается на БЛОКЕ, а не на каждом тарифе: кнопки в ряду карточек
-- обязаны выглядеть одинаково, иначе ряд визуально разъезжается.
--
-- NULL = прежнее поведение (во всю ширину, по центру) — у кого настроено,
-- ничего не меняется.
ALTER TABLE event_landing_blocks
  -- 'full'  — во всю ширину карточки (как было, дефолт)
  -- 'auto'  — по размеру текста
  ADD COLUMN IF NOT EXISTS btn_width TEXT,
  -- 'center' (дефолт) | 'left' | 'right' — куда прижата кнопка,
  -- когда она уже по размеру текста
  ADD COLUMN IF NOT EXISTS btn_align TEXT;

