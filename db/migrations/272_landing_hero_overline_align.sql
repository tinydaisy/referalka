-- 272: Надзаголовок и выравнивание шапки лендинга.
--
-- ⚠️ Зачем надзаголовок (overline). Название события в шапке одно — h1 из
-- events.title. Но у события часто есть ДВЕ смысловые части: тип («Фестиваль
-- практик и медитаций») и собственно имя («Г.У.Р.У.»). Раньше их приходилось
-- сваливать в одну строку — имя терялось. Пилюля (kicker) для этого мала:
-- она мелкая и в одну строку, а тип события просится крупной строкой над
-- названием.
--
-- ⚠️ Зачем выравнивание. Шапка была жёстко по центру. На фоновых фотографиях
-- со смысловым объектом сбоку (человек, предмет) текст по центру ложится
-- прямо на объект. Сдвиг блока текста влево/вправо решает это без правки
-- самой картинки.
--
-- NULL/пусто = прежнее поведение: надзаголовка нет, шапка по центру.

ALTER TABLE event_landing_blocks
  ADD COLUMN IF NOT EXISTS overline      TEXT,   -- строка НАД названием события
  ADD COLUMN IF NOT EXISTS overline_size SMALLINT,  -- кегль надзаголовка, px
  -- center (по умолчанию) | left | right — куда прижат весь блок шапки
  ADD COLUMN IF NOT EXISTS hero_align    TEXT NOT NULL DEFAULT 'center';

GRANT SELECT, INSERT, UPDATE, DELETE ON event_landing_blocks TO plusson;
