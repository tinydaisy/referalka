-- 213: (1) В коллабе ВСЕ организаторы равноправны → role='owner' у всех.
--      (2) Предзаполнение текста политики клиентам, у кого его нет.
--
-- (1) «Создателя» как особой роли в коллабе нет — организаторы равноправны.
--     Роль co_owner осталась от старой логики приглашений. Никаких прав она не даёт:
--     во всём коде role используется только как тай-брейкер
--     `ORDER BY (role='owner') DESC, id LIMIT 1` (выбрать клиента события по умолчанию).
--     После этой миграции сортировка выберет организатора с наименьшим id — это ок.
--     DEFAULT колонки уже 'owner', код тоже переведён на 'owner'.
UPDATE event_owners SET role = 'owner' WHERE role = 'co_owner';

-- (2) Политика обработки персональных данных.
--     ⚠️ Раньше шаблон показывался как серый placeholder → поле было ПУСТЫМ, публикация
--     блокировалась (нужно ≥100 символов), и у 97 из 101 клиента политики не было вовсе,
--     а `/c/{id}/privacy` отдавал 404 — то есть ссылка в согласии 152-ФЗ вела в никуда.
--     Кладём готовый текст ЧЕРНОВИКОМ. Публикацию (privacy_policy_published_at) НЕ ставим:
--     она требует юр-данных оператора (ФИО/ИНН/адрес/email), которых у большинства нет.
--     Клиент открывает Настройки → Юр.данные, видит красную плашку, заполняет реквизиты
--     и жмёт «Опубликовать».
