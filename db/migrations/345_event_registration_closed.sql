-- 345: «Регистрация ещё не открыта» — событие видно, записаться нельзя.
--
-- Зачем. Дата и тема события уже известны, а показывать нечего: спикеры
-- собираются, программа не утверждена, лендинга нет. Раньше выбор был из двух
-- крайностей — держать в черновике (тогда события не видно вовсе, и о нём
-- невозможно объявить) либо опубликовать и звать записываться туда, где
-- записываться не на что.
--
-- ⚠️ Это НЕ новый статус события. `status` отвечает за «видно ли событие
-- вообще», а здесь — «что показать пришедшему». Смешивать нельзя: иначе
-- клиенту придётся объяснять разницу между «Анонс» и «Опубликовано», а весь
-- код, который проверяет status='published', пришлось бы переучивать.
--
-- ⚠️⚠️ Показывается ОТДЕЛЬНАЯ СТРАНИЦА, а не «та же страница без кнопки».
-- Причина в устройстве Mini App: когда у события есть лендинг (свой или
-- сторонний), экран события УВОДИТ на него автоматически, ещё до отрисовки —
-- кнопки «Хочу участвовать» человек не видит вовсе. Заменять «кнопку на текст»
-- там было бы негде: заменять нечего. Поэтому при закрытой регистрации все
-- входы (Mini App, веб-страница, бот, витрина событий, короткая ссылка)
-- показывают одну общую страницу-заглушку и никуда не уводят.
ALTER TABLE events ADD COLUMN IF NOT EXISTS registration_closed BOOLEAN NOT NULL DEFAULT FALSE;

-- Крупный текст под описанием — главное на странице: когда откроется
-- регистрация. Пусто → формулировка из кода.
ALTER TABLE events ADD COLUMN IF NOT EXISTS pre_reg_text TEXT;

-- Необязательная кнопка: подпись + произвольная ссылка. Нужна, чтобы событие
-- без регистрации всё-таки вело куда-то — «Выступить спикером», «Стать жюри»,
-- «Написать организатору». Кнопка ОДНА: список кнопок на странице-заглушке
-- превращается в меню, а у неё одна задача — не оставить человека без действия.
ALTER TABLE events ADD COLUMN IF NOT EXISTS pre_reg_btn_label TEXT;
ALTER TABLE events ADD COLUMN IF NOT EXISTS pre_reg_btn_url TEXT;

-- ⚠️ Афиша хранится КОЛОНКОЙ, а не строкой в event_posters, хотя в интерфейсе
-- стоит среди афиш. Причина: `event_posters.orientation` ограничен CHECK-ом
-- ('horizontal'|'vertical'|'square'), и четвёртый вид потребовал бы расширить
-- ограничение, а затем отфильтровывать его в КАЖДОМ месте, которое берёт
-- «афишу события», — таких запросов 31 в 18 файлах (они уже фильтруют
-- `day IS NULL` после афиш дней). Один забытый фильтр молча подменил бы
-- боевую афишу временной — на лендинге, в рассылке или в Mini App.
--
-- Отдельная колонка нужна и по сути: временная картинка живёт, пока
-- регистрация закрыта, а финальную клиент готовит параллельно. Обе должны
-- существовать одновременно, иначе в день запуска пришлось бы ещё и
-- перезаливать афишу поверх временной.
ALTER TABLE events ADD COLUMN IF NOT EXISTS pre_reg_poster_url TEXT;
