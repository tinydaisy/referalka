-- 406: Вкладка «Интро» в Mini App — показывать или нет, решает клиент.
--
-- Зачем. Экран-поздравление после регистрации («В этом приложении у вас:»
-- с плитками разделов) одним клиентам нужен как онбординг, другим только
-- отодвигает от содержимого события. 11.09.2026 его отключили всем разом
-- прямо в коде — то есть у тех, кому он был нужен, он пропал без спроса.
-- Теперь это настройка события, а не решение в коде.
--
-- ⚠️ DEFAULT TRUE и NOT NULL: у всех существующих событий вкладка остаётся
-- ровно там, где была. Выключение — осознанное действие клиента.
--
-- ⚠️ НЕ ПУТАТЬ с events.welcome_enabled — та колонка про ПИСЬМО о регистрации
-- (welcome_text / welcome_email_subject рядом), к вкладке отношения не имеет.
--
-- ⚠️ Шлюз подписки на каналы живёт в этой же вкладке. Выключенная галочка его
-- НЕ отключает: при закрытом шлюзе «Интро» показывается всё равно, иначе
-- человеку негде подписаться и он упрётся в замки без объяснения.

ALTER TABLE events
    ADD COLUMN IF NOT EXISTS show_welcome_tab BOOLEAN NOT NULL DEFAULT TRUE;

COMMENT ON COLUMN events.show_welcome_tab IS
    'Показывать вкладку «Интро» в Mini App после регистрации. '
    'Шлюз подписки показывается независимо от этого флага.';
