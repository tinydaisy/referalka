-- 466: порядок спикеров по рядам — ОТДЕЛЬНО ДЛЯ КАЖДОГО ДНЯ.
--
-- ⚠️⚠️ ЗАЧЕМ. Афиши по дням (миграция 459) хранят настройки одной строкой на
-- (event_id, 'day', orientation) — дня в ключе нет. Для цвета, шрифта и полей
-- это правильно: оформление у всех дней одно. Но `speaker_rows` (миграция 445)
-- так хранить нельзя: в первый день выступают одни люди, во второй другие, и
-- один общий список рядов для них бессмысленен.
--
-- Что видел клиент: расставил ряды на дне 1, открыл день 2 — там его спикеров
-- в сохранённом порядке нет вовсе, и они сваливаются в авторасстановку.
-- Переставил на дне 2 — сломал день 1. «Порядок надо отдельно по каждому дню»
-- (владелец, 19.09.2026).
--
-- ⚠️ ПОЧЕМУ НЕ НОВАЯ СТРОКА НА КАЖДЫЙ ДЕНЬ. Можно было добавить `day` в ключ
-- уникальности и плодить по строке на день. Тогда оформление (шрифты, поля,
-- фон) пришлось бы дублировать в каждую строку и править во всех сразу —
-- ровно та беда, из-за которой в 459 виды разделили, а дни оставили общими.
-- Здесь же по дням расходится РОВНО ОДНА настройка, и ей достаточно словаря.
--
-- Формат: {"1": [[12,5],[7,9]], "2": [[3,4]]} — ключ это номер дня строкой
-- (JSON не умеет числовые ключи), значение — те же ряды, что в `speaker_rows`.
-- Дня нет в словаре — раскладываем автоматически, как сейчас.

BEGIN;

ALTER TABLE event_poster_layouts
  ADD COLUMN IF NOT EXISTS day_speaker_rows JSONB NOT NULL DEFAULT '{}'::jsonb;

-- ⚠️ Именно объект, а не массив: ключ — номер дня. Без проверки сюда однажды
-- приедет массив, и чтение по ключу молча вернёт пусто.
ALTER TABLE event_poster_layouts
  DROP CONSTRAINT IF EXISTS event_poster_layouts_day_rows_check;
ALTER TABLE event_poster_layouts
  ADD CONSTRAINT event_poster_layouts_day_rows_check
  CHECK (jsonb_typeof(day_speaker_rows) = 'object');

COMMENT ON COLUMN event_poster_layouts.day_speaker_rows IS
  'Ряды спикеров ОТДЕЛЬНО по дням: {"1": [[id,id],[id]], "2": [...]}. '
  'Пусто для дня — авторасстановка. Применяется только к kind=''day''';

GRANT SELECT, INSERT, UPDATE, DELETE ON event_poster_layouts TO plusson;

COMMIT;
