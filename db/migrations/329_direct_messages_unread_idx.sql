-- 329: индекс под «непрочитанные сверху» в списке контактов.
--
-- Зачем. В списке контактов (/dashboard/clients) без фильтров контакты с
-- непрочитанными сообщениями поднимаются наверх, и рядом с именем рисуется
-- счётчик. И сортировка, и счётчик спрашивают у direct_messages одно и то же:
-- «есть ли у этого контакта входящие, которые ещё не прочли».
--
-- ⚠️ Индекс ЧАСТИЧНЫЙ (WHERE direction='in' AND NOT is_read). Непрочитанных в
-- переписке всегда единицы, тогда как всего сообщений десятки тысяч: полный
-- индекс по тем же колонкам весил бы в сотни раз больше и переписывался бы на
-- каждой отправке. Частичный вдобавок худеет сам — прочитанное сообщение из
-- него выпадает.
--
-- Существующий direct_messages_contact_idx (client_id, contact_id, sent_at)
-- здесь не помогает: он ничего не знает про is_read, и Postgres пришлось бы
-- отсеивать прочитанные уже после чтения строк.

CREATE INDEX IF NOT EXISTS direct_messages_unread_idx
    ON direct_messages (client_id, contact_id)
    WHERE direction = 'in' AND NOT is_read;
