-- Миграция 205: кастомные кнопки «Общего приветствия» VIP-бота клиента.
-- Раньше приветствие на голый /start имело ровно 2 кнопки (события / об основателе),
-- тексты которых хранились в start_btn_events_label / start_btn_owner_label.
-- Теперь клиент сам собирает список кнопок (до 5), у каждой один из 3 типов:
--   events — готовая ссылка «Все события»    (pluson.ru/o/{id})       — меняется только текст;
--   owner  — готовая ссылка «Об основателе»  (pluson.ru/o/{id}?tab=ecosystem) — меняется только текст;
--   custom — произвольная: свой текст + любой URL.
-- Формат: JSONB-массив [{ "type": "events|owner|custom", "label": "...", "url": "..." }].
-- NULL / пустой массив → обратная совместимость: резолвер соберёт 2 кнопки из старых полей.

ALTER TABLE clients
  ADD COLUMN IF NOT EXISTS start_buttons JSONB;
