-- 423: раздельное выравнивание внутри карточек + подарки у партнёров
--
-- ⚠️ ЧТО БЫЛО СЛОМАНО. «Выравнивание текста секции» (`title_align`) управляло
-- заголовком и содержимым разом, а у карточек партнёров поверх этого стоял
-- жёсткий `text-center` прямо в вёрстке. Клиент выбирал в секции «Слева», а
-- регалии партнёров всё равно вставали по центру — настройка на них не
-- действовала вовсе.
--
-- Теперь внутри карточки две независимые настройки:
--   card_name_align — имя, бейдж роли и ДОЛЖНОСТЬ (обычно по центру);
--   card_text_align — РЕГАЛИИ, перечень (читается только слева).
-- Выравнивание самого заголовка секции остаётся за `title_align`.
--
-- ⚠️ NULL = прежний вид, и это главное: у спикеров всё было слева, у
-- партнёров — по центру. Дефолт колонки не ставим, иначе уже собранные
-- лендинги поехали бы сами (решение владельца: «оставить как сейчас»).

ALTER TABLE event_landing_blocks
  ADD COLUMN IF NOT EXISTS card_name_align TEXT,
  ADD COLUMN IF NOT EXISTS card_text_align TEXT;

-- Значения ('left'|'center'|'right') проверяются В КОДЕ (normalize_block_gift),
-- а не CHECK-ом — как btn_width, card_style и survey_view: новый вариант тогда
-- добавляется кодом, без миграции, а мусор приводится к дефолту, а не роняет
-- запрос.

COMMENT ON COLUMN event_landing_blocks.card_name_align IS
  'Выравнивание имени и должности в карточке. NULL = прежний вид блока.';
COMMENT ON COLUMN event_landing_blocks.card_text_align IS
  'Выравнивание регалий в карточке. NULL = прежний вид блока.';
