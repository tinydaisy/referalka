-- 403. Тестовые аккаунты техспецов + разделение «в отпуске» и «уволился».
--
-- ── 1. Тестовые аккаунты ───────────────────────────────────────────────────
-- Техспецы заводят себе кабинеты, чтобы проверить платформу руками. В списке
-- «Клиенты без ответственного» такой кабинет неотличим от настоящего лида —
-- его берут в работу, распределяют, пытаются оживить. Пометка убирает их
-- оттуда и из статистики.
--
-- ⚠️ Флаг на КЛИЕНТЕ, а не на техспеце: кабинет — это `clients`, и распределение
-- идёт по нему. Связи «кто именно из спецов его завёл» намеренно нет — важно
-- только «это не живой клиент», а кто создал, видно по `referred_by_tech_id`.
--
-- ── 2. Работает / уволился ─────────────────────────────────────────────────
-- У `tech_specialists` уже есть `is_active`, но он отвечает СРАЗУ ЗА ДВА
-- разных состояния: пускать ли в кабинет и можно ли давать новых клиентов.
-- Из-за этого «человек в отпуске» и «человек уволился» выражаются одинаково —
-- снятием одной галочки, после чего он теряет и доступ к своим начислениям.
--
-- Теперь состояния разведены:
--   `is_active`   — РАБОТАЕТ ЛИ ВООБЩЕ (уволился → FALSE, кабинет закрыт);
--   `takes_clients` — берёт ли НОВЫХ клиентов (отпуск, загрузка → FALSE,
--                     кабинет и начисления остаются).
--
-- ⚠️ Значение по умолчанию TRUE и бэкфилл по `is_active`: у действующих спецов
-- поведение не меняется, иначе после миграции распределять стало бы некому.

ALTER TABLE clients
  ADD COLUMN IF NOT EXISTS is_tech_test BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN clients.is_tech_test IS
  'Тестовый кабинет техспеца: не распределяется, не считается в статистике.';

ALTER TABLE tech_specialists
  ADD COLUMN IF NOT EXISTS takes_clients BOOLEAN NOT NULL DEFAULT TRUE;

COMMENT ON COLUMN tech_specialists.takes_clients IS
  'Берёт ли новых клиентов. FALSE — отпуск или перегруз: кабинет и начисления '
  'остаются, распределение не идёт. Уволился — это is_active = FALSE.';

-- ⚠️ Уволенным новых клиентов не даём и после миграции: у них `is_active`
-- уже FALSE, значит и `takes_clients` должен быть FALSE — иначе они всплывут
-- в списке «кому назначить».
UPDATE tech_specialists SET takes_clients = FALSE WHERE NOT is_active;

-- ⚠️ Частичный индекс — по нему строится список «кому можно назначить».
CREATE INDEX IF NOT EXISTS idx_tech_specialists_available
    ON tech_specialists (id) WHERE is_active AND takes_clients;

-- ⚠️ Индекс по «живым» клиентам: тестовые исключаются в каждом запросе
-- распределения, без него он читал бы таблицу целиком.
CREATE INDEX IF NOT EXISTS idx_clients_real
    ON clients (created_at DESC) WHERE NOT is_tech_test;
