-- 285: Квадратик-цифра + разделение анкет (2026-08-13)
--
-- Зачем. «Квадратик» в понимании владельца (и в GetCourse, откуда она
-- уходит) — это ПЛИТКА С ОДНОЙ ЦИФРОЙ: «200-300 т.р. — 176 пользователей».
-- Первая версия делала карточку со списком всех вариантов сразу — это
-- другое. Теперь есть оба вида, вид выбирается при генерации.

-- view: 'list' — карточка со всеми вариантами (как было),
--       'tile' — одна крупная цифра по конкретному варианту.
ALTER TABLE analytics_cards
    ADD COLUMN IF NOT EXISTS view TEXT NOT NULL DEFAULT 'list'
        CHECK (view IN ('list', 'tile'));

-- Какой именно вариант показывает плитка ('200.000- 300.000 рублей').
-- NULL у вида 'tile' = «сколько всего ответили на этот вопрос».
ALTER TABLE analytics_cards
    ADD COLUMN IF NOT EXISTS option_value TEXT;

-- ⚠️ Один и тот же вопрос («Сколько вам лет?», «Готовы выступать спикером?»)
-- заведён в КАЖДОЙ из анкет клиента отдельной строкой survey_questions.
-- Автогенерация «взять все вопросы» плодила по 4 одинаковых квадратика.
-- Решение владельца: считать в рамках ОДНОЙ анкеты — поэтому при генерации
-- сначала выбирается анкета, и сюда пишется её id (для показа в подписи и
-- чтобы не смешивать аудитории зрителей и номинантов).
ALTER TABLE analytics_cards
    ADD COLUMN IF NOT EXISTS survey_id INTEGER REFERENCES surveys(id) ON DELETE SET NULL;
