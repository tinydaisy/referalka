-- 501. Генератор афиш — открыть тарифу «Экстра» (vip)
--
-- Было (миграция 436, 18.09.2026): фича `poster_generator` выдана ТОЛЬКО
-- скрытому тарифу `admin` — «делай пока у админов», возможность не обкатана
-- на живых событиях.
--
-- Стало (решение владельца 23.09.2026): обкатали, открываем клиентам —
-- но не всем, а тарифу «Экстра» (`vip`). Генератор собирает афишу сам,
-- включая индивидуальные афиши каждому спикеру: это тяжёлая возможность
-- (headless Chrome на каждую картинку) и заметная разница между тарифами.
--
-- ⚠️ ПРАВОК КОДА НЕ НУЖНО — и в этом был смысл гейта по ФИЧЕ, а не по
-- `client_id`. `_guard` в `event_posters_gen.py` и подвкладка в кабинете
-- читают фичу из тарифа: добавили строку — возможность появилась.
--
-- ⚠️ В `trial` руками НЕ пишем: триал зеркалит фичи Профи автоматически
-- (`_mirror_pro_features_to_trial`), а Профи генератор не получает.

BEGIN;

INSERT INTO tariff_features (tariff_id, feature_id)
SELECT t.id, f.id
  FROM tariffs t
  CROSS JOIN features f
 WHERE t.slug = 'vip' AND f.slug = 'poster_generator'
ON CONFLICT DO NOTHING;

COMMIT;
