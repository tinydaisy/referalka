-- 399. Лид-магнит «Доступ к ПЛЮСОНу»: ссылка на бот платформы (10.09.2026).
--
-- ЗАЧЕМ.
-- Клиент раздаёт своей аудитории доступ к ПЛЮСОНу и получает приведённых людей
-- по своей партнёрской ссылке. Ссылка РАЗНАЯ у каждой площадки (у ВКонтакте
-- код уходит параметром `ref`, а не `start`), и собирать её руками клиент не
-- должен — иначе он вставит телеграмную ссылку всем, и пришедшие из MAX и ВК
-- уйдут в чужой мессенджер.
--
-- Расширяем существующий `link_source` вместо новой колонки: он уже отвечает
-- ровно на вопрос «откуда берётся ссылка материала» (`fixed` — вписана руками,
-- `support` — служба заботы клиента). Заводить рядом второй флаг значило бы
-- два поля об одном и том же, которые рано или поздно разойдутся.
--
--   plusson_self     — ссылка ВЛАДЕЛЬЦА бота: приведённый достаётся тому, в
--                      чьей воронке лежит подарок. Обычный случай.
--   plusson_referrer — ссылка РЕФОВОДА забега: человек пришёл в бот Кати по
--                      ссылке Алёны — регистрация закрепляется за Алёной.
--
-- ⚠️⚠️ `plusson_referrer` — ТОЛЬКО ДЛЯ admin (решение владельца 10.09.2026).
-- Проверено на боевых данных: из 3704 забегов воронок рефовод не указан НИ В
-- ОДНОМ. То есть режим почти никогда не срабатывает, и обычному клиенту он
-- будет непонятен: он увидит выбор, смысла которого не поймёт, и выберет
-- наугад. Прячем гейтом по тарифу, а не убираем — владельцу он нужен.
--
-- ⚠️ ЗАПАСНОЙ ВАРИАНТ ОБЯЗАТЕЛЕН: при `plusson_referrer` рефовода может не
-- оказаться (пришёл по общей ссылке) либо он не клиент ПЛЮСОНа — тогда его код
-- не резолвится. В этом случае отдаём ссылку ВЛАДЕЛЬЦА, а не пустоту: подарок
-- без ссылки хуже, чем подарок, приведший человека не тому.

BEGIN;

ALTER TABLE lead_magnets DROP CONSTRAINT IF EXISTS lead_magnets_link_source_check;

ALTER TABLE lead_magnets
    ADD CONSTRAINT lead_magnets_link_source_check
    CHECK (link_source = ANY (ARRAY[
        'fixed'::text,             -- ссылка вписана руками (как было)
        'support'::text,           -- служба заботы клиента
        'plusson_self'::text,      -- бот ПЛЮСОНа, реф-код ВЛАДЕЛЬЦА бота
        'plusson_referrer'::text   -- бот ПЛЮСОНа, реф-код РЕФОВОДА (только admin)
    ]));

COMMENT ON COLUMN lead_magnets.link_source IS
    'Откуда берётся ссылка материала: fixed — вписана руками; support — служба '
    'заботы клиента; plusson_self — бот ПЛЮСОНа с реф-кодом владельца бота; '
    'plusson_referrer — то же, но с кодом рефовода забега (только admin, при '
    'отсутствии рефовода падает на plusson_self)';

COMMIT;
