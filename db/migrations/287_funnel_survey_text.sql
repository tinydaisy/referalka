-- 287: Редактируемый текст «сначала анкета» в шаблоне воронки (2026-08-13)
--
-- Зачем. Когда подарок закрыт анкетой (`lead_magnets.require_survey_id`),
-- человек после подписки получает отдельное сообщение с ссылкой на анкету.
-- Текст этого сообщения был ЗАШИТ в коде (`survey_prompt_text`) — клиент не
-- мог его поправить, хотя правит все остальные тексты воронки рядом.
--
-- ⚠️ Порядок шагов при этом НЕ меняется и менять его не надо:
--   подписка на канал → сообщение про анкету → выдача материала.
-- Требование заполнить анкету не должно попадать в Текст 1 вместе с
-- просьбой подписаться: два требования сразу человек не разбирает.

ALTER TABLE funnel_templates
    ADD COLUMN IF NOT EXISTS text_survey TEXT;

