-- 324: адрес страницы спикера — случайный код вместо номера клиента (2026-08-22)
--
-- Зачем. Было `/sp/{client_id}` — то есть `/sp/1`, `/sp/2`, `/sp/3`. Такой адрес
-- подбирается перебором: набрал соседнее число и смотришь материалы чужого
-- клиента. Страница публичная по замыслу, но показывать её должен ТОТ, КОМУ
-- она принадлежит, а не случайный любопытный.
--
-- Теперь `/sp/{код}` — 10 символов из алфавита без похожих букв (нет 0/o/1/l/i),
-- как у slug событий и лид-магнитов. Перебрать 30^10 вариантов нереально.
--
-- ⚠️ Старый адрес `/sp/{id}` продолжает работать: ссылку могли уже кому-то
-- отдать. Новый код показывается в кабинете, номерной остаётся как запасной.

ALTER TABLE clients
  ADD COLUMN IF NOT EXISTS speaker_page_slug TEXT;

-- Заполняем существующим клиентам, иначе у них не будет адреса вовсе.
-- gen_random_uuid() есть в pgcrypto/PG13+; берём hex и режем до 10 символов,
-- потом заменяем визуально похожие символы на безопасные.
UPDATE clients
   SET speaker_page_slug = translate(
         substr(replace(gen_random_uuid()::text, '-', ''), 1, 10),
         '01l', 'xyz')
 WHERE speaker_page_slug IS NULL;

-- Код обязан быть уникальным — по нему ищем клиента.
CREATE UNIQUE INDEX IF NOT EXISTS uq_clients_speaker_page_slug
    ON clients (speaker_page_slug) WHERE speaker_page_slug IS NOT NULL;

COMMENT ON COLUMN clients.speaker_page_slug IS
  'Код публичной страницы спикера: pluson.ru/sp/{код}. Случайный, чтобы чужую '
  'страницу нельзя было открыть перебором номеров.';

