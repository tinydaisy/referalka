-- 413: Отметки писем об ОЖИДАНИИ в очереди автонастройки.
--
-- Зачем. Человек нажал «Настроить», работа не началась сразу — и он не знает
-- ничего: экран он мог закрыть, а письмо уходило только когда бот уже готов.
-- Теперь два письма: «заявка принята» (если не началось за 2 минуты) и
-- «ещё в очереди» (если ждём больше 10 минут) с точным временем возврата,
-- когда оно известно.
--
-- ⚠️⚠️ ОТМЕТКИ, А НЕ «ПРОШЛО ЛИ N МИНУТ». Поллер бежит каждую минуту: без
-- отметки письмо «заявка принята» ушло бы 10 раз за 10 минут. Та же причина,
-- по которой у напоминаний есть `reminders_sent` (см. `remind`).
ALTER TABLE service_orders
  ADD COLUMN IF NOT EXISTS queued_notice_at   TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS delay_notice_at    TIMESTAMPTZ;

COMMENT ON COLUMN service_orders.queued_notice_at IS
  'Когда отправлено письмо «заявка принята, ждёт очереди». NULL — не отправлялось.';
COMMENT ON COLUMN service_orders.delay_notice_at IS
  'Когда отправлено письмо «всё ещё в очереди». NULL — не отправлялось.';
