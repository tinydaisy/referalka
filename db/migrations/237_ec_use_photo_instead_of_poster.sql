-- 237: Тумблер «не использовать индивидуальную афишу спикера»
--
-- Зачем. У части спикеров индивидуальные афиши сделаны под конкретную
-- айдентику события (например, «с кокошниками» у iViSiON-8). Для другого
-- события такая афиша не подходит, а удалять её из библиотеки коллаба
-- нельзя — она нужна там, где делалась.
--
-- Решение: per-event тумблер на карточке спикера. TRUE = в ЭТОМ событии
-- индивидуальная афиша не используется вовсе, везде (рассылки бота, Mini App,
-- лендинг, виджет лендинга, кабинет спикера, экспорт материалов) вместо неё
-- берётся обычное фото коллаборатора (collaborators.photo_url).
--
-- FALSE (default) = прежнее поведение: афиша из библиотеки, fallback на фото.
-- Библиотека афиш при этом не трогается — тумблер только про использование.

ALTER TABLE event_collaborators
  ADD COLUMN IF NOT EXISTS use_photo_instead_of_poster BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN event_collaborators.use_photo_instead_of_poster IS
  'TRUE = в этом событии не использовать индивидуальную афишу спикера, '
  'везде брать обычное фото коллаборатора (collaborators.photo_url). '
  'Миграция 237.';
