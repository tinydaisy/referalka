--
-- ЗАЧЕМ. Коллабораторная перестаёт быть источником дохода и становится
-- инструментом ПРИВЛЕЧЕНИЯ: человек приходит на пробный период, сразу видит
-- партнёров и совместные события — то, чего нет больше нигде, — и остаётся
-- ради этого. Владелец: «у меня нет ресурса уговаривать покупать каждый месяц,
-- я буду давать акции: две проведённые активности дают бесплатное пользование,
-- иначе вылетают». То есть удержание переносится с уговоров на активность.
--
-- ⚠️⚠️ ЗА КОЛЛАБОРАТОРНУЮ СЕЙЧАС ПЛАТЯТ 17 КЛИЕНТОВ по 1000 ₽/мес. Их доступ
-- этой миграцией НЕ ТРОГАЕТСЯ: аддон остаётся, `client_addons` не изменяется,
-- деньги не возвращаются. Владелец предупреждён и решил, что скажет им о
-- возможности пользоваться дальше — это её решение, а не побочный эффект.
--
-- ⚠️⚠️ ТОЛЬКО В ТРИАЛ, В ПРОФИ НЕ ДОБАВЛЯЕМ (решение владельца). Это НАМЕРЕННОЕ
-- отступление от правила «триал = Профи»: коллаба здесь — приманка пробного
-- периода, а не часть платного тарифа. Кто остаётся на Профи — покупает её
-- отдельно, как и раньше.
--
-- ⚠️ Из-за этого триал на ОДНУ фичу богаче Профи. Не «чинить» автоматическим
-- зеркалированием pro → trial: оно добавляет триалу фичи Профи, но обратно
-- ничего не отбирает, так что коллаба у триала переживёт следующую сверку.
--
-- ⚠️ ПРОДАЖУ АДДОНА НЕ ЛОМАЕТ. `GET /addons` уже умеет показывать «входит в
-- ваш тариф» (поле `in_tariff` считается из `tariff_features`) и не предлагает
-- купить то, что и так есть. Правок кода не потребовалось.
--
-- ⚠️ `features.is_addon` НЕ снимаем: у клиентов на тарифах БЕЗ коллабы (Профи,
-- Экстра, Бизнес) она по-прежнему покупается отдельно. Снять флаг значило бы
-- убрать её из витрины модулей вовсе.

BEGIN;

INSERT INTO tariff_features (tariff_id, feature_id)
SELECT t.id, f.id
  FROM tariffs t
  CROSS JOIN features f
 WHERE t.slug = 'trial'
   AND f.slug = 'collab_hub'
ON CONFLICT DO NOTHING;

COMMIT;
