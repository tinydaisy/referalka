-- 434: точка лица на фото («где нос») — чтобы миниатюры не срезали голову.
--
-- ⚠️ ЗАЧЕМ. Фото человека везде показывается с `object-fit: cover`: картинка
-- заполняет рамку, лишнее режется по краям. Резалось всегда ОТ ЦЕНТРА, и на
-- вертикальном снимке в полный рост в квадратную миниатюру попадал живот, а
-- голова уезжала за верхний край. Обратный случай: портрет крупным планом с
-- большим отступом сверху — макушка срезалась.
--
-- Значение — ровно то же, что у CSS `object-position`: проценты по горизонтали
-- и вертикали, строкой. '50% 50%' = центр (прежнее поведение), '50% 30%' =
-- кадр держится за точку, стоящую на 30 % высоты фото.
--
-- ⚠️ ХРАНИМ ПРОЦЕНТЫ, А НЕ ПИКСЕЛИ. Одно и то же фото показывается в рамках
-- разного размера и разной формы (круг 40 px в программе, квадрат карточки,
-- прямоугольник 3:4 в библиотеке, афиша). Пиксели пришлось бы пересчитывать под
-- каждый показ; проценты работают во всех рамках одинаково.
--
-- ⚠️ ТОЧКА У ФОТО, А НЕ У ЧЕЛОВЕКА. У одного спикера основное фото, вырезка на
-- прозрачном фоне и снимки в библиотеке скадрированы по-разному: на одном лицо
-- в центре, на другом человек стоит сбоку в полный рост. Одно поле на человека
-- поправило бы один снимок и испортило остальные.
--
-- ⚠️ NULL = «не отмечено», и это НЕ то же самое, что '50% 50%'. По NULL показ
-- применяет умолчание (лицо ищем в верхней трети кадра — см. код), а явные
-- '50% 50%' означают «клиент посмотрел и сказал: именно центр». Если проставить
-- всем центр сейчас, отличить одно от другого станет нельзя, и улучшенное
-- умолчание перестанет доезжать до тех, кто ничего не отмечал.

BEGIN;

-- Основное фото человека и его вырезка на прозрачном фоне.
-- Два отдельных поля: это два разных файла с разной композицией.
ALTER TABLE collaborators
  ADD COLUMN IF NOT EXISTS photo_focal        TEXT,
  ADD COLUMN IF NOT EXISTS cutout_photo_focal TEXT;

COMMENT ON COLUMN collaborators.photo_focal IS
  'Точка лица на основном фото в формате CSS object-position («50% 35%»). NULL = не отмечено';
COMMENT ON COLUMN collaborators.cutout_photo_focal IS
  'Точка лица на вырезке (прозрачный фон). NULL = не отмечено';

-- Библиотека фото спикера-клиента (мигр. 323) — там снимки того же человека,
-- и кадрированы они по-разному, поэтому точка нужна у каждой строки.
ALTER TABLE client_speaker_photos
  ADD COLUMN IF NOT EXISTS focal TEXT;

COMMENT ON COLUMN client_speaker_photos.focal IS
  'Точка лица на этом снимке («50% 35%»). NULL = не отмечено';

-- Фото владельца кабинета: он тоже выступает спикером, и его портрет попадает
-- в те же карточки, афиши и шапку Экосистемы.
ALTER TABLE clients
  ADD COLUMN IF NOT EXISTS owner_photo_focal   TEXT,
  ADD COLUMN IF NOT EXISTS profile_photo_focal TEXT;

COMMENT ON COLUMN clients.owner_photo_focal IS
  'Точка лица на фото основателя («50% 35%»). NULL = не отмечено';
COMMENT ON COLUMN clients.profile_photo_focal IS
  'Точка лица на фото бренда в шапке Экосистемы. NULL = не отмечено';

-- ⚠️ GRANT в той же миграции: без него рабочая роль не увидит новые колонки.
GRANT SELECT, INSERT, UPDATE, DELETE ON collaborators          TO plusson;
GRANT SELECT, INSERT, UPDATE, DELETE ON client_speaker_photos  TO plusson;
GRANT SELECT, INSERT, UPDATE, DELETE ON clients                TO plusson;

COMMIT;
