-- 420: Подарки спикера на лендинге + свой лимит регалий у клиента
--
-- 1) Блок «Спикеры» умеет показывать подарки спикера («Подарок участникам:»).
--    По умолчанию ВЫКЛЮЧЕНО — на уже собранных лендингах ничего не появится
--    само: подарок может быть внутренней договорённостью, и выводить его
--    наружу без спроса нельзя.
--
--    ⚠️ Цвет и прозрачность плашки — НАСТРОЙКИ, а не константы в вёрстке.
--    NULL = «как у блоков» (page.card_bg / card_bg_opacity): у клиента уже
--    настроены цвет и прозрачность карточек, и плашка обязана попадать в них
--    сама. Захардкоженный оттенок выбивался бы из темы у каждого второго.
--
-- 2) Лимит символов в регалиях спикера — тоже настройка клиента. Число 1100
--    жило константой в шести местах кода: клиенту, которому нужно длиннее
--    (или короче), поменять было нечем, кроме релиза. Заодно умолчание
--    платформы поднято до 1530 (решение владельца): на премиях в регалии идёт
--    список достижений номинанта, и 1100 обрезали его на полуслове.

ALTER TABLE event_landing_blocks
  -- Показывать ли подарки в карточках спикеров этого блока.
  ADD COLUMN IF NOT EXISTS show_speaker_gift   BOOLEAN NOT NULL DEFAULT FALSE,
  -- Подпись над списком. NULL → «Подарок участникам:» (дефолт в коде, не здесь:
  -- в БД дефолт-строкой его нельзя было бы отличить от осознанно выбранного
  -- клиентом такого же текста).
  ADD COLUMN IF NOT EXISTS speaker_gift_label  TEXT,
  -- Цвет плашки. NULL → цвет блоков темы (page.card_bg).
  ADD COLUMN IF NOT EXISTS speaker_gift_bg     TEXT,
  -- Прозрачность заливки, 0..100 (% непрозрачности, как card_bg_opacity).
  -- NULL → прозрачность блоков темы (page.card_bg_opacity).
  ADD COLUMN IF NOT EXISTS speaker_gift_opacity INT,
  -- Где показывать: 'after' — после регалий (по умолчанию), 'before' — до них.
  ADD COLUMN IF NOT EXISTS speaker_gift_position TEXT;

-- Значения проверяются В КОДЕ (normalize_block_gift), а не CHECK-ом — как
-- btn_width, card_style и survey_view: новый вариант раскладки добавляется
-- тогда кодом, без миграции, а мусор приводится к дефолту, а не роняет запрос.

COMMENT ON COLUMN event_landing_blocks.show_speaker_gift IS
  'Показывать подарки спикера в карточках блока «Спикеры». FALSE по умолчанию.';
COMMENT ON COLUMN event_landing_blocks.speaker_gift_opacity IS
  'Непрозрачность плашки подарка в %, 0..100. NULL = как у блоков (card_bg_opacity).';

-- ── Лимит регалий спикера ────────────────────────────────────────────────────
-- NULL = значение по умолчанию из кода (1530). Не ставим число дефолтом
-- колонки: тогда поменять «умолчание платформы» для всех сразу стало бы
-- невозможно — пришлось бы бэкфиллить каждого клиента.
ALTER TABLE clients
  ADD COLUMN IF NOT EXISTS speaker_achievements_limit INT;

COMMENT ON COLUMN clients.speaker_achievements_limit IS
  'Сколько символов клиент разрешает в регалиях спикера. NULL = умолчание платформы (1530).';

-- ── Расширенный лимит (решение владельца 16.09.2026) ────────────────────────
-- 1530 — новое умолчание платформы, и его получают ВСЕ клиенты (колонка пуста
-- → код берёт умолчание). Отдельный UPDATE Марго Форбс и Лилии Гришиной не
-- нужен: расширенный лимит у них уже действует.
--
-- ⚠️ Проставлять им то же число ЯВНО было бы вредно: тогда они перестали бы
-- следовать за умолчанием платформы, и следующее его изменение обошло бы
-- ровно тех двоих, ради кого лимит и поднимали.
