-- 314: повтор кнопки регистрации под описанием события — ПО ГАЛОЧКЕ.
--
-- У события с длинным описанием кнопка «Хочу участвовать» уезжает далеко вверх,
-- и дочитавший до конца человек не понимает, что делать дальше, — приходится
-- скроллить обратно. Повтор кнопки внизу это снимает.
--
-- Почему галочка, а не «если описание длиннее N символов». Порог всегда врёт:
-- у одного клиента три абзаца — это уже много, у другого длинный текст свёрстан
-- так, что вторая кнопка мешает. Клиент видит свою страницу и решает сам
-- (решение владельца, 2026-08-18).
--
-- FALSE по умолчанию: у кого настроено сейчас, ничего не меняется.
ALTER TABLE events
  ADD COLUMN IF NOT EXISTS landing_cta_repeat BOOLEAN NOT NULL DEFAULT FALSE;
