-- Демо-лид-магниты автонастройки: помечаем, из какого решения они созданы.
--
-- Зачем. В конце автонастройки клиенту создаются две рабочие заготовки
-- (решение 1 «Выдача материала за подписку» и решение 4 «Запись на
-- консультацию») — чтобы бот сразу что-то умел, а человек мог проверить
-- выдачу на себе и заменить тексты на свои.
--
-- ⚠️⚠️ БЕЗ МЕТКИ ИХ НЕЛЬЗЯ ОТЛИЧИТЬ ОТ СОБСТВЕННЫХ магнитов клиента: у него
-- их бывают десятки, и понять, какой создан автоматически, а какой он завёл
-- сам, не по чему. Метка нужна экрану итога — он показывает ссылки именно на
-- эти два и подписывает, что их надо заменить на своё.
--
-- ⚠️ Храним НОМЕР РЕШЕНИЯ, а не просто «да/нет»: заготовки из разных решений
-- ведут себя по-разному (одна отдаёт файл, другая — ссылку в личку), и в
-- итоге они подписаны по-своему. Номер совпадает с `SOLUTION_NUMS`
-- (backend/app/api/solutions.py) и с полем `num` во фронтовом каталоге.
--
-- ⚠️ NULL = обычный магнит клиента. Существующие записи не трогаются: у всех
-- них метки нет, и они остаются «своими».
ALTER TABLE lead_magnets
  ADD COLUMN IF NOT EXISTS demo_solution_num INTEGER;

COMMENT ON COLUMN lead_magnets.demo_solution_num IS
  'Номер решения, из которого магнит создан автонастройкой как демо. NULL — свой магнит клиента.';

CREATE INDEX IF NOT EXISTS idx_lead_magnets_demo
  ON lead_magnets(client_id, demo_solution_num)
  WHERE demo_solution_num IS NOT NULL;
