-- 367: смена почты в кабинете покупателя — код подтверждения на НОВЫЙ адрес.
--
-- Зачем. Почта в кабинете `/my` — это логин: код входа приходит на неё.
-- Разрешить правку «как обычное поле» нельзя: описка в адресе (лишняя точка,
-- чужая раскладка) навсегда отрезала бы человека от купленного, и чинить
-- пришлось бы вручную в базе. Ровно так владелец не мог войти в собственный
-- кабинет 07.09.2026: в базе почта была записана без точки, а вводил он свою
-- настоящую — с точкой.
--
-- Решение: новый адрес сначала подтверждается кодом, который уходит НА НЕГО.
-- Не подтвердил — почта не сменилась, вход продолжает работать по старой.
--
-- ⚠️ Переиспользуем существующую таблицу кодов, а не заводим вторую: механика
-- та же (одноразовый код, 15 минут, гасится `used_at`), и второй набор правил
-- протухания неминуемо разъехался бы с первым.
--
-- ⚠️ NULL в `new_email` — это обычный код ВХОДА (так работали все коды до
-- этой миграции). Непустой — код ПОДТВЕРЖДЕНИЯ новой почты. Подтверждение
-- ищется строго с совпадением адреса, поэтому код входа сменить почту не
-- может, а код смены — не пускает в кабинет.

ALTER TABLE product_cabinet_codes
    ADD COLUMN IF NOT EXISTS new_email TEXT;

COMMENT ON COLUMN product_cabinet_codes.new_email IS
    'Подтверждаемый новый адрес почты. NULL = обычный код входа в кабинет.';
