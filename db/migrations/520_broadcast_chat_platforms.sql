-- 520: Площадки ОТДЕЛЬНО для каждого вида чатов рассылки
--
-- Зачем. С 22.09.2026 чаты слушались «Каналов для отправки»: снял Telegram в
-- каналах — не уходило и в телеграмный чат. Из-за этого нельзя было отправить
-- ТОЛЬКО в чат одной площадки, не трогая личные сообщения по базе. Связь
-- откатили: «Каналы для отправки» снова управляют только личкой, а у каждого
-- вида чатов свои галочки площадок.
--
-- Формат: {"private": ["telegram","vk","max"],
--          "common":  ["telegram","vk","max","whatsapp"],
--          "event":   [...], "speakers": [...]}
-- NULL или нет ключа вида = ВСЕ площадки (по умолчанию все галочки стоят;
-- старые рассылки работают как до 22.09).
-- Рассылка без своего значения берёт значение шаблона — по тому же правилу,
-- что галочки чатов (chats_overridden, миграция 235).

ALTER TABLE broadcast_schedules ADD COLUMN IF NOT EXISTS chat_platforms JSONB;
ALTER TABLE broadcast_templates ADD COLUMN IF NOT EXISTS chat_platforms JSONB;
