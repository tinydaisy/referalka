-- 516: ФАКТ ВОСПРОИЗВЕДЕНИЯ у зрителя, а не «страница открыта»
--
-- ⚠️⚠️ Зачем. На вебинаре 25.09.2026 из 158 зрителей 71 не увидел видео, и
-- понять это по логам было НЕЛЬЗЯ: nginx видит только «запросил файл / отдал
-- файл», а что дальше произошло в браузере — собралась картинка или чёрный
-- экран — сервер не знает вовсе. Отсюда ложные доклады «видео отдаётся» при
-- чёрном экране у человека: на Android Chrome сегменты шли по 500 КБ, а
-- картинки не было.
--
-- webinar_presence до сих пор писала только факт «страница открыта» (heartbeat),
-- поэтому «158 уникальных зрителей» означало «158 открыли страницу», а не
-- «158 смотрели». Теперь heartbeat присылает состояние ПЛЕЕРА, и в аналитике
-- видно, у кого видео реально идёт.
--
-- ⚠️ Признак берётся с самого <video> (currentTime растёт + readyState), а не
-- «плеер не сообщил об ошибке»: при чёрном экране ошибки часто нет вовсе —
-- именно так и выглядела вся история 25.09.

ALTER TABLE webinar_presence
  -- играется ли видео у этого зрителя в эту минуту (NULL — старые записи,
  -- когда признака ещё не собирали; не путать с false)
  ADD COLUMN IF NOT EXISTS playing BOOLEAN,
  -- сколько секунд видео он посмотрел с момента открытия страницы: отличает
  -- «не запустилось вовсе» (0) от «шло и прервалось» (больше нуля)
  ADD COLUMN IF NOT EXISTS played_sec INTEGER,
  -- какой способ воспроизведения выбрал фронт: 'native' или 'hlsjs'.
  -- ⚠️ Нужен, чтобы сравнивать способы по ФАКТУ просмотра, а не по догадкам:
  -- 25.09 два дня ушло на угадывание, какому браузеру какой путь подходит.
  ADD COLUMN IF NOT EXISTS player_mode TEXT,
  -- последняя ошибка плеера, если была (тип hls.js или код media error)
  ADD COLUMN IF NOT EXISTS player_error TEXT;

-- ⚠️ Отдельный индекс под playing НЕ нужен: разбор идёт по room_id+bucket_at,
-- а под них уже есть idx_webinar_presence_room_bucket. Лишний индекс замедлял
-- бы запись heartbeat, которая идёт каждую минуту от каждого зрителя.
--
-- ⚠️ UNIQUE для ON CONFLICT в heartbeat — существующий webinar_presence_uq:
--   (room_id, COALESCE(contact_id,0), COALESCE(session_key,''), bucket_at)
-- Он на ВЫРАЖЕНИЯХ, поэтому в коде ON CONFLICT перечисляет их дословно, иначе
-- Postgres не находит индекс и падает на каждом пинге.

-- ⚠️ GRANT в той же миграции: роль plusson не владелец схемы, без этого
-- добавленные колонки окажутся недоступны приложению.
GRANT SELECT, INSERT, UPDATE ON webinar_presence TO plusson;
