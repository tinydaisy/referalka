-- 239: новым клиентам по умолчанию — ВЕБ-ВЕРСИЯ ссылок (bot), не Mini App.
--
-- Зачем. Mini App подключён далеко не у всех клиентов (в Telegram его надо
-- отдельно привязывать через @BotFather, во ВКонтакте — проходить модерацию,
-- в MAX он вообще не используется — см. ниже). Дефолт 'miniapp' приводил к
-- тому, что у нового клиента ссылки вели в несуществующее приложение.
-- Веб-версия (pluson.ru/event/{slug}) работает у всех и всегда, поэтому она
-- и становится дефолтом.
--
-- ⚠️ MAX: Mini App там не используется НИКОГДА. В MAX нет запроса «разрешить
-- боту писать» (в Telegram — requestWriteAccess, во ВКонтакте — разрешение
-- сообщений от сообщества), поэтому зашедший через Mini App человек НЕ
-- подписывается на бота: рассылки, напоминания и подарки до него не дойдут.
-- Веб-ссылка ведёт в бота (?start=…) и подписка возникает сама. Переключатель
-- «Mini App» для MAX заблокирован в дашборде, а резолвер режима
-- (share_links.resolve_event_link_mode) форсит 'bot' для платформы max.
--
-- Существующие клиенты НЕ трогаются — у них уже осознанный выбор.
-- Меняется только DEFAULT для новых записей.

ALTER TABLE clients ALTER COLUMN default_link_mode SET DEFAULT 'bot';
