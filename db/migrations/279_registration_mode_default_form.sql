-- 279: способ регистрации по умолчанию — ПРОСТАЯ ФОРМА (миграция 262 ввела поле).
--
-- Было: registration_mode NULL, и весь код угадывал «заполнен landing_url →
-- сторонний сайт, иначе форма». Угадывание неверное:
--   • у подавляющего большинства событий landing_url пуст — то есть дефолта
--     как такового не было;
--   • у кого заполнен, там нередко лежит ссылка на БОТА или на ЧУЖОЕ событие
--     (осталась от копирования, от старой интеграции), и человек с рассылки
--     или из бота уезжал не на регистрацию, а неизвестно куда.
--
-- Дефолт должен быть тем, что работает у всех и всегда: встроенная форма
-- /event/{slug}/register. Сторонний сайт и наш лендинг-конструктор — только
-- когда клиент ВЫБРАЛ их явно.
--
-- ⚠️ Бэкфилл ставит 'form' всем, у кого режим не задан, — В ТОМ ЧИСЛЕ тем,
-- у кого заполнен landing_url. Это осознанно: раз поле не выбрано, значит
-- клиент способ не задавал, а адрес в поле мог остаться от копии события.
-- Кому нужен сторонний сайт — переключат в настройках одним кликом, и это
-- честнее, чем молча уводить их аудиторию по случайной ссылке.

ALTER TABLE events ALTER COLUMN registration_mode SET DEFAULT 'form';

UPDATE events SET registration_mode = 'form' WHERE registration_mode IS NULL;

COMMENT ON COLUMN events.registration_mode IS
    'Способ регистрации: form — встроенная форма (по умолчанию), landing — наш конструктор /e/{slug}, external — сторонний сайт клиента (events.landing_url)';
