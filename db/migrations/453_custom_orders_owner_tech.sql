-- 453. В персональном заказе видно, ЗА КЕМ ЧИСЛИТСЯ клиент.
--
-- ⚠️⚠️ «ПРИВЁЛ» И «ВЕДЁТ» — РАЗНЫЕ ЛЮДИ, и в миграции 443 сохранялся только
-- первый. Клиента мог привести один внедренец (или партнёр), а закреплён за
-- ним может быть другой: `clients.referred_by_tech_id` и
-- `clients.tech_specialist_id` — независимые поля, и совпадают они далеко не
-- всегда. Ставку по-прежнему определяет ПРИВЁДШИЙ (кто привёл — тому 80 %), но
-- без ответственного непонятно, в чьей базе человек и кто по нему работает.
--
-- ⚠️ Снимок, а не только ссылка — по той же причине, что и с источником:
-- клиента могут передать другому внедренцу, а в заказе должно остаться видно,
-- за кем он числился НА МОМЕНТ заказа. Иначе прошлые заказы задним числом
-- «переедут» к новому ответственному.
ALTER TABLE custom_orders
    ADD COLUMN IF NOT EXISTS owner_tech_id INTEGER
        REFERENCES tech_specialists(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS owner_tech_title TEXT;

COMMENT ON COLUMN custom_orders.owner_tech_id IS
    'За каким внедренцем числится клиент (clients.tech_specialist_id) на момент заказа.';
COMMENT ON COLUMN custom_orders.owner_tech_title IS
    'Имя ответственного снимком: клиента могут передать, а в заказе должно остаться видно.';
