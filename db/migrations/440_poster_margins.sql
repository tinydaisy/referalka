-- 440: поля афиши — отступы от края, в миллиметрах, со всех четырёх сторон.
--
-- ⚠️ ЗАЧЕМ. Раньше от края отступал ТОЛЬКО блок спикеров (`speakers_side`, и то
-- лишь по бокам). Логотип бренда, логотипы партнёров, заголовок и пилюля
-- ставились своими координатами и при значении 0 упирались прямо в край
-- полотна. Верх и низ не были защищены вовсе: подпись нижнего ряда спикеров
-- могла лечь на самый край. Это видно сразу — афиша выглядит обрезанной, а при
-- печати обрез съедает буквы.
--
-- ⚠️ ПОЛЕ ДЕЙСТВУЕТ НА ВСЁ. Правило владельца 18.09.2026: «чтобы за эти отступы
-- все отрисовки спикеров и их имён и всего всего не вылезали». Значит поле —
-- это не отступ одного блока, а граница РАБОЧЕЙ ОБЛАСТИ: за неё не заходит
-- ничего, включая логотипы и подписи, координаты которых задаёт клиент.
--
-- ⚠️ МИЛЛИМЕТРЫ, А НЕ ПРОЦЕНТЫ. «5 мм» человек представляет, «2.38 %» — нет.
-- Афиша цифровая, физического размера у неё нет, поэтому миллиметр считается
-- от опорной ширины листа: 297 мм у горизонтальной (A4 альбомная) и 210 мм у
-- вертикальной и квадратной (A4 книжная). То есть одно и то же «10 мм» на
-- разных форматах даёт разную долю ширины — и это правильно: на широком
-- полотне то же поле в долях выглядело бы вдвое толще.
--
-- ⚠️ Хранятся именно МИЛЛИМЕТРЫ, а пересчёт в проценты живёт в коде отрисовки.
-- Хранить посчитанные проценты нельзя: сменится опорный лист — и старые макеты
-- молча поедут, потому что в базе будет результат вчерашней формулы.

BEGIN;

ALTER TABLE event_poster_layouts
  ADD COLUMN IF NOT EXISTS margin_top    NUMERIC(5,1) NOT NULL DEFAULT 10
      CHECK (margin_top    BETWEEN 0 AND 60),
  ADD COLUMN IF NOT EXISTS margin_bottom NUMERIC(5,1) NOT NULL DEFAULT 10
      CHECK (margin_bottom BETWEEN 0 AND 60),
  ADD COLUMN IF NOT EXISTS margin_left   NUMERIC(5,1) NOT NULL DEFAULT 10
      CHECK (margin_left   BETWEEN 0 AND 60),
  ADD COLUMN IF NOT EXISTS margin_right  NUMERIC(5,1) NOT NULL DEFAULT 10
      CHECK (margin_right  BETWEEN 0 AND 60);

COMMENT ON COLUMN event_poster_layouts.margin_top IS
  'Поле сверху в мм: за него не заходит ничего — ни логотипы, ни заголовок';
COMMENT ON COLUMN event_poster_layouts.margin_bottom IS
  'Поле снизу в мм: подписи нижнего ряда спикеров упираются в него, не в край';
COMMENT ON COLUMN event_poster_layouts.margin_left IS
  'Поле слева в мм';
COMMENT ON COLUMN event_poster_layouts.margin_right IS
  'Поле справа в мм';

-- ⚠️ `speakers_side` БОЛЬШЕ НЕ НУЖЕН: боковое поле теперь общее для всей афиши,
-- а не отдельная настройка одного блока. Два способа задать один отступ — это
-- гарантированный вопрос «почему спикеры отступают иначе, чем заголовок».
-- Колонку НЕ удаляем (DROP не идёт в автонакат), но переносим её значение в
-- боковые поля там, где клиент его менял, и код её больше не читает.
UPDATE event_poster_layouts
   SET margin_left  = GREATEST(margin_left,  ROUND((speakers_side * 210 / 100.0)::numeric, 1)),
       margin_right = GREATEST(margin_right, ROUND((speakers_side * 210 / 100.0)::numeric, 1))
 WHERE speakers_side IS NOT NULL
   AND speakers_side <> 5;          -- 5 % — прежнее умолчание, переносить нечего

COMMENT ON COLUMN event_poster_layouts.speakers_side IS
  'УСТАРЕЛО (миграция 440): боковое поле задаётся margin_left/margin_right в мм. Колонка оставлена, кодом не читается.';

COMMIT;
