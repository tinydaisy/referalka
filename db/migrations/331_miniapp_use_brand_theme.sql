-- 331: галочка «применять фирменные цвета в Mini App и на веб-витрине»
--
-- Зачем. Цвета клиента (`clients.lp_*`) настраиваются в «Стилях лендингов» и
-- до сих пор применялись ТОЛЬКО к лендингу. Mini App и веб-витрина события
-- рисовались зашитыми цветами платформы — клиент собирал фирменную тему и не
-- видел её там, куда приводит свою аудиторию.
--
-- ⚠️ ПО УМОЛЧАНИЮ ВЫКЛЮЧЕНО (FALSE). Тема есть у каждого клиента (колонки
-- `lp_*` заполнены значениями по умолчанию с миграции 241), поэтому включение
-- «всем сразу» перекрасило бы Mini App у всех, кто цвета не выбирал осознанно.
-- Смена оформления там, где идут регистрации, — это то, что клиент решает сам.
ALTER TABLE clients
  ADD COLUMN IF NOT EXISTS miniapp_use_brand_theme BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN clients.miniapp_use_brand_theme IS
  'Применять фирменные цвета (lp_*) в Mini App и на веб-витрине события. FALSE = стандартные цвета платформы.';
