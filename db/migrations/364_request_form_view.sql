-- 364: как показывать анкету заявки — квизом или всеми вопросами сразу
--
-- ⚠️ Настройка переезжает ИЗ БЛОКА ЛЕНДИНГА в форму заявки (решение владельца
-- 07.09.2026). Причина та же, что у заголовка и выбора анкеты: в конструкторе
-- лендинга это второе место для одного и того же, и они разъезжаются. Плюс
-- простой форме (Mini App) настройка тоже нужна, а блока лендинга там нет
-- вовсе — взять режим было неоткуда.
--
-- ⚠️ ПО УМОЛЧАНИЮ КВИЗ: в узком окне мессенджера десяток полей сразу
-- превращается в простыню, человек закрывает окно, не начав.
--
-- `event_landing_blocks.survey_view` НЕ трогаем — у блоков, созданных раньше,
-- он заполнен и служит запасным значением, как и `survey_id`.

ALTER TABLE request_forms
    ADD COLUMN IF NOT EXISTS survey_view TEXT NOT NULL DEFAULT 'quiz';

