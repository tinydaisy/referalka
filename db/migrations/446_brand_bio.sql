-- 446: «О бренде» — текстовое полотно про проект, рядом с регалиями основателя.
--
-- ⚠️ ЗАЧЕМ ОТДЕЛЬНОЕ ПОЛЕ. У основателя уже есть `clients.bio` — рассказ о
-- человеке (кто он, чего добился). Про ПРОЕКТ рассказать было негде: у бренда
-- только `positioning` (одна строка, 140 символов) и «Факты в цифрах»
-- (`achievements` — пары «цифра + подпись»). Связного текста «что мы делаем,
-- для кого, чем отличаемся» не помещалось никуда, и клиенты дописывали его в
-- регалии основателя — получалась мешанина «я» и «мы» в одной плашке.
--
-- Устроено ОДИНАКОВО с `clients.bio`, сознательно:
--   • тот же лимит 1500 символов (web/src/components/FieldLimits.tsx → BIO_LIMIT);
--   • те же HTML-теги (<b>, <i>, списки) и та же проверка перед сохранением;
--   • тот же вывод через safe_html / sanitizeHtml.
-- Один способ на два поля — чтобы клиент не разбирался дважды.
--
-- Пусто — блок не выводится вовсе (ни в Mini App, ни на страницах).

BEGIN;

ALTER TABLE clients
  ADD COLUMN IF NOT EXISTS brand_bio TEXT;

COMMENT ON COLUMN clients.brand_bio IS
  'Текст о БРЕНДЕ/проекте (HTML-теги, лимит 1500). Плашка над блоком основателя в Mini App и раздел «Информация о проекте» на странице организатора. Пусто — не выводится.';

COMMIT;
