-- 282: Второй логотип клиента — для СВЕТЛОГО фона (2026-08-12)
--
-- ⚠️ Логотип у клиента был один (`brand_logo_url`), и он рисуется белым:
-- на тёмном лендинге виден, на светлой карточке анкеты сливается с фоном
-- и выглядит как пустое место (жалоба владельца).
--
-- Держим два файла и выбираем по фону страницы. Пусто → берём основной,
-- поведение прежнее.
ALTER TABLE clients
    ADD COLUMN IF NOT EXISTS brand_logo_light_url TEXT;

COMMENT ON COLUMN clients.brand_logo_light_url IS
    'Логотип для СВЕТЛОГО фона (тёмная версия знака). Пусто → brand_logo_url.';
