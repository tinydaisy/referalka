-- 390. Обложка у блока материала — чтобы видео не было чёрным прямоугольником.
--
-- ⚠️⚠️ ПОЧЕМУ ОБЛОЖКУ НАДО ХРАНИТЬ У СЕБЯ. У YouTube адрес обложки достаётся из
-- самой ссылки (`img.youtube.com/vi/<id>/hqdefault.jpg`) — там ничего хранить не
-- нужно. У VK Видео и Rutube так нельзя: публичного адреса обложки нет, а метод
-- API `video.get` требует ПОЛЬЗОВАТЕЛЬСКИЙ токен владельца сообщества — токеном
-- сообщества он отвечает «User authorization failed» (проверено на проде).
--
-- Значит запрашивать обложку в момент показа нечем, и материал с видео из VK
-- выглядел чёрным прямоугольником — ровно на это и пожаловался клиент.
--
-- ⚠️ Колонка на БЛОКЕ, а не на материале: в одном материале может быть
-- несколько видео, и обложка у каждого своя.
--
-- ⚠️ NULL = «взять из ссылки, если получится» (YouTube), а не «нет обложки».
-- Пустая строка и NULL здесь означают одно и то же — прежнее поведение.

ALTER TABLE material_blocks
    ADD COLUMN IF NOT EXISTS poster_url TEXT;

COMMENT ON COLUMN material_blocks.poster_url IS
    'Обложка блока (пока используется у kind=video). Пусто — плеер пробует '
    'достать её из ссылки: у YouTube получается, у VK и Rutube нет.';
