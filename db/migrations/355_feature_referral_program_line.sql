-- 355: Строка «Реферальная программа» в список возможностей всех тарифов
--
-- Реферальная программа события (участник зовёт друзей по личной ссылке и
-- получает подарки за пороги приглашённых) — то, ради чего платформу и берут,
-- но в карточках тарифов её не было вовсе: гейта у неё нет, работает у всех,
-- а список строится только из фич.
--
-- ⚠️ Как и `miniapp_funnels` (миграция 353) — строка ОПИСАТЕЛЬНАЯ:
-- `client_has_feature('referral_program')` нигде не вызывается и вызываться не
-- должен. Появится желание что-то ею закрыть — сначала проверить, что рефералку
-- действительно решено сделать платной, иначе она отключится у всех разом.
--
-- ⚠️ Не путать с `partner_program` (партнёры КЛИЕНТА, которым он платит деньги)
-- и с реф-программой самого ПЛЮСОНа (кэшбэк за приведённых клиентов). Здесь —
-- подарки участникам события за приглашённых друзей.

INSERT INTO features (slug, name, description, sort)
VALUES ('referral_program',
        'Реферальная программа (выдача подарков за приглашения на эфиры/мероприятия)',
        'Участник получает личную ссылку, зовёт друзей и получает подарки за пороги '
        'приглашённых. Описательная строка тарифа — доступ ничем не гейтится.',
        35)
ON CONFLICT (slug) DO UPDATE SET name = EXCLUDED.name, sort = EXCLUDED.sort;

-- Всем тарифам, у которых есть лид-магниты (trial, start, pro, vip, admin).
INSERT INTO tariff_features (tariff_id, feature_id)
SELECT tf.tariff_id, (SELECT id FROM features WHERE slug = 'referral_program')
  FROM tariff_features tf
 WHERE tf.feature_id = (SELECT id FROM features WHERE slug = 'lead_magnets')
ON CONFLICT DO NOTHING;
