-- 288: Обнаружение чужого вебхука на боте клиента (2026-08-13)
--
-- Зачем. Клиент подключает своего бота ещё и к стороннему сервису (BotHelp,
-- merexo и т.п.). Telegram отдаёт сообщения ТОЛЬКО ОДНОМУ получателю:
-- пока висит чужой вебхук, наш polling не получает ничего. У клиента молча
-- перестают работать воронки лид-магнитов, выдача подарков, проверка
-- подписки, приветствия и регистрация на события — а он об этом не знает и
-- думает, что всё в порядке.
--
-- ⚠️ Вебхук САМИ НЕ СНИМАЕМ: это сломает клиенту работу в его сервисе.
-- Наше дело — обнаружить и внятно сказать; решение за клиентом.

-- Адрес чужого вебхука; NULL/'' = вебхука нет, всё в порядке.
ALTER TABLE channels
    ADD COLUMN IF NOT EXISTS webhook_url TEXT;

-- Когда последний раз спрашивали Telegram. Нужно, чтобы отличить
-- «проверено, чисто» от «ещё ни разу не проверяли».
ALTER TABLE channels
    ADD COLUMN IF NOT EXISTS webhook_checked_at TIMESTAMPTZ;

-- ⚠️ Когда уведомили клиента. Уведомление уходит ОДИН РАЗ на проблему —
-- долбить письмом каждый час нельзя. Плашка в кабинете при этом висит,
-- пока проблема есть. Починил (вебхук исчез) → сбрасываем в NULL, и при
-- повторной поломке человек снова получит письмо.
ALTER TABLE channels
    ADD COLUMN IF NOT EXISTS webhook_notified_at TIMESTAMPTZ;

CREATE INDEX IF NOT EXISTS idx_channels_webhook
    ON channels(id) WHERE COALESCE(webhook_url, '') <> '';
