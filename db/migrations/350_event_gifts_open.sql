-- 350: Вкладка «Подарки» — показывать ли её незарегистрированным
--
-- Зачем (решения № 17, № 26). Сейчас у незарегистрированного вкладка целиком
-- под замком. Но реф-ссылка есть у КАЖДОГО контакта (`contacts.ref_code` —
-- NOT NULL у всех 22 485), и человек способен рекомендовать событие, ещё не
-- решив, идёт ли он сам. Особенно на платном событии: «прорекламирую и
-- заработаю» — нормальная мотивация, а мы её глушим замком.
--
-- ⚠️ Открывается ПОЛОВИНА вкладки, а не вся:
--
--     ссылка + рекламные материалы  → всем, кто открыл событие
--     подарки за пороги             → только зарегистрированным, с замком
--
-- Иначе человек решит, что подарок уже его, и обидится. Замок на второй
-- половине объясняет, что нужно сделать.
--
-- ⚠️ Это РЕФЕРАЛКА СОБЫТИЯ, не партнёрка: тут подарки, а не деньги. Добывать
-- ничего не нужно — только снять замок с половины вкладки.
--
-- ⚠️ DEFAULT FALSE: поведение существующих событий не меняем. Клиент включает
-- осознанно — он и решает, показывать ли раздел тем, кто ещё не с ним.

ALTER TABLE events
  ADD COLUMN IF NOT EXISTS gifts_open_to_guests BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN events.gifts_open_to_guests IS
  'Показывать вкладку «Подарки» незарегистрированным (решения № 17, № 26). Ссылка и материалы — всем; сами подарки за пороги остаются под замком до регистрации.';
