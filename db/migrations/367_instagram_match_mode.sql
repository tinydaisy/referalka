-- 367: как сравнивать кодовое слово — «содержит» или «точное совпадение»
--
-- ⚠️ По умолчанию «содержит»: люди пишут «хочу!!», «Хочу гайд», «хочу 🙏» —
-- требовать точного равенства значило бы терять почти всех. Но клиенту нужен
-- и строгий режим: слово «хочу» встречается в «не хочу» и в «хочу спросить
-- совсем про другое».
--
-- ⚠️ Регистр не учитывается ВСЕГДА, отдельной настройки для этого нет:
-- «ХОЧУ», «Хочу» и «хочу» — одно и то же слово, и выбор здесь только запутал бы.

BEGIN;

ALTER TABLE instagram_funnels
  ADD COLUMN IF NOT EXISTS match_mode TEXT NOT NULL DEFAULT 'contains'
  CHECK (match_mode IN ('contains', 'exact'));

COMMIT;
