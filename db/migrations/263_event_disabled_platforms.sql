-- 263: Площадки, ОТКЛЮЧЁННЫЕ у события (миграции 240-262).
--
-- Зачем. У клиента канал на площадке подключён, но для КОНКРЕТНОГО события
-- использовать его не нужно: например ВК-приложение глючит и ссылку спикерам
-- туда давать нельзя. Раньше выключить это можно было только отключив канал
-- целиком — то есть у всех событий сразу.
--
-- Пусто = все подключённые площадки работают (прежнее поведение).
-- ['vk'] = ВК-ссылки этого события НИГДЕ не отдаются наружу:
--   • материалы и реф-ссылки в кабинете спикера;
--   • карточка спикера в дашборде;
--   • реф-ссылки участников;
--   • ссылка регистрации в рассылках — вместо ВК срабатывает приоритет
--     подмены (из ВК уводим в MAX, см. SIGNUP_FALLBACK_ORDER).
--
-- ⚠️ Сам бот площадки НЕ отключается: кто уже в ВК — продолжает общаться,
-- рассылки туда идут, воронки работают. Прячем только ПУБЛИЧНУЮ ВЫДАЧУ ссылок,
-- чтобы новых людей не заводить на площадку, которой клиент не пользуется.
--
-- Массив, а не три булевых поля: площадок со временем становится больше,
-- добавление новой не потребует миграции.

ALTER TABLE events
  ADD COLUMN IF NOT EXISTS disabled_platforms TEXT[] NOT NULL DEFAULT '{}';

GRANT SELECT, INSERT, UPDATE, DELETE ON events TO plusson;
