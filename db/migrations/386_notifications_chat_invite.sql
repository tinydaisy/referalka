-- 386. Ссылка-приглашение в группу уведомлений (09.09.2026).
--
-- ЗАЧЕМ.
-- Автонастройка (миграция 364) создаёт клиенту закрытую группу для уведомлений
-- и кладёт ссылку-приглашение в `service_orders.group_invite_link`. Но заказ —
-- это ПРОЦЕСС: он завершается и уходит из активных, а вместе с ним пропадает и
-- ссылка. Клиент, который не вступил сразу (или вышел, или зашёл с другого
-- устройства), попасть в свою же группу больше не мог: id чата в настройках
-- есть, а ссылки нет, и по id в Telegram не вступишь.
--
-- ⚠️ ХРАНИМ У КЛИЕНТА, А НЕ В ЗАКАЗЕ. Группа живёт, пока живёт кабинет, — это
-- постоянная настройка, рядом с `notifications_telegram_chat_id`, а не след
-- разового процесса.
--
-- ⚠️ Отдельная колонка, а не `client_broadcast_chats`: там ГРУППЫ ДЛЯ РАССЫЛОК,
-- куда уходят анонсы аудитории. Служебная группа уведомлений туда намеренно не
-- попадает (см. `is_setup_group` в services/tg_setup_events.py) — иначе клиент
-- разослал бы приглашение на эфир самому себе в служебный чат.

BEGIN;

ALTER TABLE clients
    ADD COLUMN IF NOT EXISTS notifications_telegram_invite_link TEXT;

COMMENT ON COLUMN clients.notifications_telegram_invite_link IS
    'Ссылка-приглашение в группу уведомлений. Заполняет автонастройка; нужна, чтобы клиент мог вступить позже — по chat_id в Telegram не вступишь';

COMMIT;
