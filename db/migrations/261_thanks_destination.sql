-- 261: Куда вести человека со страницы после оплаты (миграции 240-260).
--
-- Два сценария:
--   'bots'  — в бота события (по умолчанию). Там меню события: чат, программа,
--             подарки, эфир. Человеку показывается просьба вернуться на ТУ ЖЕ
--             площадку, с которой он начинал, — иначе его идентичность в боте
--             не свяжется с регистрацией и рассылки до него не дойдут.
--   'chats' — сразу в чаты события, без захода в бота. Годится, когда бот
--             клиенту не нужен и вся жизнь события идёт в чате.
--
-- Настройка у СОБЫТИЯ: у одной конференции путь может быть через бота,
-- у другой — сразу в чат.

ALTER TABLE events
  ADD COLUMN IF NOT EXISTS thanks_destination TEXT NOT NULL DEFAULT 'bots'
    CHECK (thanks_destination IN ('bots', 'chats'));

GRANT SELECT, INSERT, UPDATE, DELETE ON events TO plusson;
