-- 342: роль помощника «Менеджер заказов» (2026-09-02)
--
-- Зачем. Заявки из анкет разбирает не сам владелец, а сотрудник: звонит,
-- отмечает «обработано», пишет заметку. Отдавать ему весь кабинет ради
-- этого нельзя — он видел бы рассылки, события, деньги и настройки.
--
-- Уровней стало три:
--   full    — как владелец (кроме управления помощниками и пароля)
--   limited — прежний широкий набор: события, рассылки, программа…
--   orders  — ТОЛЬКО контакты и анкеты. Всё остальное закрыто.
--
-- ⚠️ Именно «только два раздела», а не «limited минус лишнее»: перечислять
-- запреты пришлось бы дописывать при каждом новом разделе, и однажды забыли
-- бы — менеджер получил бы доступ к тому, чего видеть не должен. Разрешаем
-- список, а не запрещаем.

ALTER TABLE assistant_grants DROP CONSTRAINT IF EXISTS assistant_grants_access_level_check;

ALTER TABLE assistant_grants
    ADD CONSTRAINT assistant_grants_access_level_check
    CHECK (access_level IN ('full', 'limited', 'orders'));

COMMENT ON COLUMN assistant_grants.access_level IS
  'full — как владелец; limited — прежний широкий набор; '
  'orders — только «Контакты» и «Анкеты» (менеджер заказов).';
