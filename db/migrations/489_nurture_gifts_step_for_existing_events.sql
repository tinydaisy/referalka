-- 489. Шаг догрева «Подарки за рекомендации» — существующим событиям
--
-- Шаг добавлен в DEFAULT_STEPS (`event_nurture_reg.py`) 22.09.2026, но дефолты
-- сеются ЛЕНИВО и ровно один раз: `_seed_default_steps_if_empty` проверяет
-- флаг `events.nurture_reg_defaults_seeded`. У событий, чей клиент уже
-- открывал вкладку «Воронка догрева», флаг стоит — и новый шаг не пришёл бы к
-- ним НИКОГДА (на проде это 7 событий, включая 89/ivision9, где владелец его
-- и искал). Через кнопку «Вернуть по умолчанию» приехали бы разом все три
-- шага, то есть два дубля к существующим.
--
-- Поэтому доносим ровно недостающий шаг — тем, у кого дефолты уже сеяны, но
-- шага с `button_kind='gifts'` нет.
--
-- ⚠️ ВЫКЛЮЧЕННЫМ (`is_active = FALSE`). Текст про подарки уйдёт людям только
-- когда клиент его прочитает и включит сам: реферальная программа есть не у
-- каждого события, и без неё сообщение было бы пустым обещанием. Ровно то же
-- правило у кнопки «Вернуть по умолчанию».
--
-- ⚠️ Тип события не смотрим (`module_slug`: base / conference / turnir, и
-- коллабы `is_collab`): воронка догрева зарегистрированных общая для всех
-- типов, таблица одна. Владелец просил проверить, что шаг есть и у обычных
-- мероприятий, и у конференций, и у премий, и у коллаб — фильтра нет, значит
-- получат все.
--
-- Идемпотентно: NOT EXISTS по `button_kind='gifts'` — повторный прогон
-- (или прогон после того, как клиент уже получил шаг) ничего не добавит.

INSERT INTO event_nurture_reg_steps
    (event_id, sort_order, offset_seconds, text, button_label, button_kind, is_active)
SELECT
    e.id,
    COALESCE((SELECT MAX(s.sort_order) + 1
                FROM event_nurture_reg_steps s WHERE s.event_id = e.id), 0),
    3600,  -- через час после регистрации
    'Мы щедро благодарим тех, кто рекомендует нас и помогает нам сделать наше событие еще более масштабным.' || E'\n\n' ||
    'Вы можете получать ценнейшие подарки, просто рекомендуя наше событие по своей реферальной ссылке.' || E'\n\n' ||
    '<b>Ваши реферальные ссылки:</b>' || E'\n' ||
    '{ref_links}' || E'\n\n' ||
    'А именно:' || E'\n\n' ||
    '{gift_ladder}' || E'\n\n' ||
    'Нажмите на кнопку, чтобы перейти в свой кабинет на вкладку «{gifts_tab}», чтобы забрать вашу реферальную ссылку и готовые материалы для анонсов.',
    'Подарки и все для анонсов',
    'gifts',
    FALSE
  FROM events e
 WHERE e.nurture_reg_defaults_seeded = TRUE
   AND NOT EXISTS (
         SELECT 1 FROM event_nurture_reg_steps s
          WHERE s.event_id = e.id AND s.button_kind = 'gifts');
