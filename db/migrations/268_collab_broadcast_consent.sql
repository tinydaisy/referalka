-- 268: Предварительное согласие организатора на рассылки в коллаб-событии.
--
-- Событие в Коллаборативной — ОБЩЕЕ, анонсируется всеми организаторами (они
-- равноправны, «инициатора» нет). Раньше рассылка по базе другого организатора
-- требовала его подтверждения КАЖДЫЙ раз (awaiting_confirm, миграция 194).
--
-- Теперь у каждого организатора одна галочка на СОБЫТИЕ: «разрешаю рассылки по
-- моей базе/боту в этом событии». Поставил → всё, что ставится в этом событии,
-- уходит и по его базе СРАЗУ, без запроса подтверждения.
--
-- ⚠️ Одноразовая на событие. При ЗАВЕРШЕНИИ события галочки автоматически
-- снимаются (в это событие больше не рассылаем) — снятие делает код при переходе
-- status→ended, а движок дополнительно не шлёт в фактически завершённое событие.
ALTER TABLE event_owners
    ADD COLUMN IF NOT EXISTS allow_collab_broadcasts BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN event_owners.allow_collab_broadcasts IS
    'Согласие организатора на рассылки соорганизаторов по его базе в этом коллаб-событии. Снимается при завершении события';
