-- 448. Автонастройка при УЖЕ СУЩЕСТВУЮЩЕМ боте: спрашиваем роль (18.09.2026).
--
-- ЗАЧЕМ. У клиента может быть несколько ботов на одной платформе, и роль
-- задаётся флагом `client_channels.is_active`:
--   TRUE  — ГЛАВНЫЙ: воронки, /start, регистрации, приветствия, Mini App,
--           системные уведомления;
--   FALSE — ДОПОЛНИТЕЛЬНЫЙ: только база для рассылок, события не слушает.
--
-- ⚠️⚠️ РАНЬШЕ ЭТО РЕШАЛОСЬ ЗА ЧЕЛОВЕКА И МОЛЧА. Автонастройка смотрела, есть
-- ли у клиента главный telegram-бот, и если есть — новый заводился
-- дополнительным. Осторожно (не перебить работающего), но человека не
-- спрашивали вовсе: он покупал услугу «настроим бота», получал бота, который
-- не ведёт ни одной воронки, и не понимал, почему в нём ничего не работает.
--
-- ⚠️ Обратный случай не лучше: молча сделать новый главным — значит отобрать
-- воронки у бота, который уже работает с аудиторией. Оба варианта законны,
-- выбрать может только владелец аккаунта.
--
-- ⚠️ ПОЧЕМУ ПОЛЕ В ЗАКАЗЕ, А НЕ ВОПРОС В МОМЕНТ СОЗДАНИЯ. Бот создаётся
-- фоновой задачей, иногда через час после нажатия (лимит BotFather). Спросить
-- в этот момент некого — человек давно закрыл вкладку. Значит ответ берём
-- заранее, на экране запуска, и кладём в заказ.
--
-- NULL = «вопрос не задавали» (у клиента не было бота, или заказ старый).
-- Тогда работает прежнее правило: первый бот — главный.

BEGIN;

ALTER TABLE service_orders
  ADD COLUMN IF NOT EXISTS bot_role TEXT;

COMMENT ON COLUMN service_orders.bot_role IS
  'Роль создаваемого бота, если у клиента уже есть главный: main (забрать воронки) | broadcast (только рассылки). NULL — вопрос не задавался';

COMMIT;
