-- 358: «Платежи» и «Платные тарифы» — одна строка вместо двух
--
-- В карточке Экстры стояли рядом два пункта: «Подключение платёжных систем»
-- (фича `payments` — раздел Настройки → «Платёжные системы») и «Платные тарифы
-- мероприятия» (фича `event_tariffs` — вкладка «Тарифы» события). Для клиента
-- это ОДНА возможность: платные тарифы без подключённой платёжки не принимают
-- деньги, а платёжка без тарифов ничего не продаёт. Обе входят в Экстру, врозь
-- не покупаются и порознь бесполезны.
--
-- ⚠️ Фичи НЕ объединяем в коде — они закрывают разные разделы, и слияние
-- потребовало бы переписать оба гейта ради одной строки в карточке. Вместо
-- этого показываем одну: `event_tariffs` получает общее название, `payments`
-- прячется флагом `hidden_in_card` (миграция 353). Доступ у обеих сохраняется.
--
-- ⚠️ Названия систем — как в разделе «Платёжные системы» кабинета
-- (`client_payments.PROVIDERS`): человек, оплатив тариф, пойдёт искать их там,
-- и подписи должны совпадать. Отсюда «LeadPay» латиницей, а не «ЛидПей».

UPDATE features
   SET name = 'Платные тарифы и подключение платёжных систем '
              '(Продамус, LeadPay, эквайринг Т-Банка и др.)'
 WHERE slug = 'event_tariffs';

UPDATE features SET hidden_in_card = TRUE WHERE slug = 'payments';
