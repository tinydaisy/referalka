-- 464. Заказ открывается по СЛУЧАЙНОМУ токену, а не по номеру.
--
-- ⚠️⚠️ ДЫРА, КОТОРУЮ ЭТО ЗАКРЫВАЕТ. Ссылка была вида `/order/PZ-000123` —
-- номера идут подряд, и любой, кому дали одну ссылку, перебором читал чужие
-- заказы: что человек заказывал, на какую сумму, его имя, почту и телефон.
-- Страница публичная по замыслу (её открывают без входа), поэтому защита
-- может быть только одна — неугадываемый адрес.
--
-- Номер `PZ-…` остаётся: он нужен в разговоре и в платёжке. Но в АДРЕСЕ теперь
-- токен, и по номеру страница больше не открывается.

ALTER TABLE custom_orders
    ADD COLUMN IF NOT EXISTS public_token TEXT;

-- Раздаём токены уже существующим заказам.
-- ⚠️ 16 байт (32 hex-символа): столько же, сколько у ссылок сброса пароля.
-- Перебрать нельзя, а ссылка остаётся достаточно короткой, чтобы её присылали
-- в мессенджере одной строкой.
UPDATE custom_orders
   SET public_token = encode(gen_random_bytes(16), 'hex')
 WHERE public_token IS NULL;

ALTER TABLE custom_orders
    ALTER COLUMN public_token SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uniq_custom_orders_public_token
    ON custom_orders (public_token);

COMMENT ON COLUMN custom_orders.public_token IS
    'Адрес публичной страницы заказа. ⚠️ Единственная защита от чтения чужих '
    'заказов — страница открывается без входа. По номеру PZ-… НЕ открывать.';
