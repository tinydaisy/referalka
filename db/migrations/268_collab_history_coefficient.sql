-- 268. Win-Win коэффициент коллаборации — храним посчитанным.
--
-- Показатель на карточке в Хабе меняется с «процента от всех участников» на
-- Win-Win коэффициент: `мои приведённые / среднее по организаторам коллабы`.
-- Ориентир 1.0 = сработал вровень с партнёрами.
--
-- Почему НЕ считаем на лету из brought_live/participants_total: коэффициент
-- зависит от того, сколько привели ДРУГИЕ организаторы той же коллабы и
-- сколько их было. Восстанавливать это на каждой карточке каталога — тяжёлый
-- запрос по всем строкам события. Пишем готовое число в момент завершения
-- коллабы, рядом с brought_live.
--
-- Старая формула наказывала за масштаб: вдвоём поровну = 50%, вчетвером
-- поровну = 25% — тот же человек при той же работе получал вдвое меньше
-- только потому, что собрал больше партнёров. Плюс знаменатель врал:
-- participants_total включает участников без реф-метки, которых никто себе
-- не засчитывает.
--
-- NULL = коэффициент не имеет смысла (организатор один либо никто никого
-- не привёл). В UI показывать «—», а НЕ 0.

ALTER TABLE hub_collab_history
    ADD COLUMN IF NOT EXISTS win_win_coefficient NUMERIC(6,2),
    ADD COLUMN IF NOT EXISTS organizers_count    INTEGER;

COMMENT ON COLUMN hub_collab_history.win_win_coefficient IS
    'Мои приведённые / среднее по организаторам коллабы. 1.0 = вровень. NULL = не считается';
COMMENT ON COLUMN hub_collab_history.organizers_count IS
    'Сколько организаторов было в коллабе (для пересчёта и прозрачности)';
