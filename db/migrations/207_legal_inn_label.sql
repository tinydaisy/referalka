-- 207_legal_inn_label.sql
-- Переименовываемая метка поля «ИНН» в юр-данных клиента.
--
-- Зачем: в РФ это ИНН, но в Беларуси — УНП, в других странах — другой аналог.
-- Клиент сам задаёт название поля (свободный текст, по умолчанию «ИНН»).
-- Это название подставляется на публичной странице политики /c/{client_id}/privacy
-- рядом со значением идентификатора налогоплательщика.

ALTER TABLE clients
    ADD COLUMN IF NOT EXISTS legal_inn_label TEXT;  -- название поля ИНН (напр. «ИНН», «УНП»)
