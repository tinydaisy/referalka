-- Тест-режим воронки Instagram: отвечать на КАЖДЫЙ комментарий.
--
-- ⚠️ Зачем. В боевом режиме повторная выдача тому же человеку идёт не чаще
-- раза в час (`_REPEAT_COOLDOWN_MIN`): десять комментариев подряд не должны
-- давать десять писем в личку. Но при настройке воронки это мешает — клиент
-- пишет второй проверочный комментарий и не получает ничего, а понять,
-- сломалось или сработала защита, по интерфейсу невозможно.
--
-- ⚠️ Галочка снимает ТОЛЬКО ограничение частоты. Ограничение самой Meta —
-- один приватный ответ на один комментарий — она обойти не может: это
-- правило их платформы, и новый ответ требует нового комментария.
ALTER TABLE instagram_funnels
  ADD COLUMN IF NOT EXISTS test_mode BOOLEAN NOT NULL DEFAULT FALSE;
