-- 128: Галочка «Скрыть кнопку стрима в Mini App»
--
-- По умолчанию кнопка стрима показывается (поле FALSE). Клиент может
-- жёстко выключить её показ в Mini App на этапе настройки события
-- (конференция / турнир / мероприятие), даже если stream_url задан.
--
-- Кнопка стрима теперь всегда кликабельна (ведёт на stream_url сразу),
-- видимость регулируется только этим флагом.

ALTER TABLE events
  ADD COLUMN IF NOT EXISTS hide_stream_button BOOLEAN NOT NULL DEFAULT FALSE;
