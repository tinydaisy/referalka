/**
 * Правила для поисковых роботов — /robots.txt
 *
 * ⚠️ Кабинет закрыт от индексации. Причины две:
 *  1. Те же статьи базы знаний открываются и в кабинете (/dashboard/help/…),
 *     и снаружи (/help/…) — поисковик счёл бы это дублями и понизил обе.
 *  2. Внутренние страницы кабинета в выдаче не нужны никому.
 *
 * ⚠️ Личные кабинеты покупателей (/my) и страницы предпросмотра тоже закрыты —
 * там чужие данные.
 */
import type { MetadataRoute } from 'next'

export default function robots(): MetadataRoute.Robots {
  return {
    rules: {
      userAgent: '*',
      allow: '/',
      disallow: [
        '/dashboard',   // кабинет клиента — дубли статей и внутренние страницы
        '/admin',       // админка платформы
        '/my',          // кабинет покупателя
        '/api/',        // служебные адреса
        '/r/',          // возврат с лендинга
        '/l/',          // веб-вход в событие
      ],
    },
    sitemap: 'https://pluson.ru/sitemap.xml',
  }
}
