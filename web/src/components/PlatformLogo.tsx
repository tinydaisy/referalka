/**
 * Логотипы площадок — ОДИН источник на весь кабинет.
 *
 * ⚠️ Раньше логотипов не было нигде: и «Написать в тех.поддержку», и списки
 * контактов рисовали кружок с первой буквой («T», «M», «TG», «MX»). Выглядело
 * как заглушка, а у MAX и Telegram первая буква ещё и не опознаётся.
 *
 * ⚠️⚠️ SVG ВСТРОЕН В КОД, А НЕ ГРУЗИТСЯ КАРТИНКОЙ. Файл из /public — это ещё
 * один сетевой запрос на каждую иконку и пустое место, пока он не пришёл;
 * встроенный SVG попадает в сборку и рисуется сразу. Плюс цвет и размер
 * задаются пропсами, а не пересохранением картинки.
 *
 * ⚠️ Фирменные цвета площадок — здесь же (`PLATFORM_COLORS`), чтобы Telegram
 * везде был одного синего, а не «примерно похожего» в каждом файле.
 */

export const PLATFORM_COLORS: Record<string, string> = {
  telegram: '#229ED9',
  max: '#6D4AFF',
  vk: '#0077FF',
  whatsapp: '#25D366',
}

type Props = {
  /** telegram | max | vk | whatsapp */
  slug: string
  /** Размер квадрата в пикселях (по умолчанию 20). */
  size?: number
  /** Цвет логотипа. По умолчанию — фирменный цвет площадки. */
  color?: string
  className?: string
}

export function PlatformLogo({ slug, size = 20, color, className }: Props) {
  const fill = color || PLATFORM_COLORS[slug] || '#25455D'
  const common = {
    width: size,
    height: size,
    viewBox: '0 0 24 24',
    fill: 'none' as const,
    className,
    'aria-hidden': true,
  }

  if (slug === 'telegram') {
    return (
      <svg {...common}>
        <path
          d="M21.94 4.3 18.9 19.1c-.23 1.02-.84 1.27-1.7.79l-4.7-3.46-2.27 2.18c-.25.25-.46.46-.94.46l.33-4.78 8.7-7.86c.38-.34-.08-.53-.59-.19L6.98 13.1 2.34 11.6c-1.01-.31-1.03-1.01.21-1.5L20.64 3.1c.84-.31 1.57.19 1.3 1.2Z"
          fill={fill}
        />
      </svg>
    )
  }

  if (slug === 'max') {
    // ⚠️ У MAX нет общепринятого узнаваемого знака вроде телеграмного самолёта,
    // поэтому рисуем литеру «M» в фирменном квадрате — так её не путают с
    // первой буквой случайного слова.
    return (
      <svg {...common}>
        <rect x="2" y="2" width="20" height="20" rx="6" fill={fill} />
        <path
          d="M7 16.5v-9h2.2l2.8 4.6 2.8-4.6H17v9h-2.1v-5.4l-2.3 3.7h-1.2L9.1 11.1v5.4H7Z"
          fill="#fff"
        />
      </svg>
    )
  }

  if (slug === 'vk') {
    return (
      <svg {...common}>
        <path
          d="M12.9 17.2c-5.2 0-8.5-3.7-8.6-9.9h2.7c.1 4.6 2.2 6.5 3.8 6.9V7.3h2.5v3.9c1.6-.2 3.3-2 3.9-3.9h2.5c-.4 2.4-2.2 4.2-3.4 4.9 1.2.6 3.2 2.1 4 4.9h-2.8c-.6-1.9-2.1-3.4-4.1-3.6v3.6h-.5Z"
          fill={fill}
        />
      </svg>
    )
  }

  if (slug === 'whatsapp') {
    // Трубка в «облачке» — знак, по которому WhatsApp узнают сразу.
    return (
      <svg {...common}>
        <path
          d="M12 2.5a9.5 9.5 0 0 0-8.2 14.3L2.5 21.5l4.8-1.3A9.5 9.5 0 1 0 12 2.5Z"
          fill={fill}
        />
        <path
          d="M9.1 7.6c-.2-.4-.4-.4-.6-.4h-.5c-.2 0-.5.1-.7.3-.3.3-.9.9-.9 2.2s.9 2.5 1 2.7c.1.2 1.8 2.9 4.5 3.9 2.2.9 2.7.7 3.2.7.5-.1 1.6-.7 1.8-1.3.2-.6.2-1.2.2-1.3-.1-.1-.2-.2-.5-.3l-1.7-.8c-.2-.1-.4-.1-.6.1l-.8 1c-.1.2-.3.2-.5.1-.3-.1-1.1-.4-2-1.3-.8-.7-1.3-1.5-1.4-1.8-.2-.3 0-.4.1-.5l.4-.4.2-.4c.1-.1 0-.3 0-.4l-.8-1.9Z"
          fill="#fff"
        />
      </svg>
    )
  }

  // Незнакомая площадка — нейтральный кружок с буквой, чтобы верстка не поехала.
  return (
    <svg {...common}>
      <circle cx="12" cy="12" r="10" fill={fill} />
      <text x="12" y="16" textAnchor="middle" fontSize="11" fontWeight="700" fill="#fff">
        {(slug || '?')[0].toUpperCase()}
      </text>
    </svg>
  )
}

export default PlatformLogo
