'use client'

/**
 * Замораживает содержимое кабинета, когда подписка истекла.
 *
 * ⚠️⚠️ Решение владельца: разделы НЕ прячем и НЕ подменяем заглушкой — всё
 * остаётся на экране, но замылено и некликабельно. Причина: пропавший раздел
 * человек читает как «у меня всё удалили». Ровно так и вышло на кабинете
 * Виктории Ивановой: её боты (10 466 подписчиков) исчезли из «Каналов», и она
 * решила, что данные потеряны, хотя они лежали в базе целыми.
 *
 * ⚠️ Стоит В МАКЕТЕ, а не на каждой странице: разделов два десятка, и обходить
 * их по одному значит забыть половину — на этом уже спотыкались. Здесь это
 * одна точка, которая накрывает весь кабинет разом.
 *
 * ⚠️ Замыливание — ПОКАЗ, а не защита: содержимое приходит в браузер и
 * достаётся из вёрстки. Настоящий запрет живёт на сервере
 * (subscription_guard + гейты фич).
 *
 * ⚠️ Страницы оплаты и партнёрки НЕ замораживаем: именно через них человек
 * возвращает доступ. Заблокировать их значило бы запереть его снаружи —
 * ту же ошибку уже ловили в subscription_guard, когда для продления подписки
 * требовалась действующая подписка.
 */
import { usePathname } from 'next/navigation'
import { useMe } from '@/hooks/useMe'

/** Куда пускаем даже с истёкшей подпиской — это путь обратно к оплате. */
const ALWAYS_OPEN = [
  '/dashboard/subscription',
  '/dashboard/partner-program',
  '/dashboard/my-partners',
  '/dashboard/settings',
  '/dashboard/help',
]

export default function FrozenContent({ children }: { children: React.ReactNode }) {
  const { subFrozen } = useMe()
  const pathname = usePathname() || ''

  const open = ALWAYS_OPEN.some(p => pathname.startsWith(p))
  if (!subFrozen || open) return <>{children}</>

  // ⚠️ ЗАГОЛОВОК РАЗДЕЛА НЕ ЗАМЫЛИВАЕМ (решение владельца): человек должен
  // понимать, где он находится. Размытая шапка выглядит как сломанная
  // страница, а не как «раздел закрыт».
  //
  // ⚠️ `filter: none` у потомка НЕ отменяет фильтр родителя — CSS применяет
  // фильтр ко всему поддереву как к единому слою. Поэтому размытие вешается
  // НЕ на контейнер, а на каждый элемент содержимого ОТДЕЛЬНО, и заголовок
  // из этого набора исключается селектором.
  //
  // ⚠️ Селектором, а не правкой каждой страницы: разделов два десятка, шапки у
  // всех свои, и обходить их по одному значит забыть половину — ровно на этом
  // уже спотыкались.
  return (
    <div className="frozen-wrap">
      <style jsx global>{`
        /* Размываем всё содержимое поэлементно… */
        .frozen-wrap > * > * {
          filter: blur(3px);
          opacity: 0.75;
          pointer-events: none;
          user-select: none;
        }
        /* …кроме заголовка раздела и ПОДМЕНЮ (вкладки внутри раздела):
           человек должен видеть, где он и какие вкладки есть.
           :has() поддерживают все актуальные браузеры (Safari 15.4+,
           Chrome 105+); где не поддержан — эти блоки просто останутся
           размытыми, страница не ломается. */
        .frozen-wrap > * > *:has(> h1),
        .frozen-wrap > * > h1,
        .frozen-wrap > * > h1 + p,
        .frozen-wrap > * > .border-b {
          filter: none;
          opacity: 1;
          user-select: auto;
        }
        /* ⚠️ Но кликать в них нельзя: раздел закрыт, и работающая вкладка
           внутри замороженного раздела вводит в заблуждение. Кнопки в шапке
           («Создать» и подобные) остаются размытыми — они ведут к действию,
           которое всё равно запрещено на сервере. */
        .frozen-wrap > * > *:has(> h1) a,
        .frozen-wrap > * > *:has(> h1) button {
          filter: blur(3px);
          opacity: 0.75;
          pointer-events: none;
        }
        .frozen-wrap > * > .border-b {
          pointer-events: none;
        }
      `}</style>
      <div aria-hidden>{children}</div>
    </div>
  )
}
