'use client'

/**
 * Лимиты длины полей спикера/коллаба — ОДНО место на все экраны.
 *
 * Одни и те же поля правятся в трёх местах: карточка спикера в конференции,
 * карточка коллаба и кабинет самого спикера. Держать цифры порознь нельзя —
 * разъедутся, и человек упрётся в разный лимит на разных экранах.
 *
 * ⚠️ Числа подобраны по РЕАЛЬНЫМ данным (замер 22.08.2026), не назначены:
 *  — позиционирование: 140 — столько же, сколько уже стояло в профиле
 *    основателя. Медиана 50 символов, «Основатель конференции ВИДЕНИЕ/iViSiON
 *    и платформы ПЛЮСОН» = 59. В поле писали офферы («увеличиваю доход…»),
 *    хотя оно отвечает на вопрос «кто вы».
 *  — регалии: медиана 465, 90% в пределах 1035. У Нурии Карычевой туда был
 *    вставлен весь лендинг — 5922 символа с кейсами и призывами.
 */

export const POSITIONING_LIMIT = 140
export const ACHIEVEMENTS_LIMIT = 1100

/**
 * Регалии ОСНОВАТЕЛЯ и БРЕНДА устроены иначе — это пары «цифра + подпись»
 * («1500+» / «учеников»), а не список строк. Поэтому лимиты свои:
 * подпись — короткая расшифровка, а не абзац (у одного клиента туда уехало
 * 229 символов связного текста, и «Факты в цифрах» перестали читаться).
 */
export const ACH_VALUE_LIMIT = 30
export const ACH_LABEL_LIMIT = 120

/**
 * «Регалии» в профиле ОСНОВАТЕЛЯ (clients.bio) — ещё одно поле, отдельное от
 * регалий коллаба. Оно показывается на странице «Об основателе», где места
 * больше, и допускает теги <b>. Поэтому 1500, а не 1100 (решение владельца):
 * медиана 503, 90% укладываются в 1554, максимум был 4563.
 */
export const BIO_LIMIT = 1500

/** Счётчик под полем: сколько осталось, при переборе — на сколько сократить. */
export function CharCount({ value, limit }: { value: string; limit: number }) {
  const len = (value || '').length
  const over = len - limit
  if (len === 0) return null
  return (
    <div
      className="text-[11px] mt-1 text-right"
      style={{
        color: over > 0 ? '#d64545' : len > limit * 0.85 ? '#b8860b' : '#9aa9b5',
        fontWeight: over > 0 ? 700 : 400,
      }}
    >
      {over > 0 ? `Слишком длинно — сократите на ${over}` : `${len} / ${limit}`}
    </div>
  )
}

/** Рамка поля при переборе — чтобы не дублировать условие на каждом экране. */
export function overClass(value: string, limit: number): string {
  return (value || '').length > limit ? 'border-red-400 bg-red-50' : ''
}
