/**
 * ⚠️ Чем закрывается нехватка — сверено с прод-базой (`tariff_features`)
 * 10.09.2026. Писать всем подряд «Подключить Экстру» было прямым обманом:
 * «Продукты» на Экстре не появятся вовсе — они только в Бизнесе.
 *
 * ⚠️ Модули (Конференции, Премии/Турниры, Коллабораторная) сюда НЕ входят —
 * это отдельные покупки (`features.is_addon`), а не тариф. Понадобится
 * решение на модуле — добавлять его как отдельный вид, а не приписывать к
 * тарифу: клиент купит Экстру и не получит обещанного.
 */
export const FEATURE_TARIFF: Record<SolutionFeature, { title: string; slug: string }> = {
  surveys:       { title: 'Экстра', slug: 'vip' },
  payments:      { title: 'Экстра', slug: 'vip' },
  event_landing: { title: 'Профи',  slug: 'pro' },
  webinar_room:  { title: 'Профи',  slug: 'pro' },
  products:      { title: 'Бизнес', slug: 'business_beta' },
}

/** ⚠️ Порядок = от дешёвого к дорогому. Нужен, чтобы назвать МИНИМАЛЬНЫЙ
 *  тариф, закрывающий все нехватки разом: решению может не хватать и анкет
 *  (Экстра), и продуктов (Бизнес) — звать надо в Бизнес, а не в оба. */
const TARIFF_RANK: Record<string, number> = { pro: 1, vip: 2, business_beta: 3 }

/** Минимальный тариф, закрывающий ВСЕ нехватки решения. */
export function requiredTariff(missing: SolutionFeature[]): { title: string; slug: string } | null {
  let best: { title: string; slug: string } | null = null
  for (const f of missing) {
    const t = FEATURE_TARIFF[f]
    if (!t) continue
    if (!best || (TARIFF_RANK[t.slug] || 0) > (TARIFF_RANK[best.slug] || 0)) best = t
  }
  return best
}

