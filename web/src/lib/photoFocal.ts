/**
 * Точка лица на фото — общие правила кадрирования.
 *
 * ⚠️⚠️ ОДИН ИСТОЧНИК НА ВСЕ ЭКРАНЫ. Фото человека показывается в четырёх с
 * лишним десятках мест (кабинет, лендинг, витрина, ЛК спикера, Mini App в
 * Telegram / ВК / МАХ / вебе, афиши), и везде это `object-fit: cover` — рамка
 * заполняется, лишнее режется. Пока формула кадрирования жила в каждом месте
 * своя (а точнее, её не было вовсе — резалось от центра), получалось
 * по-разному: на одном экране человек с головой, на другом срезана макушка.
 *
 * ⚠️ ЗАЧЕМ ВООБЩЕ. Резка от центра ломает два частых случая:
 *   • снимок в полный рост → в квадратную миниатюру попадает живот, голова
 *     уходит за верхний край;
 *   • портрет с большим отступом сверху → срезается макушка.
 * Точка лица говорит рамке, за что держаться, и оба случая пропадают.
 *
 * ⚠️ ПРОЦЕНТЫ, А НЕ ПИКСЕЛИ: одно фото показывается в круге 40 px, в квадрате
 * карточки и в афише 2160 px шириной. Проценты одинаково работают везде.
 */

/** Точка по умолчанию, когда клиент ничего не отмечал. */
export const FOCAL_DEFAULT = '50% 33%'

/**
 * Значение для CSS `object-position` / `background-position`.
 *
 * ⚠️ Пусто → НЕ центр, а верхняя треть кадра. На портретной фотографии лицо
 * почти всегда там: это чинит большинство снимков ещё до того, как клиент
 * что-то отметит. Центр (50% 50%) — это ровно то поведение, которое и срезало
 * головы, возвращать его умолчанием нельзя.
 *
 * ⚠️ Явные «50% 50%» в базе умолчанием НЕ считаются: их клиент поставил
 * осознанно, посмотрев на фото, и переучивать его не надо.
 */
export function focalCss(focal?: string | null): string {
  const v = (focal || '').trim()
  return v || FOCAL_DEFAULT
}

/**
 * Разбор строки в числа — для редактора точки и для расчётов в афише.
 * Мусор в поле не должен ронять показ: непарсимое значение = умолчание.
 */
export function parseFocal(focal?: string | null): { x: number; y: number } {
  const m = (focal || '').match(/(-?[\d.]+)\s*%\s+(-?[\d.]+)\s*%/)
  if (!m) return { x: 50, y: 33 }
  const x = Number(m[1]); const y = Number(m[2])
  if (!Number.isFinite(x) || !Number.isFinite(y)) return { x: 50, y: 33 }
  return { x: clamp(x), y: clamp(y) }
}

/** Сборка строки обратно. Округляем до целых: доли процента глазом не видны. */
export function formatFocal(x: number, y: number): string {
  return `${Math.round(clamp(x))}% ${Math.round(clamp(y))}%`
}

function clamp(n: number): number {
  return Math.max(0, Math.min(100, n))
}

/**
 * Точка лица для афиши — с правилом «лицо не ниже середины».
 *
 * ⚠️ Требование владельца: на афише лицо должно оказаться НЕ НИЖЕ центра
 * карточки, чуть выше — можно. Причина в том, что под фото идёт подпись имени:
 * лицо, прижатое к низу, упирается в собственную фамилию.
 *
 * Поэтому для афиши точку по вертикали ПОДНИМАЕМ до потолка, если клиент
 * отметил нос низко. Горизонталь не трогаем — вбок ограничивать нечего.
 *
 * ⚠️ Правим только показ на афише, а НЕ саму запись в базе: в карточке
 * спикера должна остаться та точка, которую клиент поставил своей рукой.
 */
export function focalCssForPoster(focal?: string | null, maxY = 45): string {
  const { x, y } = parseFocal(focal)
  return formatFocal(x, Math.min(y, maxY))
}
