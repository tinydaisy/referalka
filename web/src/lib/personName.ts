/**
 * Имя человека — фронтовая пара к backend/app/services/person_name.py.
 *
 * Имя разбито на два поля: у коллаборатора с миграции 302, у владельца
 * кабинета — с миграции 381. Порядок слов зависит от того, что человек делает
 * на экране:
 *
 *   ПОКАЗ  → «Имя Фамилия»  — шапка кабинета, карточки, заголовки.
 *   ПОИСК  → «Фамилия Имя»  — списки, которые ищут глазами.
 *
 * ⚠️ Руками не склеивать. До этого хелпера склейка была скопирована в трёх
 * местах фронта — такие копии расходятся по формату ровно так же, как уже
 * расходились на бэкенде.
 *
 * ⚠️ Пустая фамилия — норма, а не ошибка: у компаний и у записей, заведённых
 * до миграции, её нет. Лишнего пробела не остаётся.
 */

const clean = (v?: string | null) => (v ?? '').trim()

/** «Имя Фамилия» — там, где человека показывают. */
export function displayName(first?: string | null, last?: string | null): string {
  return [clean(first), clean(last)].filter(Boolean).join(' ')
}

/** «Фамилия Имя» — там, где человека ищут глазами в списке. */
export function searchName(first?: string | null, last?: string | null): string {
  return [clean(last), clean(first)].filter(Boolean).join(' ')
}
