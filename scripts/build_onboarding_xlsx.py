def set_widths(ws, widths):
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w


def title_bar(ws, text, span_cols):
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=span_cols)
    cell = ws.cell(row=1, column=1, value=text)
    cell.font = TITLE
    cell.fill = FILL_DARK
    cell.alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[1].height = 38


def section_header(ws, row, text, span_cols):
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=span_cols)
    cell = ws.cell(row=row, column=1, value=text)
    cell.font = H1
    cell.fill = FILL_PEACH
    cell.alignment = LEFT_MID
    ws.row_dimensions[row].height = 26


def write_para(ws, row, text, span_cols, bold=False, fill=None, height=None):
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=span_cols)
    cell = ws.cell(row=row, column=1, value=text)
    cell.font = BODY_B if bold else BODY
    cell.alignment = LEFT
    if fill:
        cell.fill = fill
    if height:
        ws.row_dimensions[row].height = height
    else:
        lines = max(1, text.count("\n") + 1 + len(text) // 110)
        ws.row_dimensions[row].height = max(18, 16 * lines)


def write_table_header(ws, row, headers):
    for i, h in enumerate(headers, 1):
        c = ws.cell(row=row, column=i, value=h)
        c.font = TH
        c.fill = FILL_DARK
        c.alignment = CENTER
        c.border = BORDER
    ws.row_dimensions[row].height = 30


def write_table_row(ws, row, values, fill=None):
    for i, v in enumerate(values, 1):
        c = ws.cell(row=row, column=i, value=v)
        c.font = BODY
        c.alignment = LEFT if isinstance(v, str) and len(str(v)) > 30 else CENTER
        c.border = BORDER
        if fill:
            c.fill = fill
    ws.row_dimensions[row].height = 24


